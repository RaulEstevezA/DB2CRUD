"""Entry point of the API: run it with "uvicorn app.main:app --reload"."""

from fastapi import FastAPI

from app.errors import register_error_handlers
from app.repositories.author import InMemoryAuthorRepository
from app.repositories.book import InMemoryBookRepository
from app.routers.author import router as author_router
from app.routers.book import router as book_router


def create_app() -> FastAPI:
    """Builds the application: error format, storage and the routes of every resource."""
    app = FastAPI(
        title="library-api",
        version="0.1.0",
        description="REST API generated by Model2API. Review it before using it in production.",
    )
    register_error_handlers(app)
    # Data kept in memory while the application runs; restarting it starts empty
    app.state.repositories = {
        "author": InMemoryAuthorRepository(),
        "book": InMemoryBookRepository(),
    }
    app.include_router(author_router)
    app.include_router(book_router)
    return app


app = create_app()
