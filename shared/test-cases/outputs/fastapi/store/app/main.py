"""Entry point of the API: run it with "uvicorn app.main:app --reload"."""

from fastapi import FastAPI

from app.errors import register_error_handlers
from app.repositories.customer import InMemoryCustomerRepository
from app.repositories.order import InMemoryOrderRepository
from app.repositories.product import InMemoryProductRepository
from app.routers.customer import router as customer_router
from app.routers.order import router as order_router
from app.routers.product import router as product_router


def create_app() -> FastAPI:
    """Builds the application: error format, storage and the routes of every resource."""
    app = FastAPI(
        title="shop-api",
        version="0.1.0",
        description="REST API generated by Model2API. Review it before using it in production.",
    )
    register_error_handlers(app)
    # Data kept in memory while the application runs; restarting it starts empty
    app.state.repositories = {
        "customer": InMemoryCustomerRepository(),
        "product": InMemoryProductRepository(),
        "order": InMemoryOrderRepository(),
    }
    app.include_router(customer_router)
    app.include_router(product_router)
    app.include_router(order_router)
    return app


app = create_app()
