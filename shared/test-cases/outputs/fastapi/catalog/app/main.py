"""Entry point of the API: run it with "uvicorn app.main:app --reload"."""

from fastapi import FastAPI

from app.errors import register_error_handlers
from app.repositories.category import InMemoryCategoryRepository
from app.repositories.item import InMemoryItemRepository
from app.routers.category import router as category_router
from app.routers.item import router as item_router


def create_app() -> FastAPI:
    """Builds the application: error format, storage and the routes of every resource."""
    app = FastAPI(
        title="catalog-api",
        version="0.1.0",
        description="REST API generated by Model2API. Review it before using it in production.",
    )
    register_error_handlers(app)
    # Data kept in memory while the application runs; restarting it starts empty
    app.state.repositories = {
        "category": InMemoryCategoryRepository(),
        "item": InMemoryItemRepository(),
    }
    app.include_router(category_router)
    app.include_router(item_router)
    return app


app = create_app()
