_DRIVERS = {
    "postgresql": {
        "package": "psycopg[binary]>=3.1,<4",
        "url": "postgresql+psycopg://api:change-me@localhost:5432/api",
    },
    "mysql": {"package": "pymysql>=1.1,<2", "url": "mysql+pymysql://api:change-me@localhost:3306/api"},
    "mariadb": {"package": "pymysql>=1.1,<2", "url": "mysql+pymysql://api:change-me@localhost:3306/api"},
    "sqlite": {"package": "", "url": "sqlite:///./app.db"},
}


def _uses_email(context: FastApiContext) -> bool:
    fields = [field for resource in context.spec["resources"] for field in resource["fields"]]
    fields += [field for spec_object in context.spec["objects"] for field in spec_object["fields"]]
    return any(field["constraints"].get("format") == "email" for field in fields)


def requirements_files(context: FastApiContext) -> list[dict]:
    database = context.settings["database"]
    driver = _DRIVERS.get(database) if database else None
    runtime = lines(
        "fastapi>=0.115,<1",
        "uvicorn[standard]>=0.30,<1",
        "pydantic>=2.7,<3",
        _uses_email(context) and "email-validator>=2.1,<3",
        context.sql and "sqlalchemy>=2.0,<3",
        driver["package"] if driver else None,
        database in ("mysql", "mariadb") and "cryptography>=42",
        context.settings["auth"] == "jwt" and "PyJWT>=2.8,<3",
    )
    dev = lines("-r requirements.txt", "pytest>=8,<9", "httpx2>=2.10,<3")
    return [
        {"path": "requirements.txt", "content": file_text(runtime)},
        {"path": "requirements-dev.txt", "content": file_text(dev)},
    ]


