def _pending_work(context: FastApiContext) -> list[str]:
    items: list[str] = []
    if context.pending:
        items.append("- Storage: every repository in `app/` answers 501 until you write it (search for `TODO`).")
    for resource in context.spec["resources"]:
        if resource.get("todo"):
            items.append(f"- {resource['todo']}")
        for field in resource["fields"]:
            if field.get("todo"):
                items.append(f"- {resource['name']}: {field['todo']}")
        for endpoint in resource["endpoints"]:
            if endpoint["operation"] == "custom":
                items.append(
                    f"- `{endpoint['method']} {endpoint['path']}` ({endpoint['summary']}): write its logic in the "
                    "service; it answers 501 until then."
                )
    return items


def endpoint_rows(resources: list[dict]) -> list[str]:
    rows = []
    for resource in resources:
        for endpoint in resource["endpoints"]:
            access = f"roles: {', '.join(endpoint['roles'])}" if endpoint["access"] == "roles" else endpoint["access"]
            rows.append(
                f"| `{endpoint['method']}` | `{endpoint['path']}` | {endpoint['summary']} | "
                f"{number_text(endpoint['status'])} | {access} |"
            )
    return rows


def readme_file(context: FastApiContext) -> dict:
    settings = context.settings
    spec = context.spec
    pending = _pending_work(context)
    if settings["persistence"] == "memory":
        persistence = (
            "Data is kept in memory while the application runs and is lost when it stops. Replace the repositories "
            "in `app/dependencies.py` to use a database."
        )
    elif settings["persistence"] == "none":
        persistence = (
            "Storage is left to you: each repository is an interface with methods to implement, and the API answers "
            "501 until they are."
        )
    else:
        persistence = (
            f"SQLAlchemy 2 on {settings['database']}. Missing tables are created at startup so the API runs at once; "
            "for a real database, use migrations (Model2DB writes them). Embedded objects and lists are stored as "
            "JSON columns."
        )
    if settings["auth"] == "none":
        auth = "Every endpoint is public."
    elif settings["auth"] == "apiKey":
        auth = (
            "Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. "
            "Without `API_KEYS`, every protected request is rejected."
        )
    else:
        auth = (
            "Protected endpoints need a bearer token issued by your identity provider. The API verifies it with "
            "`JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from "
            "the `roles` claim. It does not issue tokens."
        )
    if settings["architecture"] == "modular":
        layout = [
            "app/",
            "  main.py, config.py, errors.py, dependencies.py, validators.py",
            "  shared/schemas.py     enums and embedded objects",
            "  <resource>/           schemas, repository, service and router of one resource",
        ]
    else:
        layout = [
            "app/",
            "  main.py, config.py, errors.py, dependencies.py, validators.py",
            "  schemas/              request and response schemas",
            "  repositories/         storage",
            "  services/             rules of each resource",
            "  routers/              HTTP routes",
        ]
    database_note = " (a SQLite file per test, or the database in `TEST_DATABASE_URL`)" if context.sql else ""
    content = lines(
        f"# {spec['title']}",
        "",
        "REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with FastAPI. It is a "
        "starting point: review it before using it in production.",
        "",
        "## Run it",
        "",
        "Requires Python 3.11 or later.",
        "",
        "```bash",
        "python -m venv .venv",
        "source .venv/bin/activate        # Windows: .venv\\Scripts\\activate",
        "pip install -r requirements-dev.txt",
        "cp .env.example .env             # then fill in your values",
        "uvicorn app.main:app --reload --env-file .env",
        "```",
        "",
        "The interactive documentation is at http://localhost:8000/docs, and the contract in `openapi.yaml`.",
        "",
        "## Test it",
        "",
        "```bash",
        "pytest",
        "```",
        "",
        f"The tests call every endpoint with an empty storage{database_note}.",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does | Success | Access |",
        "|---|---|---|---|---|",
        endpoint_rows(spec["resources"]),
        "",
        'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid '
        "requests answer 400.",
        "",
        "## Storage",
        "",
        persistence,
        "",
        "## Authentication",
        "",
        auth,
        "",
        "## Structure",
        "",
        "```text",
        layout,
        "tests/                  one test file per resource",
        "openapi.yaml            the contract of the API",
        "```",
        "",
        "## Left to you",
        "",
        pending if pending else "- Nothing marked: review the generated code before using it.",
    )
    return {"path": "README.md", "content": file_text(content)}
