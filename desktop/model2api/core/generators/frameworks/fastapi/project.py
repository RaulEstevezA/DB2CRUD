def env_example_file(context: FastApiContext) -> dict:
    auth = context.settings["auth"]
    database = context.settings["database"]
    content = lines(
        "# Copy this file to .env and fill in your own values. Never commit .env.",
        context.sql
        and ["", "# Database connection (SQLAlchemy URL)", f"DATABASE_URL={_DRIVERS[database or 'sqlite']['url']}"],
        auth == "apiKey" and ["", "# Accepted API keys, separated by commas. Use long random values.", "API_KEYS="],
        auth == "jwt"
        and [
            "",
            "# Secret that signs the tokens of your identity provider. Without it every request is rejected.",
            "JWT_SECRET=",
            "JWT_ALGORITHM=HS256",
            "# Optional: expected audience and issuer of the tokens",
            "JWT_AUDIENCE=",
            "JWT_ISSUER=",
        ],
        not context.sql and auth == "none" and "# This project needs no configuration.",
    )
    return {"path": ".env.example", "content": file_text(content)}


