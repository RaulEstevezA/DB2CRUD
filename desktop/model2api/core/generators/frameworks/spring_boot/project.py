"""Project files of the Spring Boot project: the Maven build (pom.xml), the environment example, ignore rules and
the README. Mirrors web/src/core/generators/frameworks/springBoot/project.ts.
"""

from ...common.text import file_text, lines
from .context import SpringContext

SPRING_BOOT_VERSION = "4.1.2"
SPRINGDOC_VERSION = "3.2.0"

_DRIVERS = {
    "postgresql": ("org.postgresql", "postgresql"),
    "mysql": ("com.mysql", "mysql-connector-j"),
    "mariadb": ("org.mariadb.jdbc", "mariadb-java-client"),
}

_DATABASE_URLS = {
    "postgresql": "jdbc:postgresql://localhost:5432/api",
    "mysql": "jdbc:mysql://localhost:3306/api",
    "mariadb": "jdbc:mariadb://localhost:3306/api",
}


def _dependency(group: str, artifact: str, scope: str | None = None, version: str | None = None) -> list[str]:
    return [
        "        <dependency>",
        f"            <groupId>{group}</groupId>",
        f"            <artifactId>{artifact}</artifactId>",
        *([f"            <version>{version}</version>"] if version else []),
        *([f"            <scope>{scope}</scope>"] if scope else []),
        "        </dependency>",
    ]


def pom_file(context: SpringContext) -> dict:
    settings = context.settings
    driver = _DRIVERS.get(settings["database"]) if settings.get("database") else None
    group = ".".join(settings["javaPackage"].split(".")[:-1]) or settings["javaPackage"]
    content = lines(
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Maven build of the API generated by Model2API. -->",
        '<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
        '         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">',
        "    <modelVersion>4.0.0</modelVersion>",
        "",
        "    <parent>",
        "        <groupId>org.springframework.boot</groupId>",
        "        <artifactId>spring-boot-starter-parent</artifactId>",
        f"        <version>{SPRING_BOOT_VERSION}</version>",
        "        <relativePath/>",
        "    </parent>",
        "",
        f"    <groupId>{group}</groupId>",
        f"    <artifactId>{settings['name']}</artifactId>",
        "    <version>0.1.0</version>",
        f"    <name>{settings['name']}</name>",
        "    <description>REST API generated by Model2API</description>",
        "",
        "    <properties>",
        "        <java.version>21</java.version>",
        "    </properties>",
        "",
        "    <dependencies>",
        _dependency("org.springframework.boot", "spring-boot-starter-webmvc"),
        _dependency("org.springframework.boot", "spring-boot-starter-validation"),
        context.jpa and _dependency("org.springframework.boot", "spring-boot-starter-data-jpa"),
        context.security and _dependency("org.springframework.boot", "spring-boot-starter-security"),
        settings["auth"] == "jwt"
        and _dependency("org.springframework.boot", "spring-boot-starter-oauth2-resource-server"),
        _dependency("org.springdoc", "springdoc-openapi-starter-webmvc-ui", None, SPRINGDOC_VERSION),
        driver and _dependency(driver[0], driver[1], "runtime"),
        context.jpa and _dependency("com.h2database", "h2", "test"),
        _dependency("org.springframework.boot", "spring-boot-starter-webmvc-test", "test"),
        context.security and _dependency("org.springframework.security", "spring-security-test", "test"),
        "    </dependencies>",
        "",
        "    <build>",
        "        <plugins>",
        "            <plugin>",
        "                <groupId>org.springframework.boot</groupId>",
        "                <artifactId>spring-boot-maven-plugin</artifactId>",
        "            </plugin>",
        "        </plugins>",
        "    </build>",
        "</project>",
    )
    return {"path": "pom.xml", "content": file_text(content)}


def env_example_file(context: SpringContext) -> dict:
    auth = context.settings["auth"]
    database = context.settings.get("database") or "postgresql"
    content = lines(
        "# Environment of the API. Export these variables (or set them in your IDE) before running it. Never commit real values.",
        "",
        "# Port the API listens on",
        "PORT=8080",
        context.jpa
        and [
            "",
            "# Database connection",
            f"DATABASE_URL={_DATABASE_URLS[database]}",
            "DATABASE_USER=api",
            "DATABASE_PASSWORD=change-me",
        ],
        auth == "apiKey" and ["", "# Accepted API keys, separated by commas. Use long random values.", "API_KEYS="],
        auth == "jwt"
        and [
            "",
            "# Secret that signs the tokens of your identity provider (at least 32 bytes). Without it every protected request is rejected.",
            "JWT_SECRET=",
            "# Optional: expected audience and issuer of the tokens",
            "JWT_AUDIENCE=",
            "JWT_ISSUER=",
        ],
    )
    return {"path": ".env.example", "content": file_text(content)}


def gitignore_file() -> dict:
    return {
        "path": ".gitignore",
        "content": file_text(lines("target/", ".idea/", "*.iml", ".vscode/", ".env", ".DS_Store")),
    }


def _endpoint_rows(resources: list[dict]) -> list[str]:
    rows = []
    for resource in resources:
        for endpoint in resource["endpoints"]:
            access = f"roles: {', '.join(endpoint['roles'])}" if endpoint["access"] == "roles" else endpoint["access"]
            rows.append(
                f"| `{endpoint['method']}` | `{endpoint['path']}` | {endpoint['summary']} | {endpoint['status']} | {access} |"
            )
    return rows


def readme_file(context: SpringContext) -> dict:
    settings = context.settings
    spec = context.spec
    pending: list[str] = []
    if context.pending:
        pending.append("- Storage: every repository answers 501 until you write it (search for `TODO`).")
    for resource in spec["resources"]:
        if resource.get("todo"):
            pending.append(f"- {resource['todo']}")
        for field in resource["fields"]:
            if field.get("todo"):
                pending.append(f"- {resource['name']}: {field['todo']}")
        for endpoint in resource["endpoints"]:
            if endpoint["operation"] == "custom":
                pending.append(
                    f"- `{endpoint['method']} {endpoint['path']}` ({endpoint['summary']}): write its logic in the service; it answers 501 until then."
                )
    if settings["persistence"] == "memory":
        storage = "Data is kept in memory while the application runs and is lost when it stops. Write another implementation of each repository interface and mark it as the one to use."
    elif settings["persistence"] == "none":
        storage = (
            "Storage is left to you: each repository is an interface whose methods answer 501 until you implement them."
        )
    else:
        storage = f"JPA with Hibernate on {settings.get('database')}. Hibernate creates missing tables while you develop (`spring.jpa.hibernate.ddl-auto=update`); for a real database, use migrations (Model2DB writes them). Embedded objects and lists are stored as JSON columns, and references as key columns."
    if settings["auth"] == "none":
        auth = "Every endpoint is public."
    elif settings["auth"] == "apiKey":
        auth = "Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected."
    else:
        auth = "Protected endpoints need a bearer token issued by your identity provider, signed with HS256. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens."
    package = settings["javaPackage"].replace(".", "/")
    if settings["architecture"] == "modular":
        layout = [
            f"src/main/java/{package}/",
            "  common/               errors, lists and request bodies",
            "  shared/               enums and embedded objects",
            "  <resource>/           model, request and response, repository, service and controller of one resource",
        ]
    else:
        layout = [
            f"src/main/java/{package}/",
            "  common/               errors, lists and request bodies",
            "  model/                domain classes, enums and embedded objects",
            "  dto/                  request bodies and responses",
            "  repository/           storage",
            "  service/              rules of each resource",
            "  controller/           HTTP routes",
        ]
    content = lines(
        f"# {spec['title']}",
        "",
        "REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Spring Boot. It is a starting point: review it before using it in production.",
        "",
        "## Run it",
        "",
        "Requires Java 21 and Maven 3.9 or later.",
        "",
        "```bash",
        "mvn spring-boot:run",
        "```",
        "",
        "Set the variables of `.env.example` in your environment first. The API listens on http://localhost:8080; the interactive documentation is at http://localhost:8080/swagger-ui.html, and the contract in `openapi.yaml`.",
        "",
        "## Test it",
        "",
        "```bash",
        "mvn test",
        "```",
        "",
        context.jpa
        and "The tests use an in-memory H2 database, or the one in `TEST_DATABASE_URL` (with `TEST_DATABASE_USER` and `TEST_DATABASE_PASSWORD`).",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does | Success | Access |",
        "|---|---|---|---|---|",
        _endpoint_rows(spec["resources"]),
        "",
        'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
        "",
        "## Storage",
        "",
        storage,
        "",
        "## Authentication",
        "",
        auth,
        "",
        "## Structure",
        "",
        "```text",
        layout,
        "src/test/java/          one test class per resource",
        "openapi.yaml            the contract of the API",
        "```",
        "",
        "## Left to you",
        "",
        pending if pending else "- Nothing marked: review the generated code before using it.",
    )
    return {"path": "README.md", "content": file_text(content)}
