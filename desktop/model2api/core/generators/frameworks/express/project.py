"""Project files of the Express project: package.json with its scripts, the TypeScript and Vitest configuration,
the environment example, ignore rules and the README. Mirrors web/src/core/generators/frameworks/express/project.ts.
"""

import json

from ...common.text import file_text, lines
from ..fastapi.project import endpoint_rows
from .context import ExpressContext


def json_file(value) -> str:
    """JSON.stringify(value, null, 2), as package.json and tsconfig.json are written."""
    return json.dumps(value, indent=2, ensure_ascii=False)


def package_file(context: ExpressContext) -> dict:
    jwt = context.settings["auth"] == "jwt"
    dependencies = {"express": "^5.1.0", "zod": "^4.1.0", **({"jsonwebtoken": "^9.0.2"} if jwt else {})}
    dev_dependencies = {
        "@types/express": "^5.0.3",
        "@types/node": "^24.0.0",
        "@types/supertest": "^6.0.3",
        **({"@types/jsonwebtoken": "^9.0.10"} if jwt else {}),
        "supertest": "^7.1.0",
        "tsx": "^4.20.0",
        "typescript": "~6.0.3",
        "vitest": "^4.1.0",
    }
    manifest = {
        "name": context.settings["name"],
        "version": "0.1.0",
        "private": True,
        "description": "REST API generated by Model2API",
        "type": "module",
        "engines": {"node": ">=22"},
        "scripts": {
            "dev": "tsx watch --env-file-if-exists=.env src/server.ts",
            "build": "tsc -p tsconfig.build.json",
            "start": "node --env-file-if-exists=.env dist/server.js",
            "typecheck": "tsc --noEmit",
            "test": "vitest run",
        },
        "dependencies": dependencies,
        "devDependencies": dev_dependencies,
    }
    return {"path": "package.json", "content": file_text(json_file(manifest))}


def tsconfig_files() -> list[dict]:
    base = {
        "compilerOptions": {
            "target": "ES2023",
            "module": "NodeNext",
            "moduleResolution": "NodeNext",
            "strict": True,
            "esModuleInterop": True,
            "skipLibCheck": True,
            "forceConsistentCasingInFileNames": True,
            "noEmit": True,
        },
        "include": ["src", "tests"],
    }
    build = {
        "extends": "./tsconfig.json",
        "compilerOptions": {"noEmit": False, "outDir": "dist", "rootDir": "src"},
        "include": ["src"],
    }
    return [
        {"path": "tsconfig.json", "content": file_text(json_file(base))},
        {"path": "tsconfig.build.json", "content": file_text(json_file(build))},
    ]


