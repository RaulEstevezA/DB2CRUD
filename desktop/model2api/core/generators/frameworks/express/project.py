def auth_text(auth: str) -> str:
    """How protected endpoints are called, for a README."""
    if auth == "none":
        return "Every endpoint is public."
    if auth == "apiKey":
        return (
            "Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. "
            "Without `API_KEYS`, every protected request is rejected."
        )
    return (
        "Protected endpoints need a bearer token issued by your identity provider. The API verifies it with "
        "`JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the "
        "`roles` claim. It does not issue tokens."
    )


def pending_work(spec: dict, pending_storage: bool) -> list[str]:
    """What the developer still has to write, for a README."""
    items: list[str] = []
    if pending_storage:
        items.append("- Storage: every repository answers 501 until you write it (search for `TODO`).")
    for resource in spec["resources"]:
        if resource.get("todo"):
            items.append(f"- {resource['todo']}")
        for field in resource["fields"]:
            if field.get("todo"):
                items.append(f"- {resource['name']}: {field['todo']}")
        for endpoint in resource["endpoints"]:
            if endpoint["operation"] == "custom":
                items.append(
                    f"- `{endpoint['method']} {endpoint['path']}` ({endpoint['summary']}): write its logic in the "
                    "service; it answers 501 until then."
                )
    return items


def readme_file(context: ExpressContext) -> dict:
    settings = context.settings
    spec = context.spec
    pending = pending_work(spec, context.pending)
    if settings["persistence"] == "memory":
        storage = (
            "Data is kept in memory while the application runs and is lost when it stops. Write another "
            "implementation of each repository interface and use it in `src/app.ts`."
        )
    else:
        storage = (
            "Storage is left to you: each repository is an interface whose methods answer 501 until you implement them."
        )
    if settings["architecture"] == "modular":
        layout = [
            "src/",
            "  app.ts, server.ts, config.ts, errors.ts, listing.ts",
            "  shared/schemas.ts     enums and embedded objects",
            "  <resource>/           schemas, repository, service and routes of one resource",
        ]
    else:
        layout = [
            "src/",
            "  app.ts, server.ts, config.ts, errors.ts, listing.ts",
            "  schemas/              request and response shapes (Zod)",
            "  repositories/         storage",
            "  services/             rules of each resource",
            "  routes/               HTTP routes",
        ]
    content = lines(
        f"# {spec['title']}",
        "",
        "REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Express and "
        "TypeScript. It is a starting point: review it before using it in production.",
        "",
        "## Run it",
        "",
        "Requires Node.js 22 or later.",
        "",
        "```bash",
        "npm install",
        "cp .env.example .env             # then fill in your values",
        "npm run dev",
        "```",
        "",
        "The API listens on http://localhost:3000. Its contract is in `openapi.yaml`. For production: `npm run build` "
        "and `npm start`.",
        "",
        "## Test it",
        "",
        "```bash",
        "npm test",
        "npm run typecheck",
        "```",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does | Success | Access |",
        "|---|---|---|---|---|",
        endpoint_rows(spec["resources"]),
        "",
        'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid '
        "requests answer 400.",
        "",
        "## Storage",
        "",
        storage,
        "",
        "## Authentication",
        "",
        auth_text(settings["auth"]),
        "",
        "## Structure",
        "",
        "```text",
        layout,
        "tests/                  one test file per resource",
        "openapi.yaml            the contract of the API",
        "```",
        "",
        "## Left to you",
        "",
        pending if pending else "- Nothing marked: review the generated code before using it.",
    )
    return {"path": "README.md", "content": file_text(content)}
