# The Swift release the project is written for
SWIFT_VERSION = "6.4"


def package_file(context: VaporContext) -> dict:
    settings = context.settings
    database = settings.get("database") or "postgresql"
    dependencies = [("https://github.com/vapor/vapor.git", "4.122.0", ["Vapor"])]
    if context.fluent:
        dependencies.append(("https://github.com/vapor/fluent.git", "4.13.0", ["Fluent"]))
        # SQLite is always there: the tests run on a SQLite file when no TEST_DATABASE_URL is set
        dependencies.append(("https://github.com/vapor/fluent-sqlite-driver.git", "4.9.0", ["FluentSQLiteDriver"]))
        if database == "postgresql":
            dependencies.append(
                ("https://github.com/vapor/fluent-postgres-driver.git", "2.14.0", ["FluentPostgresDriver"])
            )
        if database in ("mysql", "mariadb"):
            dependencies.append(("https://github.com/vapor/fluent-mysql-driver.git", "4.8.0", ["FluentMySQLDriver"]))
    if settings["auth"] == "jwt":
        dependencies.append(("https://github.com/vapor/jwt.git", "5.2.0", ["JWT"]))

    def package_of(url: str) -> str:
        return url[url.rfind("/") + 1 : -len(".git")]

    content = lines(
        "// swift-tools-version:6.0",
        "// Swift package of the API generated by Model2API.",
        "import PackageDescription",
        "",
        "let package = Package(",
        f'    name: "{settings["name"]}",',
        "    platforms: [.macOS(.v13)],",
        "    dependencies: [",
        [f'        .package(url: "{url}", from: "{version}"),' for url, version, _ in dependencies],
        "    ],",
        "    targets: [",
        "        .executableTarget(",
        '            name: "App",',
        "            dependencies: [",
        [
            f'                .product(name: "{product}", package: "{package_of(url)}"),'
            for url, _, products in dependencies
            for product in products
        ],
        "            ]",
        "        ),",
        "        .testTarget(",
        '            name: "AppTests",',
        "            dependencies: [",
        '                .target(name: "App"),',
        '                .product(name: "VaporTesting", package: "vapor"),',
        "            ]",
        "        ),",
        "    ]",
        ")",
    )
    return {"path": "Package.swift", "content": file_text(content)}


def env_example_file(context: VaporContext) -> dict:
    auth = context.settings["auth"]
    database = context.settings.get("database")
    content = lines(
        "# Environment of the API. Export these variables before running it. Never commit real values.",
        "",
        "# Port the API listens on",
        "PORT=8080",
        context.fluent and ["", "# Database connection", f"DATABASE_URL={DATABASE_URLS[database or 'postgresql']}"],
        auth == "apiKey" and ["", "# Accepted API keys, separated by commas. Use long random values.", "API_KEYS="],
        auth == "jwt"
        and [
            "",
            "# Secret that signs the tokens of your identity provider (at least 32 bytes). Without it every protected "
            "request is rejected.",
            "JWT_SECRET=",
            "# Optional: expected audience and issuer of the tokens",
            "JWT_AUDIENCE=",
            "JWT_ISSUER=",
        ],
    )
    return {"path": ".env.example", "content": file_text(content)}


def gitignore_file() -> dict:
    return {
        "path": ".gitignore",
        "content": file_text(
            lines(".build/", ".swiftpm/", "Package.resolved", ".idea/", ".vscode/", ".env", "*.db", ".DS_Store")
        ),
    }


def _endpoint_rows(resources: list[dict]) -> list[str]:
    rows = []
    for resource in resources:
        for endpoint in resource["endpoints"]:
            access = f"roles: {', '.join(endpoint['roles'])}" if endpoint["access"] == "roles" else endpoint["access"]
            rows.append(
                f"| `{endpoint['method']}` | `{endpoint['path']}` | {endpoint['summary']} | "
                f"{number_text(endpoint['status'])} | {access} |"
            )
    return rows


def readme_file(context: VaporContext) -> dict:
    settings = context.settings
    spec = context.spec
    database = settings.get("database")
    pending: list[str] = []
    if context.pending:
        pending.append("- Storage: every repository answers 501 until you write it (search for `TODO`).")
    for resource in spec["resources"]:
        if resource.get("todo"):
            pending.append(f"- {resource['todo']}")
        for field in resource["fields"]:
            if field.get("todo"):
                pending.append(f"- {resource['name']}: {field['todo']}")
        for endpoint in resource["endpoints"]:
            if endpoint["operation"] == "custom":
                pending.append(
                    f"- `{endpoint['method']} {endpoint['path']}` ({endpoint['summary']}): write its logic in the "
                    "service; it answers 501 until then."
                )
    if settings["persistence"] == "memory":
        storage = (
            "Data is kept in memory while the application runs and is lost when it stops. Write another "
            "implementation of each repository protocol and create it in `configure.swift`."
        )
    elif settings["persistence"] == "none":
        storage = (
            "Storage is left to you: each repository is a protocol whose methods answer 501 until you implement them."
        )
    else:
        storage = (
            f"Fluent on {database}. The application runs the migrations that create the tables when it starts, while "
            "you develop; for a real database, use migrations you control (Model2DB writes them). Embedded objects and "
            "lists are stored as JSON text, references as key columns and decimals as doubles."
        )
    if settings["auth"] == "none":
        auth = "Every endpoint is public."
    elif settings["auth"] == "apiKey":
        auth = (
            "Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. "
            "Without `API_KEYS`, every protected request is rejected."
        )
    else:
        auth = (
            "Protected endpoints need a bearer token issued by your identity provider, signed with HS256. The API "
            "verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads "
            "the roles from the `roles` claim. It does not issue tokens."
        )
    if settings["architecture"] == "modular":
        layout = [
            "Sources/App/",
            "  entrypoint.swift      entry point: reads the settings and serves the API",
            "  configure.swift       wires errors, storage, services and routes",
            "  Common/               errors, request bodies, JSON, lists, query strings and settings",
            "  Shared/               enums and embedded objects",
            "  <Resource>/           model, request and response, repository, service and routes of one resource",
            context.fluent and "  Database/             connection and migrations",
            context.security and "  Security/             authentication",
        ]
    else:
        layout = [
            "Sources/App/",
            "  entrypoint.swift      entry point: reads the settings and serves the API",
            "  configure.swift       wires errors, storage, services and routes",
            "  Common/               errors, request bodies, JSON, lists, query strings and settings",
            "  Models/               domain types, enums and embedded objects",
            "  DTOs/                 request bodies and responses",
            "  Repositories/         storage",
            context.fluent and "  Database/             tables (Fluent models and migrations) and connection",
            "  Services/             rules of each resource",
            "  Controllers/          HTTP routes",
            context.security and "  Security/             authentication",
        ]
    content = lines(
        f"# {spec['title']}",
        "",
        "REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Vapor. It is a "
        "starting point: review it before using it in production.",
        "",
        "## Run it",
        "",
        f"Requires Swift {SWIFT_VERSION} or later.",
        "",
        "```bash",
        "swift run",
        "```",
        "",
        "Set the variables of `.env.example` in your environment first. The API listens on http://localhost:8080. "
        "Its contract is in `openapi.yaml`.",
        "",
        "## Test it",
        "",
        "```bash",
        "swift test",
        "```",
        "",
        "Each test builds the application anew, so it starts with empty storage.",
        context.fluent
        and f"The tests use a new SQLite file for each test, or the {database} database in `TEST_DATABASE_URL` (its "
        "tables are dropped and created again before each test, and the tests take turns).",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does | Success | Access |",
        "|---|---|---|---|---|",
        _endpoint_rows(spec["resources"]),
        "",
        'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. '
        "Invalid requests answer 400.",
        "",
        "## Storage",
        "",
        storage,
        "",
        "## Authentication",
        "",
        auth,
        "",
        "## Structure",
        "",
        "```text",
        layout,
        "Tests/AppTests/          one test suite per resource",
        "openapi.yaml             the contract of the API",
        "```",
        "",
        "## Left to you",
        "",
        pending if pending else "- Nothing marked: review the generated code before using it.",
    )
    return {"path": "README.md", "content": file_text(content)}
