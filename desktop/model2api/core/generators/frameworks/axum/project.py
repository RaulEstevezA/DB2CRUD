"""Project files of the Axum project: the Cargo manifest, the environment example, ignore rules and the README.
Mirrors web/src/core/generators/frameworks/axum/project.ts.
"""

from ....js import number_text
from ...common.text import file_text, lines
from .common import DATABASE_URLS
from .context import AxumContext

# The Rust release the project is written for (edition 2024, let chains)
RUST_VERSION = "1.99"

# The sqlx driver feature of SeaORM for each database
_SQLX = {
    "postgresql": "sqlx-postgres",
    "mysql": "sqlx-mysql",
    "mariadb": "sqlx-mysql",
    "sqlite": "sqlx-sqlite",
}

_JWT = 'jsonwebtoken = { version = "11", default-features = false, features = ["rust_crypto"] }'


def cargo_file(context: AxumContext) -> dict:
    settings = context.settings
    # SQLite is always there: the tests run on a SQLite file when no TEST_DATABASE_URL is set
    drivers = list(dict.fromkeys([_SQLX[settings.get("database") or "postgresql"], "sqlx-sqlite"]))
    features = [
        "runtime-tokio-rustls",
        *drivers,
        "macros",
        "with-chrono",
        "with-uuid",
        "with-rust_decimal",
        "with-json",
    ]
    quoted = ", ".join(f'"{item}"' for item in features)
    jwt = settings["auth"] == "jwt"
    content = lines(
        "# Cargo manifest of the API generated by Model2API.",
        "[package]",
        f'name = "{context.package}"',
        'version = "0.1.0"',
        'edition = "2024"',
        f'rust-version = "{RUST_VERSION}"',
        "publish = false",
        "",
        "[dependencies]",
        'async-trait = "0.1"',
        'axum = "0.8.9"',
        'chrono = { version = "0.4", features = ["serde"] }',
        'fancy-regex = "0.19"',
        jwt and _JWT,
        'rust_decimal = { version = "1", features = ["serde-float"] }',
        context.sea_orm and f'sea-orm = {{ version = "2.0.4", features = [{quoted}] }}',
        'serde = { version = "1", features = ["derive"] }',
        'serde_json = "1"',
        'serde_repr = "0.1"',
        'tokio = { version = "1", features = ["macros", "rt-multi-thread", "net", "sync"] }',
        'tower-http = { version = "0.6", features = ["catch-panic"] }',
        'tracing = "0.1"',
        'tracing-subscriber = "0.3"',
        'uuid = { version = "1", features = ["v4", "serde"] }',
        "",
        "[dev-dependencies]",
        jwt and _JWT,
        'tower = { version = "0.5", features = ["util"] }',
        "",
        "[[test]]",
        'name = "api"',
        'path = "tests/api/main.rs"',
    )
    return {"path": "Cargo.toml", "content": file_text(content)}


def env_example_file(context: AxumContext) -> dict:
    auth = context.settings["auth"]
    database = context.settings.get("database")
    content = lines(
        "# Environment of the API. Export these variables before running it. Never commit real values.",
        "",
        "# Port the API listens on",
        "PORT=8080",
        context.sea_orm and ["", "# Database connection", f"DATABASE_URL={DATABASE_URLS[database or 'postgresql']}"],
        auth == "apiKey" and ["", "# Accepted API keys, separated by commas. Use long random values.", "API_KEYS="],
        auth == "jwt"
        and [
            "",
            "# Secret that signs the tokens of your identity provider (at least 32 bytes). Without it every protected "
            "request is rejected.",
            "JWT_SECRET=",
            "# Optional: expected audience and issuer of the tokens",
            "JWT_AUDIENCE=",
            "JWT_ISSUER=",
        ],
    )
    return {"path": ".env.example", "content": file_text(content)}


def gitignore_file() -> dict:
    return {
        "path": ".gitignore",
        "content": file_text(lines("target/", ".idea/", ".vscode/", ".env", "*.db", ".DS_Store")),
    }


def _endpoint_rows(resources: list[dict]) -> list[str]:
    rows = []
    for resource in resources:
        for endpoint in resource["endpoints"]:
            access = f"roles: {', '.join(endpoint['roles'])}" if endpoint["access"] == "roles" else endpoint["access"]
            rows.append(
                f"| `{endpoint['method']}` | `{endpoint['path']}` | {endpoint['summary']} | "
                f"{number_text(endpoint['status'])} | {access} |"
            )
    return rows


def readme_file(context: AxumContext) -> dict:
    settings = context.settings
    spec = context.spec
    database = settings.get("database")
    pending: list[str] = []
    if context.pending:
        pending.append("- Storage: every repository answers 501 until you write it (search for `TODO`).")
    for resource in spec["resources"]:
        if resource.get("todo"):
            pending.append(f"- {resource['todo']}")
        for field in resource["fields"]:
            if field.get("todo"):
                pending.append(f"- {resource['name']}: {field['todo']}")
        for endpoint in resource["endpoints"]:
            if endpoint["operation"] == "custom":
                pending.append(
                    f"- `{endpoint['method']} {endpoint['path']}` ({endpoint['summary']}): write its logic in the "
                    "service; it answers 501 until then."
                )
    if settings["persistence"] == "memory":
        storage = (
            "Data is kept in memory while the application runs and is lost when it stops. Write another "
            "implementation of each repository trait and create it in `src/lib.rs`."
        )
    elif settings["persistence"] == "none":
        storage = (
            "Storage is left to you: each repository is a trait whose methods answer 501 until you implement them."
        )
    else:
        storage = (
            f"SeaORM on {database}. The application creates the tables that are missing when it starts, while you "
            "develop; for a real database, use migrations (Model2DB writes them). Embedded objects and lists are "
            "stored as JSON text, and references as key columns."
        )
    if settings["auth"] == "none":
        auth = "Every endpoint is public."
    elif settings["auth"] == "apiKey":
        auth = (
            "Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. "
            "Without `API_KEYS`, every protected request is rejected."
        )
    else:
        auth = (
            "Protected endpoints need a bearer token issued by your identity provider, signed with HS256. The API "
            "verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads "
            "the roles from the `roles` claim. It does not issue tokens."
        )
    if settings["architecture"] == "modular":
        layout = [
            "src/",
            "  main.rs               entry point: reads the settings and serves the API",
            "  lib.rs                state and router: wires storage, services and routes",
            "  common/               errors, request bodies, lists, query strings and settings",
            "  shared/               enums and embedded objects",
            "  <resource>/           model, request and response, repository, service and routes of one resource",
            context.sea_orm and "  database.rs           connection and tables",
            context.security and "  security.rs           authentication",
        ]
    else:
        layout = [
            "src/",
            "  main.rs               entry point: reads the settings and serves the API",
            "  lib.rs                state and router: wires storage, services and routes",
            "  common/               errors, request bodies, lists, query strings and settings",
            "  models/               domain types, enums and embedded objects",
            "  dtos/                 request bodies and responses",
            "  repositories/         storage",
            context.sea_orm and "  entities/             tables, as SeaORM entities",
            "  services/             rules of each resource",
            "  routes/               HTTP routes",
            context.sea_orm and "  database.rs           connection and tables",
            context.security and "  security.rs           authentication",
        ]
    content = lines(
        f"# {spec['title']}",
        "",
        "REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Axum. It is a "
        "starting point: review it before using it in production.",
        "",
        "## Run it",
        "",
        f"Requires Rust {RUST_VERSION} or later.",
        "",
        "```bash",
        "cargo run",
        "```",
        "",
        "Set the variables of `.env.example` in your environment first. The API listens on http://localhost:8080. "
        "Its contract is in `openapi.yaml`.",
        "",
        "## Test it",
        "",
        "```bash",
        "cargo test",
        "```",
        "",
        "Each test builds the application anew, so it starts with empty storage.",
        context.sea_orm
        and f"The tests use a new SQLite file for each test, or the {database} database in `TEST_DATABASE_URL` (its "
        "tables are dropped before each test, and the tests take turns).",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does | Success | Access |",
        "|---|---|---|---|---|",
        _endpoint_rows(spec["resources"]),
        "",
        'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. '
        "Invalid requests answer 400.",
        "",
        "## Storage",
        "",
        storage,
        "",
        "## Authentication",
        "",
        auth,
        "",
        "## Structure",
        "",
        "```text",
        layout,
        "tests/api/               one test module per resource",
        "openapi.yaml             the contract of the API",
        "```",
        "",
        "## Left to you",
        "",
        pending if pending else "- Nothing marked: review the generated code before using it.",
    )
    return {"path": "README.md", "content": file_text(content)}
