def _endpoint_rows(resources: list[dict]) -> list[str]:
    rows = []
    for resource in resources:
        for endpoint in resource["endpoints"]:
            access = f"roles: {', '.join(endpoint['roles'])}" if endpoint["access"] == "roles" else endpoint["access"]
            rows.append(
                f"| `{endpoint['method']}` | `{endpoint['path']}` | {endpoint['summary']} | {endpoint['status']} | {access} |"
            )
    return rows


def readme_file(context: SymfonyContext) -> dict:
    settings = context.settings
    spec = context.spec
    pending: list[str] = []
    if context.pending:
        pending.append("- Storage: every repository answers 501 until you write it (search for `TODO`).")
    for resource in spec["resources"]:
        if resource.get("todo"):
            pending.append(f"- {resource['todo']}")
        for field in resource["fields"]:
            if field.get("todo"):
                pending.append(f"- {resource['name']}: {field['todo']}")
        for endpoint in resource["endpoints"]:
            if endpoint["operation"] == "custom":
                pending.append(
                    f"- `{endpoint['method']} {endpoint['path']}` ({endpoint['summary']}): write its logic in the "
                    "service; it answers 501 until then."
                )
    if settings["persistence"] == "memory":
        storage = (
            "Data is kept in memory while the application runs and is lost when it stops. Write another "
            "implementation of each repository interface and point the interface to it in `config/services.yaml`."
        )
    elif settings["persistence"] == "none":
        storage = (
            "Storage is left to you: each repository is an interface whose methods answer 501 until you implement them."
        )
    else:
        storage = (
            f"Doctrine ORM on {settings.get('database')}. `php bin/console doctrine:schema:create` creates the tables "
            "while you develop; for a real database, use migrations (Model2DB writes them). Embedded objects and lists "
            "are stored as JSON columns, and references as key columns."
        )
    if settings["auth"] == "none":
        auth = "Every endpoint is public."
    elif settings["auth"] == "apiKey":
        auth = (
            "Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. "
            "Without `API_KEYS`, every protected request is rejected."
        )
    else:
        auth = (
            "Protected endpoints need a bearer token issued by your identity provider. The API verifies it with "
            "`JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from "
            "the `roles` claim. It does not issue tokens."
        )
    if settings["architecture"] == "modular":
        layout = [
            "src/",
            "  <Resource>/            controller, input, response, service, repository and entity of one resource",
            "  Shared/                enums",
            "  Controller/, EventSubscriber/, Exception/, Http/, Security/, Support/   what every resource shares",
        ]
    else:
        layout = [
            "src/",
            "  Controller/            HTTP routes of each resource",
            "  Input/                 request bodies and their constraints",
            "  Presenter/             responses",
            "  Service/               rules of each resource",
            "  Repository/            storage",
            context.doctrine and "  Entity/                Doctrine entities",
            "  Enum/                  enums",
        ]
    content = lines(
        f"# {spec['title']}",
        "",
        "REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Symfony. It is a "
        "starting point: review it before using it in production.",
        "",
        "## Run it",
        "",
        "Requires PHP 8.4 or later and Composer 2.",
        "",
        "```bash",
        "composer install",
        "cp .env .env.local                 # then fill in your values in .env.local",
        context.doctrine and "php bin/console doctrine:schema:create",
        "php -S localhost:8000 -t public",
        "```",
        "",
        "The API listens on http://localhost:8000. Its contract is in `openapi.yaml`.",
        "",
        "## Test it",
        "",
        "```bash",
        "composer test",
        "```",
        "",
        context.doctrine
        and "The tests use an in-memory SQLite database, or the one in `TEST_DATABASE_URL` (`postgresql://` or `mysql://`).",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does | Success | Access |",
        "|---|---|---|---|---|",
        _endpoint_rows(spec["resources"]),
        "",
        'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid '
        "requests answer 400.",
        "",
        "## Storage",
        "",
        storage,
        "",
        "## Authentication",
        "",
        auth,
        "",
        "## Structure",
        "",
        "```text",
        layout,
        "config/                  bundles, packages, routes and services",
        "tests/Api/               one test class per resource",
        "openapi.yaml             the contract of the API",
        "```",
        "",
        "## Left to you",
        "",
        pending if pending else "- Nothing marked: review the generated code before using it.",
    )
    return {"path": "README.md", "content": file_text(content)}
