"""Project files of the Laravel project: composer.json, the PHPUnit configuration, the environment example, ignore
rules and the README. Mirrors web/src/core/generators/frameworks/laravel/project.ts.
"""

import json

from ...common.testing import TEST_API_KEY, TEST_JWT_SECRET
from ...common.text import file_text, lines
from .context import LaravelContext

LARAVEL_VERSION = "^13.40"
JWT_VERSION = "^7.2"
PHPUNIT_VERSION = "^12.5"
MOCKERY_VERSION = "^1.6"

_CONNECTIONS = {
    "sqlite": ("sqlite", None),
    "postgresql": ("pgsql", 5432),
    "mysql": ("mysql", 3306),
    "mariadb": ("mariadb", 3306),
}


def composer_file(context: LaravelContext) -> dict:
    jwt = context.settings["auth"] == "jwt"
    manifest = {
        "name": f"model2api/{context.settings['name']}",
        "type": "project",
        "description": "REST API generated by Model2API",
        "require": {
            "php": "^8.3",
            **({"firebase/php-jwt": JWT_VERSION} if jwt else {}),
            "laravel/framework": LARAVEL_VERSION,
        },
        # RefreshDatabase runs the migrations through Artisan, which needs Mockery in tests
        "require-dev": {
            **({"mockery/mockery": MOCKERY_VERSION} if context.eloquent else {}),
            "phpunit/phpunit": PHPUNIT_VERSION,
        },
        "autoload": {"psr-4": {"App\\": "app/"}},
        "autoload-dev": {"psr-4": {"Tests\\": "tests/"}},
        "scripts": {
            "post-autoload-dump": [
                "Illuminate\\Foundation\\ComposerScripts::postAutoloadDump",
                "@php artisan package:discover --ansi",
            ],
            "test": ["@php vendor/bin/phpunit"],
        },
        "config": {"optimize-autoloader": True, "preferred-install": "dist", "sort-packages": True},
        "minimum-stability": "stable",
        "prefer-stable": True,
    }
    return {"path": "composer.json", "content": file_text(json.dumps(manifest, indent=4, ensure_ascii=False))}


def phpunit_file(context: LaravelContext) -> dict:
    auth = context.settings["auth"]
    content = lines(
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<phpunit xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
        '         xsi:noNamespaceSchemaLocation="vendor/phpunit/phpunit/phpunit.xsd"',
        '         bootstrap="vendor/autoload.php"',
        '         colors="true"',
        ">",
        "    <testsuites>",
        '        <testsuite name="Feature">',
        "            <directory>tests/Feature</directory>",
        "        </testsuite>",
        "    </testsuites>",
        "    <source>",
        "        <include>",
        "            <directory>app</directory>",
        "        </include>",
        "    </source>",
        "    <!-- Settings of the tests; a variable already set in the environment wins -->",
        "    <php>",
        '        <env name="APP_ENV" value="testing"/>',
        '        <env name="CACHE_STORE" value="array"/>',
        '        <env name="SESSION_DRIVER" value="array"/>',
        context.eloquent
        and [
            "        <!-- An in-memory SQLite database, or the database in TEST_DATABASE_URL (tests/TestCase.php) -->",
            '        <env name="DB_CONNECTION" value="sqlite"/>',
            '        <env name="DB_DATABASE" value=":memory:"/>',
        ],
        auth == "apiKey" and f'        <env name="API_KEYS" value="{TEST_API_KEY}" force="true"/>',
        auth == "jwt"
        and [
            f'        <env name="JWT_SECRET" value="{TEST_JWT_SECRET}" force="true"/>',
            '        <env name="JWT_AUDIENCE" value="" force="true"/>',
            '        <env name="JWT_ISSUER" value="" force="true"/>',
        ],
        "    </php>",
        "</phpunit>",
    )
    return {"path": "phpunit.xml", "content": file_text(content)}


def env_example_file(context: LaravelContext) -> dict:
    auth = context.settings["auth"]
    database = context.settings.get("database")
    connection = _CONNECTIONS.get(database) if database else None
    if connection:
        name, port = connection
        settings = (
            ["DB_HOST=127.0.0.1", f"DB_PORT={port}", "DB_DATABASE=api", "DB_USERNAME=api", "DB_PASSWORD=change-me"]
            if port
            else "# The database is the file database/database.sqlite"
        )
        database_lines = ["", "# Database connection", f"DB_CONNECTION={name}", settings]
    content = lines(
        "# Copy this file to .env and fill in your own values. Never commit .env.",
        "",
        f"APP_NAME={context.settings['name']}",
        "APP_ENV=local",
        "APP_DEBUG=true",
        "APP_URL=http://localhost:8000",
        bool(context.eloquent and connection) and database_lines,
        auth == "apiKey" and ["", "# Accepted API keys, separated by commas. Use long random values.", "API_KEYS="],
        auth == "jwt"
        and [
            "",
            "# Secret that signs the tokens of your identity provider. Without it every protected request is rejected.",
            "JWT_SECRET=",
            "JWT_ALGORITHM=HS256",
            "# Optional: expected audience and issuer of the tokens",
            "JWT_AUDIENCE=",
            "JWT_ISSUER=",
        ],
    )
    return {"path": ".env.example", "content": file_text(content)}


