"""Project files of the Ktor project: the Gradle build (Kotlin DSL), the logging configuration, the environment
example, ignore rules and the README. Mirrors web/src/core/generators/frameworks/ktor/project.ts.
"""

from ...common.text import file_text, lines
from .common import JDBC_URLS
from .context import KtorContext

KOTLIN_VERSION = "2.4.21"
KTOR_VERSION = "3.6.0"
EXPOSED_VERSION = "1.6.0"
LOGBACK_VERSION = "1.6.5"
HIKARI_VERSION = "7.0.2"
H2_VERSION = "2.5.252"

_DRIVERS = {
    "postgresql": "org.postgresql:postgresql:42.7.13",
    "mysql": "com.mysql:mysql-connector-j:26.10.0",
    "mariadb": "org.mariadb.jdbc:mariadb-java-client:3.5.11",
    "sqlite": "org.xerial:sqlite-jdbc:3.53.4.0",
}


def build_files(context: KtorContext) -> list[dict]:
    settings = context.settings
    database = settings.get("database")

    def ktor(artifact: str, scope: str = "implementation") -> str:
        return f'    {scope}("io.ktor:{artifact}:$ktorVersion")'

    def exposed(artifact: str) -> str:
        return f'    implementation("org.jetbrains.exposed:{artifact}:$exposedVersion")'

    package = settings["javaPackage"]
    build = lines(
        "// Gradle build of the API generated by Model2API.",
        "plugins {",
        f'    kotlin("jvm") version "{KOTLIN_VERSION}"',
        f'    kotlin("plugin.serialization") version "{KOTLIN_VERSION}"',
        "    application",
        "}",
        "",
        f'group = "{package}"',
        'version = "0.1.0"',
        "",
        "application {",
        f'    mainClass.set("{package}.ApplicationKt")',
        "}",
        "",
        "kotlin {",
        "    jvmToolchain(21)",
        "}",
        "",
        "repositories {",
        "    mavenCentral()",
        "}",
        "",
        f'val ktorVersion = "{KTOR_VERSION}"',
        context.exposed and f'val exposedVersion = "{EXPOSED_VERSION}"',
        "",
        "dependencies {",
        ktor("ktor-server-core"),
        ktor("ktor-server-netty"),
        ktor("ktor-server-content-negotiation"),
        ktor("ktor-serialization-kotlinx-json"),
        ktor("ktor-server-status-pages"),
        context.security and ktor("ktor-server-auth"),
        settings["auth"] == "jwt" and ktor("ktor-server-auth-jwt"),
        f'    implementation("ch.qos.logback:logback-classic:{LOGBACK_VERSION}")',
        context.exposed
        and [
            exposed("exposed-core"),
            exposed("exposed-jdbc"),
            exposed("exposed-java-time"),
            f'    implementation("com.zaxxer:HikariCP:{HIKARI_VERSION}")',
            f'    implementation("{_DRIVERS[database or "postgresql"]}")',
        ],
        "",
        ktor("ktor-server-test-host", "testImplementation"),
        '    testImplementation(kotlin("test"))',
        context.exposed and database != "sqlite" and f'    testImplementation("com.h2database:h2:{H2_VERSION}")',
        "}",
        "",
        "tasks.test {",
        "    useJUnitPlatform()",
        "}",
    )
    settings_file = lines(f'rootProject.name = "{settings["name"]}"')
    logback = lines(
        "<configuration>",
        '    <appender name="STDOUT" class="ch.qos.logback.core.ConsoleAppender">',
        "        <encoder>",
        "            <pattern>%d{HH:mm:ss.SSS} %-5level %logger{36} - %msg%n</pattern>",
        "        </encoder>",
        "    </appender>",
        '    <root level="INFO">',
        '        <appender-ref ref="STDOUT"/>',
        "    </root>",
        '    <logger name="io.netty" level="WARN"/>',
        context.exposed and '    <logger name="com.zaxxer.hikari" level="WARN"/>',
        "</configuration>",
    )
    return [
        {"path": "build.gradle.kts", "content": file_text(build)},
        {"path": "settings.gradle.kts", "content": file_text(settings_file)},
        {"path": "src/main/resources/logback.xml", "content": file_text(logback)},
    ]


def env_example_file(context: KtorContext) -> dict:
    auth = context.settings["auth"]
    database = context.settings.get("database")
    content = lines(
        "# Environment of the API. Export these variables (or set them in your IDE) before running it. Never commit real values.",
        "",
        "# Port the API listens on",
        "PORT=8080",
        context.exposed
        and [
            "",
            "# Database connection (JDBC)",
            f"DATABASE_URL={JDBC_URLS[database or 'postgresql']}",
            database != "sqlite" and ["DATABASE_USER=api", "DATABASE_PASSWORD=change-me"],
        ],
        auth == "apiKey" and ["", "# Accepted API keys, separated by commas. Use long random values.", "API_KEYS="],
        auth == "jwt"
        and [
            "",
            "# Secret that signs the tokens of your identity provider (at least 32 bytes). Without it every protected request is rejected.",
            "JWT_SECRET=",
            "# Optional: expected audience and issuer of the tokens",
            "JWT_AUDIENCE=",
            "JWT_ISSUER=",
        ],
    )
    return {"path": ".env.example", "content": file_text(content)}


def gitignore_file() -> dict:
    return {
        "path": ".gitignore",
        "content": file_text(
            lines("build/", ".gradle/", ".kotlin/", ".idea/", "*.iml", ".vscode/", ".env", "*.db", ".DS_Store")
        ),
    }


def _endpoint_rows(resources: list[dict]) -> list[str]:
    rows = []
    for resource in resources:
        for endpoint in resource["endpoints"]:
            access = f"roles: {', '.join(endpoint['roles'])}" if endpoint["access"] == "roles" else endpoint["access"]
            rows.append(
                f"| `{endpoint['method']}` | `{endpoint['path']}` | {endpoint['summary']} | {endpoint['status']} | {access} |"
            )
    return rows


def readme_file(context: KtorContext) -> dict:
    settings = context.settings
    spec = context.spec
    database = settings.get("database")
    pending: list[str] = []
    if context.pending:
        pending.append("- Storage: every repository answers 501 until you write it (search for `TODO`).")
    for resource in spec["resources"]:
        if resource.get("todo"):
            pending.append(f"- {resource['todo']}")
        for field in resource["fields"]:
            if field.get("todo"):
                pending.append(f"- {resource['name']}: {field['todo']}")
        for endpoint in resource["endpoints"]:
            if endpoint["operation"] == "custom":
                pending.append(
                    f"- `{endpoint['method']} {endpoint['path']}` ({endpoint['summary']}): write its logic in the "
                    "service; it answers 501 until then."
                )
    if settings["persistence"] == "memory":
        storage = (
            "Data is kept in memory while the application runs and is lost when it stops. Write another "
            "implementation of each repository interface and create it in `Application.kt`."
        )
    elif settings["persistence"] == "none":
        storage = "Storage is left to you: each repository is an interface whose functions answer 501 until you implement them."
    else:
        storage = (
            f"Exposed on {database}. The application creates the tables that are missing when it starts, while you "
            "develop; for a real database, use migrations (Model2DB writes them). Embedded objects and lists are "
            "stored as JSON text, and references as key columns."
        )
    if settings["auth"] == "none":
        auth = "Every endpoint is public."
    elif settings["auth"] == "apiKey":
        auth = (
            "Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. "
            "Without `API_KEYS`, every protected request is rejected."
        )
    else:
        auth = (
            "Protected endpoints need a bearer token issued by your identity provider, signed with HS256. The API "
            "verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads "
            "the roles from the `roles` claim. It does not issue tokens."
        )
    path = settings["javaPackage"].replace(".", "/")
    if settings["architecture"] == "modular":
        layout = [
            f"src/main/kotlin/{path}/",
            "  Application.kt        entry point: wires storage, services and routes",
            "  common/               errors, request bodies, JSON, lists and settings",
            "  shared/               enums and embedded objects",
            "  <resource>/           model, request and response, repository, service and routes of one resource",
            context.exposed and "  database/             connection and tables",
            context.security and "  security/             authentication",
        ]
    else:
        layout = [
            f"src/main/kotlin/{path}/",
            "  Application.kt        entry point: wires storage, services and routes",
            "  common/               errors, request bodies, JSON, lists and settings",
            "  model/                domain classes, enums and embedded objects",
            "  dto/                  request bodies and responses",
            "  repository/           storage",
            "  service/              rules of each resource",
            "  routes/               HTTP routes",
            context.exposed and "  database/             connection and tables",
            context.security and "  security/             authentication",
        ]
    each = "a new SQLite file" if database == "sqlite" else "a new in-memory H2 database"
    content = lines(
        f"# {spec['title']}",
        "",
        "REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Ktor. It is a "
        "starting point: review it before using it in production.",
        "",
        "## Run it",
        "",
        "Requires Java 21 and Gradle 9 (or a Gradle wrapper: `gradle wrapper` creates one).",
        "",
        "```bash",
        "gradle run",
        "```",
        "",
        "Set the variables of `.env.example` in your environment first. The API listens on http://localhost:8080. "
        "Its contract is in `openapi.yaml`.",
        "",
        "## Test it",
        "",
        "```bash",
        "gradle test",
        "```",
        "",
        "Each test starts the application anew, so it starts with empty storage.",
        context.exposed
        and f"The tests use {each} for each test, or the {database} database in `TEST_DATABASE_URL` (with "
        "`TEST_DATABASE_USER` and `TEST_DATABASE_PASSWORD`; its tables are dropped before each test).",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does | Success | Access |",
        "|---|---|---|---|---|",
        _endpoint_rows(spec["resources"]),
        "",
        'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid '
        "requests answer 400.",
        "",
        "## Storage",
        "",
        storage,
        "",
        "## Authentication",
        "",
        auth,
        "",
        "## Structure",
        "",
        "```text",
        layout,
        "src/test/kotlin/         one test class per resource",
        "openapi.yaml             the contract of the API",
        "```",
        "",
        "## Left to you",
        "",
        pending if pending else "- Nothing marked: review the generated code before using it.",
    )
    return {"path": "README.md", "content": file_text(content)}
