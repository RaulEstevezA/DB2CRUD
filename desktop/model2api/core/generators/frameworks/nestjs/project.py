from ...common.text import file_text, lines
from ..express.project import auth_text, json_file, pending_work
from ..fastapi.project import endpoint_rows
from .context import NestContext

_DRIVERS = {
    "postgresql": {"pg": "^8.13.0"},
    "mysql": {"mysql2": "^3.12.0"},
    "mariadb": {"mysql2": "^3.12.0"},
}

_URLS = {
    "postgresql": "postgres://api:change-me@localhost:5432/api",
    "mysql": "mysql://api:change-me@localhost:3306/api",
    "mariadb": "mysql://api:change-me@localhost:3306/api",
}


def package_file(context: NestContext) -> dict:
    auth = context.settings["auth"]
    database = context.settings["database"]
    dependencies = {
        "@nestjs/common": "^11.1.0",
        "@nestjs/core": "^11.1.0",
        "@nestjs/platform-express": "^11.1.0",
        "class-transformer": "^0.5.1",
        "class-validator": "^0.14.2",
        "reflect-metadata": "^0.2.2",
        "rxjs": "^7.8.1",
        **({"jsonwebtoken": "^9.0.2"} if auth == "jwt" else {}),
        **(
            {"@nestjs/typeorm": "^11.0.0", "typeorm": "^0.3.25", **_DRIVERS[database or "postgresql"]}
            if context.typeorm
            else {}
        ),
    }
    dev_dependencies = {
        "@nestjs/testing": "^11.1.0",
        "@types/express": "^5.0.3",
        "@types/jest": "^29.5.14",
        "@types/node": "^24.0.0",
        "@types/supertest": "^6.0.3",
        **({"@types/jsonwebtoken": "^9.0.10"} if auth == "jwt" else {}),
        **({"sql.js": "^1.13.0"} if context.typeorm else {}),
        "jest": "^29.7.0",
        "supertest": "^7.1.0",
        "ts-jest": "^29.4.0",
        "ts-node": "^10.9.2",
        "typescript": "~5.9.0",
    }
    manifest = {
        "name": context.settings["name"],
        "version": "0.1.0",
        "private": True,
        "description": "REST API generated by Model2API",
        "engines": {"node": ">=22"},
        "scripts": {
            "build": "tsc -p tsconfig.build.json",
            "start": "node dist/main.js",
            "dev": "ts-node src/main.ts",
            "typecheck": "tsc --noEmit",
            # With a database, test files take turns: each one recreates the schema
            "test": "jest --runInBand" if context.typeorm else "jest",
        },
        "dependencies": dependencies,
        "devDependencies": dev_dependencies,
        "jest": {
            "rootDir": ".",
            "testRegex": "test/.*\\.e2e-spec\\.ts$",
            "transform": {"^.+\\.ts$": "ts-jest"},
            "testEnvironment": "node",
            "setupFiles": ["<rootDir>/test/setup.ts"],
        },
    }
    return {"path": "package.json", "content": file_text(json_file(manifest))}


def tsconfig_files() -> list[dict]:
    base = {
        "compilerOptions": {
            "module": "commonjs",
            "target": "ES2023",
            "strict": True,
            "experimentalDecorators": True,
            "emitDecoratorMetadata": True,
            "esModuleInterop": True,
            "skipLibCheck": True,
            "strictPropertyInitialization": False,
            "noEmit": True,
        },
        "include": ["src", "test"],
    }
    build = {
        "extends": "./tsconfig.json",
        "compilerOptions": {"noEmit": False, "outDir": "dist", "rootDir": "src"},
        "include": ["src"],
    }
    return [
        {"path": "tsconfig.json", "content": file_text(json_file(base))},
        {"path": "tsconfig.build.json", "content": file_text(json_file(build))},
    ]


def env_example_file(context: NestContext) -> dict:
    auth = context.settings["auth"]
    database = context.settings["database"]
    content = lines(
        "# Environment of the API. Export these variables before running it. Never commit real values.",
        "",
        "# Port the API listens on",
        "PORT=3000",
        context.typeorm
        and [
            "",
            "# Database connection",
            f"DATABASE_URL={_URLS[database or 'postgresql']}",
            "# Set to false once you use migrations",
            "DATABASE_SYNCHRONIZE=true",
        ],
        auth == "apiKey" and ["", "# Accepted API keys, separated by commas. Use long random values.", "API_KEYS="],
        auth == "jwt"
        and [
            "",
            "# Secret that signs the tokens of your identity provider. Without it every protected request is rejected.",
            "JWT_SECRET=",
            "JWT_ALGORITHM=HS256",
            "JWT_AUDIENCE=",
            "JWT_ISSUER=",
        ],
    )
    return {"path": ".env.example", "content": file_text(content)}


def gitignore_file() -> dict:
    return {
        "path": ".gitignore",
        "content": file_text(lines("node_modules/", "dist/", "coverage/", ".env", "*.log", ".DS_Store")),
    }


def readme_file(context: NestContext) -> dict:
    settings = context.settings
    spec = context.spec
    pending = pending_work(spec, context.pending)
    if settings["persistence"] == "memory":
        storage = (
            "Data is kept in memory while the application runs and is lost when it stops. Bind another implementation "
            "of each repository token in its module to use a database."
        )
    elif settings["persistence"] == "none":
        storage = (
            "Storage is left to you: each repository is an interface whose methods answer 501 until you implement them."
        )
    else:
        storage = (
            f"TypeORM on {settings['database']}. Tables are synchronized at startup while you develop "
            "(DATABASE_SYNCHRONIZE); for a real database, use migrations (Model2DB writes them). Dates are stored as "
            "ISO text and embedded objects and lists as JSON text, the same on every database. The tests use an "
            "in-memory SQLite (sql.js), or the database in TEST_DATABASE_URL."
        )
    content = lines(
        f"# {spec['title']}",
        "",
        "REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with NestJS. It is a "
        "starting point: review it before using it in production.",
        "",
        "## Run it",
        "",
        "Requires Node.js 22 or later.",
        "",
        "```bash",
        "npm install",
        "npm run build",
        "npm start                        # with the variables of .env.example in your environment",
        "```",
        "",
        "The API listens on http://localhost:3000. Its contract is in `openapi.yaml`.",
        "",
        "## Test it",
        "",
        "```bash",
        "npm test",
        "npm run typecheck",
        "```",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does | Success | Access |",
        "|---|---|---|---|---|",
        endpoint_rows(spec["resources"]),
        "",
        'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid '
        "requests answer 400.",
        "",
        "## Storage",
        "",
        storage,
        "",
        "## Authentication",
        "",
        auth_text(settings["auth"]),
        "",
        "## Structure",
        "",
        "```text",
        "src/",
        "  main.ts, app.module.ts, app.setup.ts",
        "  common/               errors, validation, lists and authentication",
        "  shared/               enums and embedded objects",
        "  <resource>/           module, controller, service, repository and DTOs of one resource",
        "test/                   one end-to-end test file per resource",
        "openapi.yaml            the contract of the API",
        "```",
        "",
        "## Left to you",
        "",
        pending if pending else "- Nothing marked: review the generated code before using it.",
    )
    return {"path": "README.md", "content": file_text(content)}
