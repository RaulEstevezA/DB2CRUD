VERSIONS = {"php": ">=8.4", "phpunit": "^12.4"}


def _tests(context: dict) -> bool:
    return context["settings"]["tests"] != "none" and writes_entities(context)


def _json(value, spaces: int) -> str:
    """JSON.stringify(value, null, spaces): no escaped slashes or non-ASCII characters."""
    return json.dumps(value, indent=spaces, ensure_ascii=False)


def composer_file(context: dict, models_namespace: str | None = None) -> dict:
    """composer.json; `models_namespace` when the copy of the imported application models is in
    application-models/: Composer loads it for that namespace too, while the folder exists."""
    tests = _tests(context)
    composer = {
        "name": f"app/{context['settings']['name']}",
        "description": f"Data access layer generated by DB2CRUD ({context['orm']['label']})",
        "type": "project",
        "license": "proprietary",
        "require": {"php": VERSIONS["php"], "ext-mbstring": "*", **context["orm"]["require"](context)},
        **({"require-dev": {"phpunit/phpunit": VERSIONS["phpunit"]}} if tests else {}),
        "autoload": {
            "psr-4": {"App\\": "src/", **({f"{models_namespace}\\": "application-models/"} if models_namespace else {})}
        },
        **({"autoload-dev": {"psr-4": {"Tests\\": "tests/"}}} if tests else {}),
        **({"scripts": {"test": "phpunit"}} if tests else {}),
        "config": {"sort-packages": True},
    }
    return {"path": "composer.json", "content": f"{_json(composer, 4)}\n"}


def phpunit_file(context: dict) -> dict | None:
    if not _tests(context):
        return None
    return {
        "path": "phpunit.xml",
        "content": lines(
            '<?xml version="1.0" encoding="UTF-8"?>',
            '<phpunit xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
            '         xsi:noNamespaceSchemaLocation="vendor/phpunit/phpunit/phpunit.xsd"',
            '         bootstrap="vendor/autoload.php"',
            '         cacheDirectory=".phpunit.cache"',
            '         failOnWarning="true"',
            '         colors="true">',
            "    <testsuites>",
            '        <testsuite name="all">',
            "            <directory>tests</directory>",
            "        </testsuite>",
            "    </testsuites>",
            "    <source>",
            "        <include>",
            "            <directory>src</directory>",
            "        </include>",
            "    </source>",
            "</phpunit>",
            "",
        ),
    }


def env_example_file(context: dict) -> dict:
    sqlite = context["settings"]["database"] == "sqlite"
    return {
        "path": ".env.example",
        "content": lines(
            "# Where the database is",
            f"DATABASE_URL={context['orm']['defaultUrl'](context)}",
            "# The tests use SQLite in memory unless this names another database (it is emptied by the tests)"
            if sqlite
            else "# The database the tests use (it is emptied by the tests): one of the same kind as DATABASE_URL",
            "# TEST_DATABASE_URL=",
            "",
        ),
    }


def gitignore_file() -> dict:
    return {"path": ".gitignore", "content": lines("/vendor/", "composer.lock", ".phpunit.cache/", ".env", "*.db", "")}


LABELS = {
    "transactions": {
        "operation": "one transaction per service operation, committed when it ends",
        "caller": "the caller owns the transaction: nothing commits",
        "repository": "every repository write is committed at once",
    },
    "paging": {
        "none": "lists return every row",
        "offset": "lists return pages by offset and limit",
        "cursor": "lists return pages after a key (cursor)",
    },
    "updates": {
        "patch": "updates take a Patch per field: absent, or a value that may be null",
        "partial": "updates take an array of the fields that change",
        "full": "updates take every field that can change",
        "optional": "",
    },
}


def readme_file(context: dict) -> dict:
    settings = context["settings"]
    orm = context["orm"]
    sqlite = settings["database"] == "sqlite"
    if settings["entities"] == "missing":
        entities = "written for the tables the input had no class for"
    elif settings["entities"] == "all":
        entities = "written for every table"
    else:
        entities = f"imported from `{settings['entitiesModule']}`"
    if settings["services"]:
        kind = "classes" if settings["dtoKind"] == "class" else "readonly classes"
        types = f"DTOs ({kind})" if settings["serviceTypes"] == "dtos" else "the entities"
        services = f"take and return {types}; {LABELS['updates'][settings['updates']]}"
    else:
        services = "not written"
    if settings["architecture"] == "layer":
        layout = [
            "src/Entities/                one entity per table",
            "src/Repositories/            the repositories of each table",
            "src/Services/                one service per table" if settings["services"] else None,
        ]
    else:
        layout = ["src/Tables/<Table>/          entity, repositories and service of each table"]
    url = orm["defaultUrl"](context)
    intro = orm.get("intro") or f"entities mapped with {orm['label']}, repositories and services"
    return {
        "path": "README.md",
        "content": lines(
            f"# {settings['name']}",
            "",
            "Data access layer generated by [DB2CRUD](https://github.com/RaulEstevezA/DB2CRUD) for a database that "
            f"already exists: {intro}, in PHP 8.4. It does not "
            "create or migrate the database, and it depends on no web framework.",
            "",
            "## Settings",
            "",
            f"- Database: {settings['database']}.",
            f"- Entities: {entities}.",
            f"- Services: {services}.",
            f"- Transactions: {LABELS['transactions'][settings['transactions']]}.",
            f"- Lists: {LABELS['paging'][settings['paging']]}.",
            "",
            "## Layout",
            "",
            "```text",
            *orm["layout"](context),
            "src/UnitOfWork.php           the repositories of every table, and the transaction of each operation",
            "src/Errors/                  NotFoundException, ConflictException, ValidationFailedException: no HTTP codes",
            *layout,
            "tests/                       repositories against a database, services on the in-memory repositories"
            if _tests(context)
            else None,
            "crud-contract.json           what was written, for CRUD2Controller",
            "```",
            "",
            "## Running the tests",
            "",
            "```bash",
            "composer install",
            "vendor/bin/phpunit                                    # SQLite in memory" if sqlite else None,
            f'TEST_DATABASE_URL="{url}" vendor/bin/phpunit   # a real, disposable database: it is emptied',
            "```",
            "",
            "Look for `TODO` in the code: each one marks a decision the input did not settle.",
            "",
        ),
    }


def _type_of(column: dict) -> dict:
    column_type = column["column"]["type"]
    result = {"kind": column_type["kind"], "php": stored_type(column)}
    if column_type["kind"] == "text" and column_type.get("length") is not None:
        result["length"] = column_type["length"]
    return result


def contract_file(context: dict) -> dict:
    dtos = context["settings"]["serviceTypes"] == "dtos"

    def fields(columns: list[dict], optional: bool, name) -> list[dict]:
        return [
            {"name": name(column), "type": _type_of(column), "nullable": optional or column["column"]["nullable"]}
            for column in columns
        ]

    def field(column: dict) -> str:
        return column["field"]

    types = []
    for info in context["tables"]:
        types.append(
            {
                "name": info["entity"],
                "module": namespace_of(context, info, "entity"),
                "kind": "entity",
                "fields": fields(info["columns"], False, lambda column: column["prop"]),
            }
        )
        writes = info["role"] == "entity" and info["service"]
        if dtos and writes:
            types.append(
                {
                    "name": create_dto(info),
                    "module": namespace_of(context, info, "dtos"),
                    "kind": "create",
                    "fields": fields(create_columns(info), False, field),
                }
            )
        if writes:
            partial = partial_updates(context)
            types.append(
                {
                    "name": "array" if partial else update_type(context, info),
                    "module": None if partial else update_namespace(context, info),
                    "kind": "update",
                    "updates": context["settings"]["updates"],
                    "fields": fields(update_columns(info), True, field),
                }
            )
        if dtos and info["service"]:
            types.append(
                {
                    "name": read_dto(info),
                    "module": namespace_of(context, info, "dtos"),
                    "kind": "read",
                    "fields": fields(read_columns(info), False, field),
                }
            )
    errors_of = {"NotFound": "notFound", "Conflict": "conflict", "ValidationFailed": "validation"}
    services = []
    for info in context["tables"]:
        if not info["service"]:
            continue
        operations = []
        for operation in info["operations"]:
            item = {"name": operation_name(context, operation), "kind": operation["kind"]}
            if operation["columns"]:
                item["by"] = operation["columns"]
            if operation.get("through"):
                item["through"] = operation["through"]
            item["errors"] = [errors_of.get(error) for error in operation["errors"]]
            operations.append(item)
        services.append(
            {"name": service_class(info), "module": namespace_of(context, info, "service"), "operations": operations}
        )
    contract = {
        "format": "crud-contract",
        "version": 1,
        "stack": {
            "language": "php",
            "orm": context["orm"]["id"],
            "database": context["settings"]["database"],
            "execution": "sync",
        },
        "transactions": context["settings"]["transactions"],
        "paging": context["settings"]["paging"],
        "types": types,
        "errors": [
            {"kind": "notFound", "name": "NotFoundException", "module": errors_namespace(context)},
            {"kind": "conflict", "name": "ConflictException", "module": errors_namespace(context)},
            {"kind": "validation", "name": "ValidationFailedException", "module": errors_namespace(context)},
        ],
        "common": common_namespace(context),
        "services": services,
    }
    return {"path": "crud-contract.json", "content": f"{_json(contract, 2)}\n"}
