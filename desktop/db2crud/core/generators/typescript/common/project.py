# crud-contract.json


def _type_of(column: dict) -> dict:
    column_type = column["column"]["type"]
    result = {"kind": column_type["kind"]}
    if column_type["kind"] == "text" and "length" in column_type:
        result["length"] = column_type["length"]
    return result


def _fields(columns: list[dict], optional: bool) -> list[dict]:
    return [
        {"name": column["prop"], "type": _type_of(column), "nullable": optional or column["column"]["nullable"]}
        for column in columns
    ]


ERRORS_OF = {"NotFound": "notFound", "Conflict": "conflict", "ValidationFailed": "validation"}


def contract_file(context: dict) -> dict:
    dtos = context["settings"]["serviceTypes"] == "dtos"
    types = []
    for info in context["tables"]:
        entity = {
            "name": info["entity"],
            "module": module_of(context, info, "entity"),
            "kind": "entity",
            "fields": _fields(info["columns"], False),
        }
        if not dtos or not info["service"]:
            types.append(entity)
            continue
        module = module_of(context, info, "dtos")
        visible = [column for column in info["columns"] if column["column"]["name"] not in info["hidden"]]
        read = {"name": read_dto(info), "module": module, "kind": "read", "fields": _fields(visible, False)}
        if info["role"] != "entity":
            types.extend([entity, read])
            continue
        created = [column for column in info["columns"] if not column["generated"]]
        changed = [column for column in created if not is_in(column, info["key"])]
        types.extend(
            [
                entity,
                {"name": create_dto(info), "module": module, "kind": "create", "fields": _fields(created, False)},
                {"name": update_dto(info), "module": module, "kind": "update", "fields": _fields(changed, True)},
                read,
            ]
        )
    services = []
    for info in context["tables"]:
        if not info["service"]:
            continue
        operations = []
        for operation in info["operations"]:
            item = {"name": operation_name(context, operation), "kind": operation["kind"]}
            if operation["columns"]:
                item["by"] = operation["columns"]
            if operation.get("through"):
                item["through"] = operation["through"]
            item["errors"] = [ERRORS_OF[error] for error in operation["errors"]]
            operations.append(item)
        services.append(
            {"name": service_class(info), "module": module_of(context, info, "service"), "operations": operations}
        )
    settings = context["settings"]
    contract = {
        "format": "crud-contract",
        "version": 1,
        "stack": {
            "language": "typescript",
            "orm": context["orm"]["id"],
            "database": settings["database"],
            "execution": "async",
        },
        "transactions": settings["transactions"],
        "paging": settings["paging"],
        "types": types,
        "errors": [
            {"kind": "notFound", "name": "NotFoundError", "module": "src/errors"},
            {"kind": "conflict", "name": "ConflictError", "module": "src/errors"},
            {"kind": "validation", "name": "ValidationFailedError", "module": "src/errors"},
        ],
        "services": services,
    }
    return {"path": "crud-contract.json", "content": _json(contract)}
