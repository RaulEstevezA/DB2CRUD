"""The files around the code: package.json (an ES module, with typecheck, build and test scripts), the TypeScript
and Vitest settings, the README, an example environment, and crud-contract.json, which describes what was written
so CRUD2Controller does not have to read the code back (docs/design.md, section 6). Mirrors
web/src/core/generators/typescript/common/project.ts."""

import json

from ...types import lines
from .context import is_in, module_of, operation_name, service_class, writes_entities
from .dtos import create_dto, read_dto, update_dto

VERSIONS = {"typescript": "^5.9.3", "vitest": "^3.2.4", "typesNode": "^24.10.0"}


def _json(value) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def _sorted(record: dict) -> dict:
    return dict(sorted(record.items()))


def _has_tests(context: dict) -> bool:
    return context["settings"]["tests"] != "none" and writes_entities(context)


def package_file(context: dict) -> dict:
    tests = _has_tests(context)
    orm = context["orm"]
    content = {
        "name": context["settings"]["name"],
        "version": "0.1.0",
        "description": "Data access layer (entities, repositories and services) generated by DB2CRUD.",
        "private": True,
        "type": "module",
        "engines": {"node": ">=20"},
        "scripts": {
            "typecheck": "tsc --noEmit",
            "build": "tsc -p tsconfig.build.json",
            "test": "vitest run"
            if tests
            else 'echo "No tests: the project writes no entities, or the settings asked for none"',
            **(orm["scripts"](context) if "scripts" in orm else {}),
        },
        "dependencies": _sorted(orm["dependencies"](context)),
        "devDependencies": _sorted(
            {
                **orm["devDependencies"](context),
                "@types/node": VERSIONS["typesNode"],
                "typescript": VERSIONS["typescript"],
                **({"vitest": VERSIONS["vitest"]} if tests else {}),
            }
        ),
    }
    return {"path": "package.json", "content": _json(content)}


def tsconfig_files(context: dict) -> list[dict]:
    tests = _has_tests(context)
    orm = context["orm"]
    setup = orm["testSetup"](context) if "testSetup" in orm else None
    options = {
        "target": "ES2022",
        "module": "NodeNext",
        "moduleResolution": "NodeNext",
        "lib": ["ES2022"],
        "types": ["node"],
        "strict": True,
        # The ORM's decorators; every column names its type, so no decorator metadata is needed
        "experimentalDecorators": True,
        "useDefineForClassFields": False,
        "isolatedModules": True,
        "skipLibCheck": True,
        "noEmit": True,
    }
    build = {
        "extends": "./tsconfig.json",
        "compilerOptions": {"noEmit": False, "rootDir": "src", "outDir": "dist", "declaration": True},
        "include": ["src"],
    }
    files = [
        {
            "path": "tsconfig.json",
            "content": _json({"compilerOptions": options, "include": ["src", "test"] if tests else ["src"]}),
        },
        {"path": "tsconfig.build.json", "content": _json(build)},
    ]
    if tests:
        files.append(
            {
                "path": "vitest.config.ts",
                "content": lines(
                    "import { defineConfig } from 'vitest/config'",
                    "",
                    "export default defineConfig({",
                    "  test: {",
                    "    include: ['test/**/*.test.ts'],",
                    setup and f"    globalSetup: ['{setup}'],",
                    "    // Every test file empties the same test database: they run one after another",
                    "    fileParallelism: false,",
                    "  },",
                    "})",
                    "",
                ),
            }
        )
    return files


def env_example_file(context: dict) -> dict:
    return {
        "path": ".env.example",
        "content": lines(
            "# Where the database is",
            f"DATABASE_URL={context['orm']['defaultUrl'](context)}",
            "# The tests use SQLite in memory unless this names another database (it is emptied by the tests)"
            if context["orm"]["memoryTests"](context)
            else "# The database the tests use (it is emptied by the tests): they need one of the same kind as DATABASE_URL",
            "# TEST_DATABASE_URL=",
            "",
        ),
    }


def gitignore_file(context: dict) -> dict:
    orm = context["orm"]
    ignored = orm["ignored"](context) if "ignored" in orm else []
    return {"path": ".gitignore", "content": lines("node_modules/", "dist/", ".env", "*.db", *ignored, "")}


