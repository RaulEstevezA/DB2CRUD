from .support import default_url


def _tests(context: dict) -> bool:
    return context["settings"]["tests"] != "none" and writes_entities(context)


def package_file(context: dict, models: dict | None = None) -> dict:
    """Package.swift; `models` when the conversions use the application models, in a target of their own."""
    parts = context["orm"]["packages"](context)
    module = context["module"]
    test_dependencies = ", ".join([f'"{module}"', *parts["testProducts"]])
    return {
        "path": "Package.swift",
        "content": lines(
            "// swift-tools-version:6.0",
            "import PackageDescription",
            "",
            "let package = Package(",
            f'    name: "{context["settings"]["name"]}",',
            "    platforms: [.macOS(.v13)],",
            f'    products: [.library(name: "{module}", targets: ["{module}"])],',
            "    dependencies: [",
            *(f"        {line}" for line in parts["packages"]),
            "    ],",
            "    targets: [",
            "        .target(",
            f'            name: "{module}",',
            "            dependencies: [",
            *(f"                {line}," for line in parts["products"]),
            models and f'                "{models["target"]}",',
            "            ]",
            "        ),",
            models
            and [
                "        // The application models: the copy DB2CRUD read, while the project runs on its own. Inside the"
                " application, replace this target with your module."
                if models["imported"]
                else "        // The application models: a copy of the types DB2CRUD read.",
                f'        .target(name: "{models["target"]}", path: "{models["path"]}"),',
            ],
            _tests(context)
            and [
                "        .testTarget(",
                f'            name: "{module}Tests",',
                f"            dependencies: [{test_dependencies}]",
                "        ),",
            ],
            "    ]",
            ")",
            "",
        ),
    }


def env_example_file(context: dict) -> dict:
    sqlite = context["settings"]["database"] == "sqlite"
    return {
        "path": ".env.example",
        "content": lines(
            "# Where the database is, and who connects",
            f"DATABASE_URL={default_url(context)}",
            "# The tests use SQLite in memory unless this names another database (it is emptied by the tests)"
            if sqlite
            else "# The database the tests use (it is emptied by the tests): one of the same kind as DATABASE_URL",
            "# TEST_DATABASE_URL=",
            "",
        ),
    }


def gitignore_file() -> dict:
    return {"path": ".gitignore", "content": lines(".build/", ".swiftpm/", ".env", "*.db", "")}


