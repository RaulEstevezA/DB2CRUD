def requirements_files(context: dict) -> list[dict]:
    return [
        {"path": "requirements.txt", "content": lines(*context["orm"]["dependencies"](context), "")},
        {
            "path": "requirements-dev.txt",
            "content": lines("-r requirements.txt", *context["orm"]["devDependencies"](context), ""),
        },
    ]


def pyproject_file(context: dict) -> dict:
    def quote(items: list[str]) -> list[str]:
        return [f'    "{item}",' for item in items]

    return {
        "path": "pyproject.toml",
        "content": lines(
            "[project]",
            f'name = "{context["settings"]["name"]}"',
            'version = "0.1.0"',
            'description = "Data access layer (entities, repositories and services) generated by DB2CRUD."',
            'requires-python = ">=3.12"',
            "dependencies = [",
            *quote(context["orm"]["dependencies"](context)),
            "]",
            "",
            "[project.optional-dependencies]",
            "dev = [",
            *quote(context["orm"]["devDependencies"](context)),
            "]",
            "",
            "[tool.pytest.ini_options]",
            'testpaths = ["tests"]',
            'pythonpath = ["."]',
            *context["orm"]["pytestOptions"](context),
            "",
        ),
    }


