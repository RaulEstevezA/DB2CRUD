DRIVERS = {
    "postgresql": ("org.postgresql", "postgresql", VERSIONS["postgresql"]),
    "mysql": ("com.mysql", "mysql-connector-j", VERSIONS["mysql"]),
    "mariadb": ("org.mariadb.jdbc", "mariadb-java-client", VERSIONS["mariadb"]),
    "sqlite": ("org.xerial", "sqlite-jdbc", VERSIONS["sqlite"]),
}


def _dependency(group: str, artifact: str, version: str, scope: str | None = None) -> list[str]:
    return [
        "    <dependency>",
        f"      <groupId>{group}</groupId>",
        f"      <artifactId>{artifact}</artifactId>",
        f"      <version>{version}</version>",
        *([f"      <scope>{scope}</scope>"] if scope else []),
        "    </dependency>",
    ]


def pom_file(context: dict) -> dict:
    database = context["settings"]["database"]
    group, artifact, version = DRIVERS.get(database, DRIVERS["postgresql"])
    uses_json = any(
        column["column"]["type"]["kind"] in ("json", "array")
        for info in context["tables"]
        for column in info["columns"]
    )
    tests = context["settings"]["tests"] != "none" and writes_entities(context)
    content = lines(
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
        '         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">',
        "  <modelVersion>4.0.0</modelVersion>",
        "",
        f"  <groupId>{context['base']}</groupId>",
        f"  <artifactId>{context['settings']['name']}</artifactId>",
        "  <version>0.1.0</version>",
        "  <description>Data access layer (entities, repositories and services) generated by DB2CRUD.</description>",
        "",
        "  <properties>",
        "    <maven.compiler.release>21</maven.compiler.release>",
        "    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>",
        "  </properties>",
        "",
        "  <dependencies>",
        *_dependency("org.hibernate.orm", "hibernate-core", VERSIONS["hibernate"]),
        database == "sqlite"
        and _dependency("org.hibernate.orm", "hibernate-community-dialects", VERSIONS["hibernate"]),
        *_dependency(group, artifact, version),
        # Hibernate reads and writes JSON columns with Jackson
        uses_json and _dependency("com.fasterxml.jackson.core", "jackson-databind", VERSIONS["jackson"]),
        tests and _dependency("org.junit.jupiter", "junit-jupiter", VERSIONS["junit"], "test"),
        "  </dependencies>",
        "",
        "  <build>",
        "    <plugins>",
        "      <plugin>",
        "        <groupId>org.apache.maven.plugins</groupId>",
        "        <artifactId>maven-surefire-plugin</artifactId>",
        f"        <version>{VERSIONS['surefire']}</version>",
        "      </plugin>",
        "    </plugins>",
        "  </build>",
        "</project>",
        "",
    )
    return {"path": "pom.xml", "content": content}


