def readme_file(context: dict) -> dict:
    settings = context["settings"]
    base = context["base"]
    sqlite = settings["database"] == "sqlite"
    if settings["entities"] == "missing":
        entities = "written for the tables the input had no class for"
    elif settings["entities"] == "all":
        entities = "written for every table"
    else:
        entities = f"imported from `{settings['entitiesModule']}`"
    if settings["services"]:
        kind = (
            f"DTOs ({'classes' if settings['dtoKind'] == 'class' else 'records'})"
            if settings["serviceTypes"] == "dtos"
            else "the entities"
        )
        services = f"take and return {kind}; {LABELS['updates'][settings['updates']]}"
    else:
        services = "not written"
    if settings["architecture"] == "layer":
        layout = [
            f"src/main/java/{base}/entities/            one entity per table",
            f"src/main/java/{base}/repositories/        the repositories of each table",
            settings["services"] and f"src/main/java/{base}/services/            one service per table",
        ]
    else:
        layout = [f"src/main/java/{base}/<table>/             entity, repositories and service of each table"]
    credentials = "" if sqlite else " TEST_DATABASE_USER=app TEST_DATABASE_PASSWORD=app"
    return {
        "path": "README.md",
        "content": lines(
            f"# {settings['name']}",
            "",
            "Data access layer generated by [DB2CRUD](https://github.com/RaulEstevezA/DB2CRUD) for a database that already exists: JPA entities, repositories over an `EntityManager` (Hibernate) and services, in Java 21. It does not create or migrate the database, and it depends on no framework.",
            "",
            "## Settings",
            "",
            f"- Database: {settings['database']}.",
            f"- Entities: {entities}.",
            f"- Services: {services}.",
            f"- Transactions: {LABELS['transactions'][settings['transactions']]}.",
            f"- Lists: {LABELS['paging'][settings['paging']]}.",
            "",
            "## Layout",
            "",
            "```text",
            f"src/main/java/{base}/Database.java        the EntityManagerFactory of DATABASE_URL, with every entity",
            f"src/main/java/{base}/UnitOfWork.java      the repositories of every table, and the transaction of each operation",
            f"src/main/java/{base}/errors/              NotFoundException, ConflictException, ValidationFailedException: no HTTP codes",
            *layout,
            "src/test/java/                       repositories against a database, services on the in-memory repositories",
            "crud-contract.json                   what was written, for CRUD2Controller",
            "```",
            "",
            "## Running the tests",
            "",
            "```bash",
            sqlite and "mvn test                                          # SQLite in target/",
            f"TEST_DATABASE_URL={URLS[settings['database']]}{credentials} mvn test   # a real, disposable database: it is emptied",
            "```",
            "",
            "`Database.open()` uses the connection pool built into Hibernate, which is fine for trying the code; in production give `Database.configuration(...)` a `DataSource` or a pool such as HikariCP.",
            "",
            "Look for `TODO` in the code: each one marks a decision the input did not settle.",
            "",
        ),
    }


def _type_of(column: dict) -> dict:
    column_type = column["column"]["type"]
    result = {"kind": column_type["kind"], "java": column["java"]}
    if column_type["kind"] == "text" and column_type.get("length") is not None:
        result["length"] = column_type["length"]
    return result


def _fields(columns: list[dict], optional: bool) -> list[dict]:
    return [
        {"name": column["prop"], "type": _type_of(column), "nullable": optional or column["column"]["nullable"]}
        for column in columns
    ]


ERRORS_OF = {"NotFound": "notFound", "Conflict": "conflict", "ValidationFailed": "validation"}


def contract_file(context: dict) -> dict:
    dtos = context["settings"]["serviceTypes"] == "dtos"
    types = []
    for info in context["tables"]:
        types.append(
            {
                "name": info["entity"],
                "module": package_of(context, info, "entity"),
                "kind": "entity",
                "fields": _fields(info["columns"], False),
            }
        )
        writes = info["role"] == "entity" and info["service"]
        if dtos and info["service"] and writes:
            types.append(
                {
                    "name": create_dto(info),
                    "module": package_of(context, info, "dtos"),
                    "kind": "create",
                    "fields": _fields(create_columns(info), False),
                }
            )
        if writes:
            types.append(
                {
                    "name": update_type(context, info),
                    "module": update_package(context, info),
                    "kind": "update",
                    "updates": context["settings"]["updates"],
                    "fields": _fields(update_columns(info), True),
                }
            )
        if dtos and info["service"]:
            types.append(
                {
                    "name": read_dto(info),
                    "module": package_of(context, info, "dtos"),
                    "kind": "read",
                    "fields": _fields(read_columns(info), False),
                }
            )
    services = []
    for info in context["tables"]:
        if not info["service"]:
            continue
        operations = []
        for operation in info["operations"]:
            item = {"name": operation_name(context, operation), "kind": operation["kind"]}
            if operation["columns"]:
                item["by"] = operation["columns"]
            if operation.get("through"):
                item["through"] = operation["through"]
            item["errors"] = [ERRORS_OF[error] for error in operation["errors"]]
            operations.append(item)
        services.append(
            {"name": service_class(info), "module": package_of(context, info, "service"), "operations": operations}
        )
    contract = {
        "format": "crud-contract",
        "version": 1,
        "stack": {"language": "java", "orm": "jpa", "database": context["settings"]["database"], "execution": "sync"},
        "transactions": context["settings"]["transactions"],
        "paging": context["settings"]["paging"],
        "types": types,
        "errors": [
            {"kind": "notFound", "name": "NotFoundException", "module": errors_package(context)},
            {"kind": "conflict", "name": "ConflictException", "module": errors_package(context)},
            {"kind": "validation", "name": "ValidationFailedException", "module": errors_package(context)},
        ],
        "common": common_package(context),
        "services": services,
    }
    return {"path": "crud-contract.json", "content": json.dumps(contract, indent=2, ensure_ascii=False) + "\n"}
