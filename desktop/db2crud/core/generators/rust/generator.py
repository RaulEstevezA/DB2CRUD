"""The Rust generator: asynchronous Rust + SeaORM 2 data access layers, with no web framework. Every file of the
project, composed from the modules of this folder; each module writes one kind of file. src/lib.rs and the mod.rs of
every folder are derived from the modules written, so each one is declared exactly once. Mirrors
web/src/core/generators/rust/generator.ts."""

import re

from ...conversions.plan import plan_conversions
from .context import create_context
from .conversions import MODELS_FOLDER, conversion_files, conversion_test_file, models_module, service_plans
from .dtos import dto_file
from .entities import entity_file, table_file
from .project import cargo_file, contract_file, env_example_file, gitignore_file, readme_file
from .repositories import repository_file
from .rust import snake_name
from .services import service_file
from .support import common_file, database_file, errors_file, unit_of_work_file
from .tests import can_make, test_files


def _code(context: dict) -> list[dict]:
    files = [database_file(context), errors_file(), common_file(context), unit_of_work_file(context)]
    for info in context["tables"]:
        if info["writesEntity"]:
            files += [entity_file(context, info), table_file(context, info)]
        files.append(repository_file(context, info))
        if context["settings"]["services"] and info["service"]:
            if context["settings"]["serviceTypes"] == "dtos":
                files.append(dto_file(context, info))
            files.append(service_file(context, info))
    return [file for file in files if file is not None]


FOLDERS = {
    "entities": "The entities of every table, and the SeaORM description of each table.",
    "repositories": "The repositories of every table.",
    "services": "The services of every table.",
    "dtos": "What the services take and return.",
    "conversions": "The conversions between the application models and the tables.",
}


def _module_files(context: dict, files: list[dict], extra: list[str] | None = None) -> list[dict]:
    """lib.rs and the mod.rs of every folder, declaring the modules of the files under src/."""
    children: dict[str, list[str]] = {}
    for file in files:
        if not file["path"].startswith("src/"):
            continue
        parts = re.sub(r"\.rs$", "", file["path"][4:]).split("/")
        for depth in range(len(parts)):
            names = children.setdefault("/".join(parts[:depth]), [])
            if parts[depth] not in names:
                names.append(parts[depth])
    result = []
    for folder, names in children.items():
        declarations = [f"pub mod {snake_name(name)};" for name in sorted(names)]
        if folder == "":
            result.append(
                {
                    "path": "src/lib.rs",
                    "content": "\n".join(
                        [
                            f"//! {context['settings']['name']}: the data access layer of the database, through SeaORM. Generated by DB2CRUD.",
                            "",
                            *declarations,
                            *(extra or []),
                            "",
                        ]
                    ),
                }
            )
            continue
        table = next((info for info in context["tables"] if re.sub(r"^r#", "", info["attr"]) == folder), None)
        doc = FOLDERS.get(folder) or (
            f'What works on the "{table["name"]}" table.' if table else "The modules of this folder."
        )
        result.append({"path": f"src/{folder}/mod.rs", "content": "\n".join([f"//! {doc}", "", *declarations, ""])})
    return result


def _crates_of(files: list[dict]) -> list[str]:
    """The crates some files name: `chrono::NaiveDate`, `rust_decimal::Decimal`."""
    found: list[str] = []
    for file in files:
        for name in re.findall(r"\b(chrono|rust_decimal|uuid)::", file["content"]):
            if name not in found:
                found.append(name)
    return found


def _generate(schema: dict, design: dict, settings: dict, models: dict | None = None) -> list[dict]:
    context = create_context(schema, design, settings)
    plans = service_plans(context, plan_conversions(schema, design, models)) if models else []
    conversions = conversion_files(context, models["schema"], plans) if models else []
    files = [*_code(context), *conversions]
    # With imported models, lib.rs declares the copy while the project runs on its own
    imported = bool(conversions) and settings["modelsSource"] == "import"
    extra = (
        [
            "",
            "// The application models: the copy DB2CRUD read, while the project runs on its own. Inside the application,"
            " delete",
            "// application-models/ and declare your module here.",
            f'#[path = "../{MODELS_FOLDER}/mod.rs"]',
            f"pub mod {models_module(context).split('::')[1]};",
        ]
        if imported
        else []
    )
    tests = test_files(context)
    conversion_tests = (
        conversion_test_file(context, plans, models["schema"], lambda info: can_make(context, info))
        if models and tests and settings["tests"] in ("all", "services")
        else None
    )
    # The tests crate declares the module of the conversion tests
    if conversion_tests:
        tests = [
            {**file, "content": f"{file['content']}mod conversions;\n"}
            if file["path"] == "tests/data/main.rs"
            else file
            for file in tests
        ]
    return [
        readme_file(context),
        cargo_file(context, _crates_of(conversions)),
        env_example_file(context),
        gitignore_file(),
        contract_file(context),
        *files,
        *_module_files(context, files, extra),
        *tests,
        *([conversion_tests] if conversion_tests else []),
    ]


RUST_GENERATOR = {"language": "rust", "orm": "seaorm", "generate": _generate}
