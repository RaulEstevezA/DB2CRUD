import type { SpecResource } from '../../../api/spec.ts'
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import type { FastApiContext } from './context.ts'

const DRIVERS: Record<string, { package: string; url: string }> = {
  postgresql: { package: 'psycopg[binary]>=3.1,<4', url: 'postgresql+psycopg://api:change-me@localhost:5432/api' },
  mysql: { package: 'pymysql>=1.1,<2', url: 'mysql+pymysql://api:change-me@localhost:3306/api' },
  mariadb: { package: 'pymysql>=1.1,<2', url: 'mysql+pymysql://api:change-me@localhost:3306/api' },
  sqlite: { package: '', url: 'sqlite:///./app.db' },
}

function usesEmail(context: FastApiContext): boolean {
  const fields = [
    ...context.spec.resources.flatMap((resource) => resource.fields),
    ...context.spec.objects.flatMap((object) => object.fields),
  ]
  return fields.some((field) => field.constraints.format === 'email')
}

export function requirementsFiles(context: FastApiContext): GeneratedFile[] {
  const database = context.settings.database
  const driver = database ? DRIVERS[database] : undefined
  const runtime = lines(
    'fastapi>=0.115,<1',
    'uvicorn[standard]>=0.30,<1',
    'pydantic>=2.7,<3',
    usesEmail(context) && 'email-validator>=2.1,<3',
    context.sql && 'sqlalchemy>=2.0,<3',
    driver?.package,
    (database === 'mysql' || database === 'mariadb') && 'cryptography>=42',
    context.settings.auth === 'jwt' && 'PyJWT>=2.8,<3',
  )
  const dev = lines('-r requirements.txt', 'pytest>=8,<9', 'httpx2>=2.10,<3')
  return [
    { path: 'requirements.txt', content: fileText(runtime) },
    { path: 'requirements-dev.txt', content: fileText(dev) },
  ]
}

