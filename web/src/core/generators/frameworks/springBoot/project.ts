/**
 * Project files of the Spring Boot project: the Maven build (pom.xml), the environment example, ignore
 * rules and the README.
 */
import type { SpecResource } from '../../../api/spec.ts'
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import type { SpringContext } from './context.ts'

const SPRING_BOOT_VERSION = '4.1.2'
const SPRINGDOC_VERSION = '3.2.0'

const DRIVERS: Record<string, { group: string; artifact: string }> = {
  postgresql: { group: 'org.postgresql', artifact: 'postgresql' },
  mysql: { group: 'com.mysql', artifact: 'mysql-connector-j' },
  mariadb: { group: 'org.mariadb.jdbc', artifact: 'mariadb-java-client' },
}

function dependency(group: string, artifact: string, scope?: string, version?: string): string[] {
  return [
    '        <dependency>',
    `            <groupId>${group}</groupId>`,
    `            <artifactId>${artifact}</artifactId>`,
    version ? `            <version>${version}</version>` : '',
    scope ? `            <scope>${scope}</scope>` : '',
    '        </dependency>',
  ].filter(Boolean)
}

export function pomFile(context: SpringContext): GeneratedFile {
  const { settings } = context
  const driver = settings.database ? DRIVERS[settings.database] : undefined
  const content = lines(
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Maven build of the API generated by Model2API. -->',
    '<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
    '         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">',
    '    <modelVersion>4.0.0</modelVersion>',
    '',
    '    <parent>',
    '        <groupId>org.springframework.boot</groupId>',
    '        <artifactId>spring-boot-starter-parent</artifactId>',
    `        <version>${SPRING_BOOT_VERSION}</version>`,
    '        <relativePath/>',
    '    </parent>',
    '',
    `    <groupId>${settings.javaPackage.split('.').slice(0, -1).join('.') || settings.javaPackage}</groupId>`,
    `    <artifactId>${settings.name}</artifactId>`,
    '    <version>0.1.0</version>',
    `    <name>${settings.name}</name>`,
    '    <description>REST API generated by Model2API</description>',
    '',
    '    <properties>',
    '        <java.version>21</java.version>',
    '    </properties>',
    '',
    '    <dependencies>',
    dependency('org.springframework.boot', 'spring-boot-starter-webmvc'),
    dependency('org.springframework.boot', 'spring-boot-starter-validation'),
    context.jpa && dependency('org.springframework.boot', 'spring-boot-starter-data-jpa'),
    context.security && dependency('org.springframework.boot', 'spring-boot-starter-security'),
    settings.auth === 'jwt' && dependency('org.springframework.boot', 'spring-boot-starter-oauth2-resource-server'),
    dependency('org.springdoc', 'springdoc-openapi-starter-webmvc-ui', undefined, SPRINGDOC_VERSION),
    driver && dependency(driver.group, driver.artifact, 'runtime'),
    context.jpa && dependency('com.h2database', 'h2', 'test'),
    dependency('org.springframework.boot', 'spring-boot-starter-webmvc-test', 'test'),
    context.security && dependency('org.springframework.security', 'spring-security-test', 'test'),
    '    </dependencies>',
    '',
    '    <build>',
    '        <plugins>',
    '            <plugin>',
    '                <groupId>org.springframework.boot</groupId>',
    '                <artifactId>spring-boot-maven-plugin</artifactId>',
    '            </plugin>',
    '        </plugins>',
    '    </build>',
    '</project>',
  )
  return { path: 'pom.xml', content: fileText(content) }
}

export function envExampleFile(context: SpringContext): GeneratedFile {
  const { auth, database } = context.settings
  const urls: Record<string, string> = {
    postgresql: 'jdbc:postgresql://localhost:5432/api',
    mysql: 'jdbc:mysql://localhost:3306/api',
    mariadb: 'jdbc:mariadb://localhost:3306/api',
  }
  const content = lines(
    '# Environment of the API. Export these variables (or set them in your IDE) before running it. Never commit real values.',
    '',
    '# Port the API listens on',
    'PORT=8080',
    context.jpa && [
      '',
      '# Database connection',
      `DATABASE_URL=${urls[database ?? 'postgresql']}`,
      'DATABASE_USER=api',
      'DATABASE_PASSWORD=change-me',
    ],
    auth === 'apiKey' && ['', '# Accepted API keys, separated by commas. Use long random values.', 'API_KEYS='],
    auth === 'jwt' && [
      '',
      '# Secret that signs the tokens of your identity provider (at least 32 bytes). Without it every protected request is rejected.',
      'JWT_SECRET=',
      '# Optional: expected audience and issuer of the tokens',
      'JWT_AUDIENCE=',
      'JWT_ISSUER=',
    ],
  )
  return { path: '.env.example', content: fileText(content) }
}

export function gitignoreFile(): GeneratedFile {
  return { path: '.gitignore', content: fileText(lines('target/', '.idea/', '*.iml', '.vscode/', '.env', '.DS_Store')) }
}

function endpointRows(resources: SpecResource[]): string[] {
  return resources.flatMap((resource) =>
    resource.endpoints.map((endpoint) => {
      const access = endpoint.access === 'roles' ? `roles: ${endpoint.roles.join(', ')}` : endpoint.access
      return `| \`${endpoint.method}\` | \`${endpoint.path}\` | ${endpoint.summary} | ${endpoint.status} | ${access} |`
    }),
  )
}

export function readmeFile(context: SpringContext): GeneratedFile {
  const { settings, spec } = context
  const pending: string[] = []
  if (context.pending) pending.push('- Storage: every repository answers 501 until you write it (search for `TODO`).')
  for (const resource of spec.resources) {
    if (resource.todo) pending.push(`- ${resource.todo}`)
    for (const field of resource.fields) if (field.todo) pending.push(`- ${resource.name}: ${field.todo}`)
    for (const endpoint of resource.endpoints.filter((item) => item.operation === 'custom')) {
      pending.push(
        `- \`${endpoint.method} ${endpoint.path}\` (${endpoint.summary}): write its logic in the service; it answers 501 until then.`,
      )
    }
  }
  const storage =
    settings.persistence === 'memory'
      ? 'Data is kept in memory while the application runs and is lost when it stops. Write another implementation of each repository interface and mark it as the one to use.'
      : settings.persistence === 'none'
        ? 'Storage is left to you: each repository is an interface whose methods answer 501 until you implement them.'
        : `JPA with Hibernate on ${settings.database}. Hibernate creates missing tables while you develop (\`spring.jpa.hibernate.ddl-auto=update\`); for a real database, use migrations (Model2DB writes them). Embedded objects and lists are stored as JSON columns, and references as key columns.`
  const auth =
    settings.auth === 'none'
      ? 'Every endpoint is public.'
      : settings.auth === 'apiKey'
        ? 'Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected.'
        : 'Protected endpoints need a bearer token issued by your identity provider, signed with HS256. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens.'
  const pkg = settings.javaPackage.replace(/\./g, '/')
  const layout =
    settings.architecture === 'modular'
      ? [
          `src/main/java/${pkg}/`,
          '  common/               errors, lists and request bodies',
          '  shared/               enums and embedded objects',
          '  <resource>/           model, request and response, repository, service and controller of one resource',
        ]
      : [
          `src/main/java/${pkg}/`,
          '  common/               errors, lists and request bodies',
          '  model/                domain classes, enums and embedded objects',
          '  dto/                  request bodies and responses',
          '  repository/           storage',
          '  service/              rules of each resource',
          '  controller/           HTTP routes',
        ]
  const content = lines(
    `# ${spec.title}`,
    '',
    'REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Spring Boot. It is a starting point: review it before using it in production.',
    '',
    '## Run it',
    '',
    'Requires Java 21 and Maven 3.9 or later.',
    '',
    '```bash',
    'mvn spring-boot:run',
    '```',
    '',
    'Set the variables of `.env.example` in your environment first. The API listens on http://localhost:8080; the interactive documentation is at http://localhost:8080/swagger-ui.html, and the contract in `openapi.yaml`.',
    '',
    '## Test it',
    '',
    '```bash',
    'mvn test',
    '```',
    '',
    context.jpa
      ? 'The tests use an in-memory H2 database, or the one in `TEST_DATABASE_URL` (with `TEST_DATABASE_USER` and `TEST_DATABASE_PASSWORD`).'
      : false,
    '',
    '## Endpoints',
    '',
    '| Method | Path | What it does | Success | Access |',
    '|---|---|---|---|---|',
    endpointRows(spec.resources),
    '',
    'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
    '',
    '## Storage',
    '',
    storage,
    '',
    '## Authentication',
    '',
    auth,
    '',
    '## Structure',
    '',
    '```text',
    layout,
    'src/test/java/          one test class per resource',
    'openapi.yaml            the contract of the API',
    '```',
    '',
    '## Left to you',
    '',
    pending.length > 0 ? pending : '- Nothing marked: review the generated code before using it.',
  )
  return { path: 'README.md', content: fileText(content) }
}
