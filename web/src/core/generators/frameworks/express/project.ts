/**
 * Project files of the Express project: package.json with its scripts, the TypeScript and Vitest
 * configuration, the environment example, ignore rules and the README.
 */
import type { SpecResource } from '../../../api/spec.ts'
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import type { ExpressContext } from './context.ts'

export function packageFile(context: ExpressContext): GeneratedFile {
  const jwt = context.settings.auth === 'jwt'
  const dependencies: Record<string, string> = { express: '^5.1.0', zod: '^4.1.0', ...(jwt ? { jsonwebtoken: '^9.0.2' } : {}) }
  const devDependencies: Record<string, string> = {
    '@types/express': '^5.0.3',
    '@types/node': '^24.0.0',
    '@types/supertest': '^6.0.3',
    ...(jwt ? { '@types/jsonwebtoken': '^9.0.10' } : {}),
    supertest: '^7.1.0',
    tsx: '^4.20.0',
    typescript: '~6.0.3',
    vitest: '^4.1.0',
  }
  const manifest = {
    name: context.settings.name,
    version: '0.1.0',
    private: true,
    description: 'REST API generated by Model2API',
    type: 'module',
    engines: { node: '>=22' },
    scripts: {
      dev: 'tsx watch --env-file-if-exists=.env src/server.ts',
      build: 'tsc -p tsconfig.build.json',
      start: 'node --env-file-if-exists=.env dist/server.js',
      typecheck: 'tsc --noEmit',
      test: 'vitest run',
    },
    dependencies,
    devDependencies,
  }
  return { path: 'package.json', content: fileText(JSON.stringify(manifest, null, 2)) }
}

export function tsconfigFiles(): GeneratedFile[] {
  const base = {
    compilerOptions: {
      target: 'ES2023',
      module: 'NodeNext',
      moduleResolution: 'NodeNext',
      strict: true,
      esModuleInterop: true,
      skipLibCheck: true,
      forceConsistentCasingInFileNames: true,
      noEmit: true,
    },
    include: ['src', 'tests'],
  }
  const build = { extends: './tsconfig.json', compilerOptions: { noEmit: false, outDir: 'dist', rootDir: 'src' }, include: ['src'] }
  return [
    { path: 'tsconfig.json', content: fileText(JSON.stringify(base, null, 2)) },
    { path: 'tsconfig.build.json', content: fileText(JSON.stringify(build, null, 2)) },
  ]
}

export function vitestConfigFile(): GeneratedFile {
  const content = lines(
    '/** Test configuration: the environment of the tests is set before any of them runs. */',
    "import { defineConfig } from 'vitest/config'",
    '',
    'export default defineConfig({',
    "  test: { setupFiles: ['tests/setup.ts'] },",
    '})',
  )
  return { path: 'vitest.config.ts', content: fileText(content) }
}

export function envExampleFile(context: ExpressContext): GeneratedFile {
  const { auth } = context.settings
  const content = lines(
    '# Copy this file to .env and fill in your own values. Never commit .env.',
    '',
    '# Port the API listens on',
    'PORT=3000',
    auth === 'apiKey' && ['', '# Accepted API keys, separated by commas. Use long random values.', 'API_KEYS='],
    auth === 'jwt' && [
      '',
      '# Secret that signs the tokens of your identity provider. Without it every protected request is rejected.',
      'JWT_SECRET=',
      'JWT_ALGORITHM=HS256',
      '# Optional: expected audience and issuer of the tokens',
      'JWT_AUDIENCE=',
      'JWT_ISSUER=',
    ],
  )
  return { path: '.env.example', content: fileText(content) }
}

export function gitignoreFile(): GeneratedFile {
  return { path: '.gitignore', content: fileText(lines('node_modules/', 'dist/', 'coverage/', '.env', '*.log', '.DS_Store')) }
}

function endpointRows(resources: SpecResource[]): string[] {
  return resources.flatMap((resource) =>
    resource.endpoints.map((endpoint) => {
      const access = endpoint.access === 'roles' ? `roles: ${endpoint.roles.join(', ')}` : endpoint.access
      return `| \`${endpoint.method}\` | \`${endpoint.path}\` | ${endpoint.summary} | ${endpoint.status} | ${access} |`
    }),
  )
}

export function readmeFile(context: ExpressContext): GeneratedFile {
  const { settings, spec } = context
  const pending: string[] = []
  if (context.pending) pending.push('- Storage: every repository answers 501 until you write it (search for `TODO`).')
  for (const resource of spec.resources) {
    if (resource.todo) pending.push(`- ${resource.todo}`)
    for (const field of resource.fields) if (field.todo) pending.push(`- ${resource.name}: ${field.todo}`)
    for (const endpoint of resource.endpoints.filter((item) => item.operation === 'custom')) {
      pending.push(
        `- \`${endpoint.method} ${endpoint.path}\` (${endpoint.summary}): write its logic in the service; it answers 501 until then.`,
      )
    }
  }
  const storage =
    settings.persistence === 'memory'
      ? 'Data is kept in memory while the application runs and is lost when it stops. Write another implementation of each repository interface and use it in `src/app.ts`.'
      : 'Storage is left to you: each repository is an interface whose methods answer 501 until you implement them.'
  const auth =
    settings.auth === 'none'
      ? 'Every endpoint is public.'
      : settings.auth === 'apiKey'
        ? 'Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected.'
        : 'Protected endpoints need a bearer token issued by your identity provider. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens.'
  const layout =
    settings.architecture === 'modular'
      ? [
          'src/',
          '  app.ts, server.ts, config.ts, errors.ts, listing.ts',
          '  shared/schemas.ts     enums and embedded objects',
          '  <resource>/           schemas, repository, service and routes of one resource',
        ]
      : [
          'src/',
          '  app.ts, server.ts, config.ts, errors.ts, listing.ts',
          '  schemas/              request and response shapes (Zod)',
          '  repositories/         storage',
          '  services/             rules of each resource',
          '  routes/               HTTP routes',
        ]
  const content = lines(
    `# ${spec.title}`,
    '',
    'REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Express and TypeScript. It is a starting point: review it before using it in production.',
    '',
    '## Run it',
    '',
    'Requires Node.js 22 or later.',
    '',
    '```bash',
    'npm install',
    'cp .env.example .env             # then fill in your values',
    'npm run dev',
    '```',
    '',
    'The API listens on http://localhost:3000. Its contract is in `openapi.yaml`. For production: `npm run build` and `npm start`.',
    '',
    '## Test it',
    '',
    '```bash',
    'npm test',
    'npm run typecheck',
    '```',
    '',
    '## Endpoints',
    '',
    '| Method | Path | What it does | Success | Access |',
    '|---|---|---|---|---|',
    endpointRows(spec.resources),
    '',
    'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
    '',
    '## Storage',
    '',
    storage,
    '',
    '## Authentication',
    '',
    auth,
    '',
    '## Structure',
    '',
    '```text',
    layout,
    'tests/                  one test file per resource',
    'openapi.yaml            the contract of the API',
    '```',
    '',
    '## Left to you',
    '',
    pending.length > 0 ? pending : '- Nothing marked: review the generated code before using it.',
  )
  return { path: 'README.md', content: fileText(content) }
}
