/**
 * Project files of the Ktor project: the Gradle build (Kotlin DSL), the logging configuration, the environment
 * example, ignore rules and the README.
 */
import type { SpecResource } from '../../../api/spec.ts'
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import { JDBC_URLS } from './common.ts'
import type { KtorContext } from './context.ts'

const KOTLIN_VERSION = '2.4.21'
const KTOR_VERSION = '3.6.0'
const EXPOSED_VERSION = '1.6.0'
const LOGBACK_VERSION = '1.6.5'
const HIKARI_VERSION = '7.0.2'
const H2_VERSION = '2.5.252'

const DRIVERS: Record<string, string> = {
  postgresql: 'org.postgresql:postgresql:42.7.13',
  mysql: 'com.mysql:mysql-connector-j:26.10.0',
  mariadb: 'org.mariadb.jdbc:mariadb-java-client:3.5.11',
  sqlite: 'org.xerial:sqlite-jdbc:3.53.4.0',
}

export function buildFiles(context: KtorContext): GeneratedFile[] {
  const { settings } = context
  const ktor = (artifact: string, scope = 'implementation') => `    ${scope}("io.ktor:${artifact}:$ktorVersion")`
  const exposed = (artifact: string) => `    implementation("org.jetbrains.exposed:${artifact}:$exposedVersion")`
  const build = lines(
    '// Gradle build of the API generated by Model2API.',
    'plugins {',
    `    kotlin("jvm") version "${KOTLIN_VERSION}"`,
    `    kotlin("plugin.serialization") version "${KOTLIN_VERSION}"`,
    '    application',
    '}',
    '',
    `group = "${settings.javaPackage}"`,
    'version = "0.1.0"',
    '',
    'application {',
    `    mainClass.set("${settings.javaPackage}.ApplicationKt")`,
    '}',
    '',
    'kotlin {',
    '    jvmToolchain(21)',
    '}',
    '',
    'repositories {',
    '    mavenCentral()',
    '}',
    '',
    `val ktorVersion = "${KTOR_VERSION}"`,
    context.exposed && `val exposedVersion = "${EXPOSED_VERSION}"`,
    '',
    'dependencies {',
    ktor('ktor-server-core'),
    ktor('ktor-server-netty'),
    ktor('ktor-server-content-negotiation'),
    ktor('ktor-serialization-kotlinx-json'),
    ktor('ktor-server-status-pages'),
    context.security && ktor('ktor-server-auth'),
    settings.auth === 'jwt' && ktor('ktor-server-auth-jwt'),
    `    implementation("ch.qos.logback:logback-classic:${LOGBACK_VERSION}")`,
    context.exposed && [
      exposed('exposed-core'),
      exposed('exposed-jdbc'),
      exposed('exposed-java-time'),
      `    implementation("com.zaxxer:HikariCP:${HIKARI_VERSION}")`,
      `    implementation("${DRIVERS[settings.database ?? 'postgresql']}")`,
    ],
    '',
    ktor('ktor-server-test-host', 'testImplementation'),
    '    testImplementation(kotlin("test"))',
    context.exposed && settings.database !== 'sqlite' && `    testImplementation("com.h2database:h2:${H2_VERSION}")`,
    '}',
    '',
    'tasks.test {',
    '    useJUnitPlatform()',
    '}',
  )
  const settingsFile = lines(`rootProject.name = "${settings.name}"`)
  const logback = lines(
    '<configuration>',
    '    <appender name="STDOUT" class="ch.qos.logback.core.ConsoleAppender">',
    '        <encoder>',
    '            <pattern>%d{HH:mm:ss.SSS} %-5level %logger{36} - %msg%n</pattern>',
    '        </encoder>',
    '    </appender>',
    '    <root level="INFO">',
    '        <appender-ref ref="STDOUT"/>',
    '    </root>',
    '    <logger name="io.netty" level="WARN"/>',
    context.exposed && '    <logger name="com.zaxxer.hikari" level="WARN"/>',
    '</configuration>',
  )
  return [
    { path: 'build.gradle.kts', content: fileText(build) },
    { path: 'settings.gradle.kts', content: fileText(settingsFile) },
    { path: 'src/main/resources/logback.xml', content: fileText(logback) },
  ]
}

export function envExampleFile(context: KtorContext): GeneratedFile {
  const { auth, database } = context.settings
  const content = lines(
    '# Environment of the API. Export these variables (or set them in your IDE) before running it. Never commit real values.',
    '',
    '# Port the API listens on',
    'PORT=8080',
    context.exposed && [
      '',
      '# Database connection (JDBC)',
      `DATABASE_URL=${JDBC_URLS[database ?? 'postgresql']}`,
      database !== 'sqlite' && ['DATABASE_USER=api', 'DATABASE_PASSWORD=change-me'],
    ],
    auth === 'apiKey' && ['', '# Accepted API keys, separated by commas. Use long random values.', 'API_KEYS='],
    auth === 'jwt' && [
      '',
      '# Secret that signs the tokens of your identity provider (at least 32 bytes). Without it every protected request is rejected.',
      'JWT_SECRET=',
      '# Optional: expected audience and issuer of the tokens',
      'JWT_AUDIENCE=',
      'JWT_ISSUER=',
    ],
  )
  return { path: '.env.example', content: fileText(content) }
}

export function gitignoreFile(): GeneratedFile {
  return {
    path: '.gitignore',
    content: fileText(lines('build/', '.gradle/', '.kotlin/', '.idea/', '*.iml', '.vscode/', '.env', '*.db', '.DS_Store')),
  }
}

function endpointRows(resources: SpecResource[]): string[] {
  return resources.flatMap((resource) =>
    resource.endpoints.map((endpoint) => {
      const access = endpoint.access === 'roles' ? `roles: ${endpoint.roles.join(', ')}` : endpoint.access
      return `| \`${endpoint.method}\` | \`${endpoint.path}\` | ${endpoint.summary} | ${endpoint.status} | ${access} |`
    }),
  )
}

export function readmeFile(context: KtorContext): GeneratedFile {
  const { settings, spec } = context
  const pending: string[] = []
  if (context.pending) pending.push('- Storage: every repository answers 501 until you write it (search for `TODO`).')
  for (const resource of spec.resources) {
    if (resource.todo) pending.push(`- ${resource.todo}`)
    for (const field of resource.fields) if (field.todo) pending.push(`- ${resource.name}: ${field.todo}`)
    for (const endpoint of resource.endpoints.filter((item) => item.operation === 'custom')) {
      pending.push(
        `- \`${endpoint.method} ${endpoint.path}\` (${endpoint.summary}): write its logic in the service; it answers 501 until then.`,
      )
    }
  }
  const storage =
    settings.persistence === 'memory'
      ? 'Data is kept in memory while the application runs and is lost when it stops. Write another implementation of each repository interface and create it in `Application.kt`.'
      : settings.persistence === 'none'
        ? 'Storage is left to you: each repository is an interface whose functions answer 501 until you implement them.'
        : `Exposed on ${settings.database}. The application creates the tables that are missing when it starts, while you develop; for a real database, use migrations (Model2DB writes them). Embedded objects and lists are stored as JSON text, and references as key columns.`
  const auth =
    settings.auth === 'none'
      ? 'Every endpoint is public.'
      : settings.auth === 'apiKey'
        ? 'Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected.'
        : 'Protected endpoints need a bearer token issued by your identity provider, signed with HS256. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens.'
  const pkg = settings.javaPackage.replace(/\./g, '/')
  const layout =
    settings.architecture === 'modular'
      ? [
          `src/main/kotlin/${pkg}/`,
          '  Application.kt        entry point: wires storage, services and routes',
          '  common/               errors, request bodies, JSON, lists and settings',
          '  shared/               enums and embedded objects',
          '  <resource>/           model, request and response, repository, service and routes of one resource',
          context.exposed && '  database/             connection and tables',
          context.security && '  security/             authentication',
        ]
      : [
          `src/main/kotlin/${pkg}/`,
          '  Application.kt        entry point: wires storage, services and routes',
          '  common/               errors, request bodies, JSON, lists and settings',
          '  model/                domain classes, enums and embedded objects',
          '  dto/                  request bodies and responses',
          '  repository/           storage',
          '  service/              rules of each resource',
          '  routes/               HTTP routes',
          context.exposed && '  database/             connection and tables',
          context.security && '  security/             authentication',
        ]
  const content = lines(
    `# ${spec.title}`,
    '',
    'REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Ktor. It is a starting point: review it before using it in production.',
    '',
    '## Run it',
    '',
    'Requires Java 21 and Gradle 9 (or a Gradle wrapper: `gradle wrapper` creates one).',
    '',
    '```bash',
    'gradle run',
    '```',
    '',
    'Set the variables of `.env.example` in your environment first. The API listens on http://localhost:8080. Its contract is in `openapi.yaml`.',
    '',
    '## Test it',
    '',
    '```bash',
    'gradle test',
    '```',
    '',
    'Each test starts the application anew, so it starts with empty storage.',
    context.exposed &&
      `The tests use ${settings.database === 'sqlite' ? 'a new SQLite file' : 'a new in-memory H2 database'} for each test, or the ${settings.database} database in \`TEST_DATABASE_URL\` (with \`TEST_DATABASE_USER\` and \`TEST_DATABASE_PASSWORD\`; its tables are dropped before each test).`,
    '',
    '## Endpoints',
    '',
    '| Method | Path | What it does | Success | Access |',
    '|---|---|---|---|---|',
    endpointRows(spec.resources),
    '',
    'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
    '',
    '## Storage',
    '',
    storage,
    '',
    '## Authentication',
    '',
    auth,
    '',
    '## Structure',
    '',
    '```text',
    layout,
    'src/test/kotlin/         one test class per resource',
    'openapi.yaml             the contract of the API',
    '```',
    '',
    '## Left to you',
    '',
    pending.length > 0 ? pending : '- Nothing marked: review the generated code before using it.',
  )
  return { path: 'README.md', content: fileText(content) }
}
