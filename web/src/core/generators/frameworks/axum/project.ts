/**
 * Project files of the Axum project: the Cargo manifest, the environment example, ignore rules and the README.
 */
import type { SpecResource } from '../../../api/spec.ts'
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import { DATABASE_URLS } from './common.ts'
import type { AxumContext } from './context.ts'

/** The Rust release the project is written for (edition 2024, `let` chains). */
export const RUST_VERSION = '1.99'

/** The sqlx driver feature of SeaORM for each database. */
const SQLX: Record<string, string> = {
  postgresql: 'sqlx-postgres',
  mysql: 'sqlx-mysql',
  mariadb: 'sqlx-mysql',
  sqlite: 'sqlx-sqlite',
}

export function cargoFile(context: AxumContext): GeneratedFile {
  const { settings } = context
  // SQLite is always there: the tests run on a SQLite file when no TEST_DATABASE_URL is set
  const drivers = [...new Set([SQLX[settings.database ?? 'postgresql'], 'sqlx-sqlite'])]
  const seaOrmFeatures = ['runtime-tokio-rustls', ...drivers, 'macros', 'with-chrono', 'with-uuid', 'with-rust_decimal', 'with-json']
  const content = lines(
    '# Cargo manifest of the API generated by Model2API.',
    '[package]',
    `name = "${context.package}"`,
    'version = "0.1.0"',
    'edition = "2024"',
    `rust-version = "${RUST_VERSION}"`,
    'publish = false',
    '',
    '[dependencies]',
    'async-trait = "0.1"',
    'axum = "0.8.9"',
    'chrono = { version = "0.4", features = ["serde"] }',
    'fancy-regex = "0.19"',
    settings.auth === 'jwt' && 'jsonwebtoken = { version = "11", default-features = false, features = ["rust_crypto"] }',
    'rust_decimal = { version = "1", features = ["serde-float"] }',
    context.seaOrm && `sea-orm = { version = "2.0.4", features = [${seaOrmFeatures.map((item) => `"${item}"`).join(', ')}] }`,
    'serde = { version = "1", features = ["derive"] }',
    'serde_json = "1"',
    'serde_repr = "0.1"',
    'tokio = { version = "1", features = ["macros", "rt-multi-thread", "net", "sync"] }',
    'tower-http = { version = "0.6", features = ["catch-panic"] }',
    'tracing = "0.1"',
    'tracing-subscriber = "0.3"',
    'uuid = { version = "1", features = ["v4", "serde"] }',
    '',
    '[dev-dependencies]',
    settings.auth === 'jwt' && 'jsonwebtoken = { version = "11", default-features = false, features = ["rust_crypto"] }',
    'tower = { version = "0.5", features = ["util"] }',
    '',
    '[[test]]',
    'name = "api"',
    'path = "tests/api/main.rs"',
  )
  return { path: 'Cargo.toml', content: fileText(content) }
}

export function envExampleFile(context: AxumContext): GeneratedFile {
  const { auth, database } = context.settings
  const content = lines(
    '# Environment of the API. Export these variables before running it. Never commit real values.',
    '',
    '# Port the API listens on',
    'PORT=8080',
    context.seaOrm && ['', '# Database connection', `DATABASE_URL=${DATABASE_URLS[database ?? 'postgresql']}`],
    auth === 'apiKey' && ['', '# Accepted API keys, separated by commas. Use long random values.', 'API_KEYS='],
    auth === 'jwt' && [
      '',
      '# Secret that signs the tokens of your identity provider (at least 32 bytes). Without it every protected request is rejected.',
      'JWT_SECRET=',
      '# Optional: expected audience and issuer of the tokens',
      'JWT_AUDIENCE=',
      'JWT_ISSUER=',
    ],
  )
  return { path: '.env.example', content: fileText(content) }
}

export function gitignoreFile(): GeneratedFile {
  return { path: '.gitignore', content: fileText(lines('target/', '.idea/', '.vscode/', '.env', '*.db', '.DS_Store')) }
}

function endpointRows(resources: SpecResource[]): string[] {
  return resources.flatMap((resource) =>
    resource.endpoints.map((endpoint) => {
      const access = endpoint.access === 'roles' ? `roles: ${endpoint.roles.join(', ')}` : endpoint.access
      return `| \`${endpoint.method}\` | \`${endpoint.path}\` | ${endpoint.summary} | ${endpoint.status} | ${access} |`
    }),
  )
}

export function readmeFile(context: AxumContext): GeneratedFile {
  const { settings, spec } = context
  const pending: string[] = []
  if (context.pending) pending.push('- Storage: every repository answers 501 until you write it (search for `TODO`).')
  for (const resource of spec.resources) {
    if (resource.todo) pending.push(`- ${resource.todo}`)
    for (const field of resource.fields) if (field.todo) pending.push(`- ${resource.name}: ${field.todo}`)
    for (const endpoint of resource.endpoints.filter((item) => item.operation === 'custom')) {
      pending.push(
        `- \`${endpoint.method} ${endpoint.path}\` (${endpoint.summary}): write its logic in the service; it answers 501 until then.`,
      )
    }
  }
  const storage =
    settings.persistence === 'memory'
      ? 'Data is kept in memory while the application runs and is lost when it stops. Write another implementation of each repository trait and create it in `src/lib.rs`.'
      : settings.persistence === 'none'
        ? 'Storage is left to you: each repository is a trait whose methods answer 501 until you implement them.'
        : `SeaORM on ${settings.database}. The application creates the tables that are missing when it starts, while you develop; for a real database, use migrations (Model2DB writes them). Embedded objects and lists are stored as JSON text, and references as key columns.`
  const auth =
    settings.auth === 'none'
      ? 'Every endpoint is public.'
      : settings.auth === 'apiKey'
        ? 'Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected.'
        : 'Protected endpoints need a bearer token issued by your identity provider, signed with HS256. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens.'
  const layout =
    settings.architecture === 'modular'
      ? [
          'src/',
          '  main.rs               entry point: reads the settings and serves the API',
          '  lib.rs                state and router: wires storage, services and routes',
          '  common/               errors, request bodies, lists, query strings and settings',
          '  shared/               enums and embedded objects',
          '  <resource>/           model, request and response, repository, service and routes of one resource',
          context.seaOrm && '  database.rs           connection and tables',
          context.security && '  security.rs           authentication',
        ]
      : [
          'src/',
          '  main.rs               entry point: reads the settings and serves the API',
          '  lib.rs                state and router: wires storage, services and routes',
          '  common/               errors, request bodies, lists, query strings and settings',
          '  models/               domain types, enums and embedded objects',
          '  dtos/                 request bodies and responses',
          '  repositories/         storage',
          context.seaOrm && '  entities/             tables, as SeaORM entities',
          '  services/             rules of each resource',
          '  routes/               HTTP routes',
          context.seaOrm && '  database.rs           connection and tables',
          context.security && '  security.rs           authentication',
        ]
  const content = lines(
    `# ${spec.title}`,
    '',
    'REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Axum. It is a starting point: review it before using it in production.',
    '',
    '## Run it',
    '',
    `Requires Rust ${RUST_VERSION} or later.`,
    '',
    '```bash',
    'cargo run',
    '```',
    '',
    'Set the variables of `.env.example` in your environment first. The API listens on http://localhost:8080. Its contract is in `openapi.yaml`.',
    '',
    '## Test it',
    '',
    '```bash',
    'cargo test',
    '```',
    '',
    'Each test builds the application anew, so it starts with empty storage.',
    context.seaOrm &&
      `The tests use a new SQLite file for each test, or the ${settings.database} database in \`TEST_DATABASE_URL\` (its tables are dropped before each test, and the tests take turns).`,
    '',
    '## Endpoints',
    '',
    '| Method | Path | What it does | Success | Access |',
    '|---|---|---|---|---|',
    endpointRows(spec.resources),
    '',
    'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
    '',
    '## Storage',
    '',
    storage,
    '',
    '## Authentication',
    '',
    auth,
    '',
    '## Structure',
    '',
    '```text',
    layout,
    'tests/api/               one test module per resource',
    'openapi.yaml             the contract of the API',
    '```',
    '',
    '## Left to you',
    '',
    pending.length > 0 ? pending : '- Nothing marked: review the generated code before using it.',
  )
  return { path: 'README.md', content: fileText(content) }
}
