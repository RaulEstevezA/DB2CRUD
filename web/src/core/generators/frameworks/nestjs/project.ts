const DRIVERS: Record<string, Record<string, string>> = {
  postgresql: { pg: '^8.13.0' },
  mysql: { mysql2: '^3.12.0' },
  mariadb: { mysql2: '^3.12.0' },
}

const URLS: Record<string, string> = {
  postgresql: 'postgres://api:change-me@localhost:5432/api',
  mysql: 'mysql://api:change-me@localhost:3306/api',
  mariadb: 'mysql://api:change-me@localhost:3306/api',
}

export function packageFile(context: NestContext): GeneratedFile {
  const { auth, database } = context.settings
  const dependencies: Record<string, string> = {
    '@nestjs/common': '^11.1.0',
    '@nestjs/core': '^11.1.0',
    '@nestjs/platform-express': '^11.1.0',
    'class-transformer': '^0.5.1',
    'class-validator': '^0.14.2',
    'reflect-metadata': '^0.2.2',
    rxjs: '^7.8.1',
    ...(auth === 'jwt' ? { jsonwebtoken: '^9.0.2' } : {}),
    ...(context.typeorm ? { '@nestjs/typeorm': '^11.0.0', typeorm: '^0.3.25', ...DRIVERS[database ?? 'postgresql'] } : {}),
  }
  const devDependencies: Record<string, string> = {
    '@nestjs/testing': '^11.1.0',
    '@types/express': '^5.0.3',
    '@types/jest': '^29.5.14',
    '@types/node': '^24.0.0',
    '@types/supertest': '^6.0.3',
    ...(auth === 'jwt' ? { '@types/jsonwebtoken': '^9.0.10' } : {}),
    ...(context.typeorm ? { 'sql.js': '^1.13.0' } : {}),
    jest: '^29.7.0',
    supertest: '^7.1.0',
    'ts-jest': '^29.4.0',
    'ts-node': '^10.9.2',
    typescript: '~5.9.0',
  }
  const manifest = {
    name: context.settings.name,
    version: '0.1.0',
    private: true,
    description: 'REST API generated by Model2API',
    engines: { node: '>=22' },
    scripts: {
      build: 'tsc -p tsconfig.build.json',
      start: 'node dist/main.js',
      dev: 'ts-node src/main.ts',
      typecheck: 'tsc --noEmit',
      // With a database, test files take turns: each one recreates the schema
      test: context.typeorm ? 'jest --runInBand' : 'jest',
    },
    dependencies,
    devDependencies,
    jest: {
      rootDir: '.',
      testRegex: 'test/.*\\.e2e-spec\\.ts$',
      transform: { '^.+\\.ts$': 'ts-jest' },
      testEnvironment: 'node',
      setupFiles: ['<rootDir>/test/setup.ts'],
    },
  }
  return { path: 'package.json', content: fileText(JSON.stringify(manifest, null, 2)) }
}

export function tsconfigFiles(): GeneratedFile[] {
  const base = {
    compilerOptions: {
      module: 'commonjs',
      target: 'ES2023',
      strict: true,
      experimentalDecorators: true,
      emitDecoratorMetadata: true,
      esModuleInterop: true,
      skipLibCheck: true,
      strictPropertyInitialization: false,
      noEmit: true,
    },
    include: ['src', 'test'],
  }
  const build = { extends: './tsconfig.json', compilerOptions: { noEmit: false, outDir: 'dist', rootDir: 'src' }, include: ['src'] }
  return [
    { path: 'tsconfig.json', content: fileText(JSON.stringify(base, null, 2)) },
    { path: 'tsconfig.build.json', content: fileText(JSON.stringify(build, null, 2)) },
  ]
}

export function envExampleFile(context: NestContext): GeneratedFile {
  const { auth, database } = context.settings
  const content = lines(
    '# Environment of the API. Export these variables before running it. Never commit real values.',
    '',
    '# Port the API listens on',
    'PORT=3000',
    context.typeorm && [
      '',
      '# Database connection',
      `DATABASE_URL=${URLS[database ?? 'postgresql']}`,
      '# Set to false once you use migrations',
      'DATABASE_SYNCHRONIZE=true',
    ],
    auth === 'apiKey' && ['', '# Accepted API keys, separated by commas. Use long random values.', 'API_KEYS='],
    auth === 'jwt' && [
      '',
      '# Secret that signs the tokens of your identity provider. Without it every protected request is rejected.',
      'JWT_SECRET=',
      'JWT_ALGORITHM=HS256',
      'JWT_AUDIENCE=',
      'JWT_ISSUER=',
    ],
  )
  return { path: '.env.example', content: fileText(content) }
}

export function gitignoreFile(): GeneratedFile {
  return { path: '.gitignore', content: fileText(lines('node_modules/', 'dist/', 'coverage/', '.env', '*.log', '.DS_Store')) }
}

function endpointRows(resources: SpecResource[]): string[] {
  return resources.flatMap((resource) =>
    resource.endpoints.map((endpoint) => {
      const access = endpoint.access === 'roles' ? `roles: ${endpoint.roles.join(', ')}` : endpoint.access
      return `| \`${endpoint.method}\` | \`${endpoint.path}\` | ${endpoint.summary} | ${endpoint.status} | ${access} |`
    }),
  )
}

export function readmeFile(context: NestContext): GeneratedFile {
  const { settings, spec } = context
  const pending: string[] = []
  if (context.pending) pending.push('- Storage: every repository answers 501 until you write it (search for `TODO`).')
  for (const resource of spec.resources) {
    if (resource.todo) pending.push(`- ${resource.todo}`)
    for (const field of resource.fields) if (field.todo) pending.push(`- ${resource.name}: ${field.todo}`)
    for (const endpoint of resource.endpoints.filter((item) => item.operation === 'custom')) {
      pending.push(
        `- \`${endpoint.method} ${endpoint.path}\` (${endpoint.summary}): write its logic in the service; it answers 501 until then.`,
      )
    }
  }
  const storage =
    settings.persistence === 'memory'
      ? 'Data is kept in memory while the application runs and is lost when it stops. Bind another implementation of each repository token in its module to use a database.'
      : settings.persistence === 'none'
        ? 'Storage is left to you: each repository is an interface whose methods answer 501 until you implement them.'
        : `TypeORM on ${settings.database}. Tables are synchronized at startup while you develop (DATABASE_SYNCHRONIZE); for a real database, use migrations (Model2DB writes them). Dates are stored as ISO text and embedded objects and lists as JSON text, the same on every database. The tests use an in-memory SQLite (sql.js), or the database in TEST_DATABASE_URL.`
  const auth =
    settings.auth === 'none'
      ? 'Every endpoint is public.'
      : settings.auth === 'apiKey'
        ? 'Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected.'
        : 'Protected endpoints need a bearer token issued by your identity provider. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens.'
  const content = lines(
    `# ${spec.title}`,
    '',
    'REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with NestJS. It is a starting point: review it before using it in production.',
    '',
    '## Run it',
    '',
    'Requires Node.js 22 or later.',
    '',
    '```bash',
    'npm install',
    'npm run build',
    'npm start                        # with the variables of .env.example in your environment',
    '```',
    '',
    'The API listens on http://localhost:3000. Its contract is in `openapi.yaml`.',
    '',
    '## Test it',
    '',
    '```bash',
    'npm test',
    'npm run typecheck',
    '```',
    '',
    '## Endpoints',
    '',
    '| Method | Path | What it does | Success | Access |',
    '|---|---|---|---|---|',
    endpointRows(spec.resources),
    '',
    'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
    '',
    '## Storage',
    '',
    storage,
    '',
    '## Authentication',
    '',
    auth,
    '',
    '## Structure',
    '',
    '```text',
    'src/',
    '  main.ts, app.module.ts, app.setup.ts',
    '  common/               errors, validation, lists and authentication',
    '  shared/               enums and embedded objects',
    '  <resource>/           module, controller, service, repository and DTOs of one resource',
    'test/                   one end-to-end test file per resource',
    'openapi.yaml            the contract of the API',
    '```',
    '',
    '## Left to you',
    '',
    pending.length > 0 ? pending : '- Nothing marked: review the generated code before using it.',
  )
  return { path: 'README.md', content: fileText(content) }
}
