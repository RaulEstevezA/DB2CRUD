/**
 * Project files of the Vapor project: the Swift package manifest, the environment example, ignore rules and the
 * README.
 */
import type { SpecResource } from '../../../api/spec.ts'
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import { DATABASE_URLS } from './common.ts'
import type { VaporContext } from './context.ts'

/** The Swift release the project is written for. */
export const SWIFT_VERSION = '6.4'

interface Dependency {
  url: string
  from: string
  products: string[]
}

export function packageFile(context: VaporContext): GeneratedFile {
  const { settings } = context
  const database = settings.database ?? 'postgresql'
  const dependencies: Dependency[] = [{ url: 'https://github.com/vapor/vapor.git', from: '4.122.0', products: ['Vapor'] }]
  if (context.fluent) {
    dependencies.push({ url: 'https://github.com/vapor/fluent.git', from: '4.13.0', products: ['Fluent'] })
    // SQLite is always there: the tests run on a SQLite file when no TEST_DATABASE_URL is set
    dependencies.push({ url: 'https://github.com/vapor/fluent-sqlite-driver.git', from: '4.9.0', products: ['FluentSQLiteDriver'] })
    if (database === 'postgresql')
      dependencies.push({ url: 'https://github.com/vapor/fluent-postgres-driver.git', from: '2.14.0', products: ['FluentPostgresDriver'] })
    if (database === 'mysql' || database === 'mariadb')
      dependencies.push({ url: 'https://github.com/vapor/fluent-mysql-driver.git', from: '4.8.0', products: ['FluentMySQLDriver'] })
  }
  if (settings.auth === 'jwt') dependencies.push({ url: 'https://github.com/vapor/jwt.git', from: '5.2.0', products: ['JWT'] })
  const packageOf = (url: string) => url.slice(url.lastIndexOf('/') + 1, -'.git'.length)
  const content = lines(
    `// swift-tools-version:6.0`,
    '// Swift package of the API generated by Model2API.',
    'import PackageDescription',
    '',
    'let package = Package(',
    `    name: "${settings.name}",`,
    '    platforms: [.macOS(.v13)],',
    '    dependencies: [',
    dependencies.map((item) => `        .package(url: "${item.url}", from: "${item.from}"),`),
    '    ],',
    '    targets: [',
    '        .executableTarget(',
    '            name: "App",',
    '            dependencies: [',
    dependencies.flatMap((item) =>
      item.products.map((product) => `                .product(name: "${product}", package: "${packageOf(item.url)}"),`),
    ),
    '            ]',
    '        ),',
    '        .testTarget(',
    '            name: "AppTests",',
    '            dependencies: [',
    '                .target(name: "App"),',
    '                .product(name: "VaporTesting", package: "vapor"),',
    '            ]',
    '        ),',
    '    ]',
    ')',
  )
  return { path: 'Package.swift', content: fileText(content) }
}

export function envExampleFile(context: VaporContext): GeneratedFile {
  const { auth, database } = context.settings
  const content = lines(
    '# Environment of the API. Export these variables before running it. Never commit real values.',
    '',
    '# Port the API listens on',
    'PORT=8080',
    context.fluent && ['', '# Database connection', `DATABASE_URL=${DATABASE_URLS[database ?? 'postgresql']}`],
    auth === 'apiKey' && ['', '# Accepted API keys, separated by commas. Use long random values.', 'API_KEYS='],
    auth === 'jwt' && [
      '',
      '# Secret that signs the tokens of your identity provider (at least 32 bytes). Without it every protected request is rejected.',
      'JWT_SECRET=',
      '# Optional: expected audience and issuer of the tokens',
      'JWT_AUDIENCE=',
      'JWT_ISSUER=',
    ],
  )
  return { path: '.env.example', content: fileText(content) }
}

export function gitignoreFile(): GeneratedFile {
  return {
    path: '.gitignore',
    content: fileText(lines('.build/', '.swiftpm/', 'Package.resolved', '.idea/', '.vscode/', '.env', '*.db', '.DS_Store')),
  }
}

function endpointRows(resources: SpecResource[]): string[] {
  return resources.flatMap((resource) =>
    resource.endpoints.map((endpoint) => {
      const access = endpoint.access === 'roles' ? `roles: ${endpoint.roles.join(', ')}` : endpoint.access
      return `| \`${endpoint.method}\` | \`${endpoint.path}\` | ${endpoint.summary} | ${endpoint.status} | ${access} |`
    }),
  )
}

export function readmeFile(context: VaporContext): GeneratedFile {
  const { settings, spec } = context
  const pending: string[] = []
  if (context.pending) pending.push('- Storage: every repository answers 501 until you write it (search for `TODO`).')
  for (const resource of spec.resources) {
    if (resource.todo) pending.push(`- ${resource.todo}`)
    for (const field of resource.fields) if (field.todo) pending.push(`- ${resource.name}: ${field.todo}`)
    for (const endpoint of resource.endpoints.filter((item) => item.operation === 'custom')) {
      pending.push(
        `- \`${endpoint.method} ${endpoint.path}\` (${endpoint.summary}): write its logic in the service; it answers 501 until then.`,
      )
    }
  }
  const storage =
    settings.persistence === 'memory'
      ? 'Data is kept in memory while the application runs and is lost when it stops. Write another implementation of each repository protocol and create it in `configure.swift`.'
      : settings.persistence === 'none'
        ? 'Storage is left to you: each repository is a protocol whose methods answer 501 until you implement them.'
        : `Fluent on ${settings.database}. The application runs the migrations that create the tables when it starts, while you develop; for a real database, use migrations you control (Model2DB writes them). Embedded objects and lists are stored as JSON text, references as key columns and decimals as doubles.`
  const auth =
    settings.auth === 'none'
      ? 'Every endpoint is public.'
      : settings.auth === 'apiKey'
        ? 'Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected.'
        : 'Protected endpoints need a bearer token issued by your identity provider, signed with HS256. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens.'
  const layout =
    settings.architecture === 'modular'
      ? [
          'Sources/App/',
          '  entrypoint.swift      entry point: reads the settings and serves the API',
          '  configure.swift       wires errors, storage, services and routes',
          '  Common/               errors, request bodies, JSON, lists, query strings and settings',
          '  Shared/               enums and embedded objects',
          '  <Resource>/           model, request and response, repository, service and routes of one resource',
          context.fluent && '  Database/             connection and migrations',
          context.security && '  Security/             authentication',
        ]
      : [
          'Sources/App/',
          '  entrypoint.swift      entry point: reads the settings and serves the API',
          '  configure.swift       wires errors, storage, services and routes',
          '  Common/               errors, request bodies, JSON, lists, query strings and settings',
          '  Models/               domain types, enums and embedded objects',
          '  DTOs/                 request bodies and responses',
          '  Repositories/         storage',
          context.fluent && '  Database/             tables (Fluent models and migrations) and connection',
          '  Services/             rules of each resource',
          '  Controllers/          HTTP routes',
          context.security && '  Security/             authentication',
        ]
  const content = lines(
    `# ${spec.title}`,
    '',
    'REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Vapor. It is a starting point: review it before using it in production.',
    '',
    '## Run it',
    '',
    `Requires Swift ${SWIFT_VERSION} or later.`,
    '',
    '```bash',
    'swift run',
    '```',
    '',
    'Set the variables of `.env.example` in your environment first. The API listens on http://localhost:8080. Its contract is in `openapi.yaml`.',
    '',
    '## Test it',
    '',
    '```bash',
    'swift test',
    '```',
    '',
    'Each test builds the application anew, so it starts with empty storage.',
    context.fluent &&
      `The tests use a new SQLite file for each test, or the ${settings.database} database in \`TEST_DATABASE_URL\` (its tables are dropped and created again before each test, and the tests take turns).`,
    '',
    '## Endpoints',
    '',
    '| Method | Path | What it does | Success | Access |',
    '|---|---|---|---|---|',
    endpointRows(spec.resources),
    '',
    'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
    '',
    '## Storage',
    '',
    storage,
    '',
    '## Authentication',
    '',
    auth,
    '',
    '## Structure',
    '',
    '```text',
    layout,
    'Tests/AppTests/          one test suite per resource',
    'openapi.yaml             the contract of the API',
    '```',
    '',
    '## Left to you',
    '',
    pending.length > 0 ? pending : '- Nothing marked: review the generated code before using it.',
  )
  return { path: 'README.md', content: fileText(content) }
}
