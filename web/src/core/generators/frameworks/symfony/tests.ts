/**
 * Tests of the Symfony project: the bootstrap, and a base test class on Symfony's WebTestCase with the same
 * helpers Laravel's tests have (postJson, getJson… answering with assertStatus and json), so the test data and
 * the tests of each resource are the ones every PHP framework shares (languages/php/tests.ts).
 */
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import { phpDoc } from '../../languages/php/php.ts'
import { resourceTestFile, testDataFile } from '../../languages/php/tests.ts'
import type { SymfonyContext } from './context.ts'

function bootstrapFile(context: SymfonyContext): GeneratedFile {
  const content = lines(
    '<?php',
    '',
    'use Symfony\\Component\\Dotenv\\Dotenv;',
    '',
    "require dirname(__DIR__).'/vendor/autoload.php';",
    '',
    "(new Dotenv())->bootEnv(dirname(__DIR__).'/.env');",
    context.doctrine && [
      '',
      '// TEST_DATABASE_URL (postgresql://, mysql://…) runs the tests on that database instead of SQLite in memory',
      "$url = getenv('TEST_DATABASE_URL');",
      "if (is_string($url) && $url !== '') {",
      "    $_SERVER['DATABASE_URL'] = $_ENV['DATABASE_URL'] = $url;",
      '}',
    ],
  )
  return { path: 'tests/bootstrap.php', content: fileText(content) }
}

function apiTestCaseFiles(context: SymfonyContext): GeneratedFile[] {
  const content = lines(
    '<?php',
    '',
    'namespace App\\Tests;',
    '',
    context.doctrine && 'use Doctrine\\ORM\\Tools\\SchemaTool;',
    'use Symfony\\Bundle\\FrameworkBundle\\KernelBrowser;',
    'use Symfony\\Bundle\\FrameworkBundle\\Test\\WebTestCase;',
    '',
    phpDoc('Base of the tests: a new application for each test, and helpers to call it with JSON.'),
    'abstract class ApiTestCase extends WebTestCase',
    '{',
    '    private KernelBrowser $client;',
    '',
    '    protected function setUp(): void',
    '    {',
    '        parent::setUp();',
    '        $this->client = static::createClient();',
    '        // One application for the whole test, so what a request stores the next one reads',
    '        $this->client->disableReboot();',
    context.doctrine && [
      "        $manager = static::getContainer()->get('doctrine.orm.entity_manager');",
      '        $metadata = $manager->getMetadataFactory()->getAllMetadata();',
      '        $tool = new SchemaTool($manager);',
      '        // Empty tables for each test',
      '        $tool->dropSchema($metadata);',
      '        $tool->createSchema($metadata);',
    ],
    '    }',
    '',
    '    /**',
    '     * Sends a request with a JSON body.',
    '     *',
    '     * @param  array<string, mixed>  $data',
    '     * @param  array<string, string>  $headers',
    '     */',
    '    protected function json(string $method, string $uri, array $data = [], array $headers = []): TestResponse',
    '    {',
    "        $server = ['CONTENT_TYPE' => 'application/json', 'HTTP_ACCEPT' => 'application/json'];",
    '        foreach ($headers as $name => $value) {',
    "            $server['HTTP_'.strtoupper(str_replace('-', '_', $name))] = $value;",
    '        }',
    '        $this->client->request($method, $uri, [], [], $server, json_encode($data, JSON_THROW_ON_ERROR));',
    '',
    '        return new TestResponse($this->client->getResponse());',
    '    }',
    '',
    '    /** @param array<string, string> $headers */',
    '    protected function getJson(string $uri, array $headers = []): TestResponse',
    '    {',
    "        return $this->json('GET', $uri, [], $headers);",
    '    }',
    '',
    '    /**',
    '     * @param  array<string, mixed>  $data',
    '     * @param  array<string, string>  $headers',
    '     */',
    '    protected function postJson(string $uri, array $data = [], array $headers = []): TestResponse',
    '    {',
    "        return $this->json('POST', $uri, $data, $headers);",
    '    }',
    '',
    '    /**',
    '     * @param  array<string, mixed>  $data',
    '     * @param  array<string, string>  $headers',
    '     */',
    '    protected function putJson(string $uri, array $data = [], array $headers = []): TestResponse',
    '    {',
    "        return $this->json('PUT', $uri, $data, $headers);",
    '    }',
    '',
    '    /**',
    '     * @param  array<string, mixed>  $data',
    '     * @param  array<string, string>  $headers',
    '     */',
    '    protected function patchJson(string $uri, array $data = [], array $headers = []): TestResponse',
    '    {',
    "        return $this->json('PATCH', $uri, $data, $headers);",
    '    }',
    '',
    '    /**',
    '     * @param  array<string, mixed>  $data',
    '     * @param  array<string, string>  $headers',
    '     */',
    '    protected function deleteJson(string $uri, array $data = [], array $headers = []): TestResponse',
    '    {',
    "        return $this->json('DELETE', $uri, $data, $headers);",
    '    }',
    '}',
  )
  const response = lines(
    '<?php',
    '',
    'namespace App\\Tests;',
    '',
    'use PHPUnit\\Framework\\Assert;',
    'use Symfony\\Component\\HttpFoundation\\Response;',
    '',
    phpDoc('The answer of a request in a test: its status, and its JSON body or a value inside it ("error.code").'),
    'final class TestResponse',
    '{',
    '    public function __construct(private readonly Response $response)',
    '    {',
    '    }',
    '',
    '    public function assertStatus(int $status): void',
    '    {',
    '        Assert::assertSame($status, $this->response->getStatusCode(), (string) $this->response->getContent());',
    '    }',
    '',
    '    public function json(?string $path = null): mixed',
    '    {',
    '        $value = json_decode((string) $this->response->getContent(), true);',
    "        foreach ($path === null ? [] : explode('.', $path) as $part) {",
    '            $value = is_array($value) ? ($value[$part] ?? null) : null;',
    '        }',
    '',
    '        return $value;',
    '    }',
    '}',
  )
  return [
    { path: 'tests/ApiTestCase.php', content: fileText(content) },
    { path: 'tests/TestResponse.php', content: fileText(response) },
  ]
}

export function testFiles(context: SymfonyContext): GeneratedFile[] {
  return [
    bootstrapFile(context),
    ...apiTestCaseFiles(context),
    testDataFile(context),
    ...context.spec.resources.map((resource) => resourceTestFile(context, resource)),
  ]
}
