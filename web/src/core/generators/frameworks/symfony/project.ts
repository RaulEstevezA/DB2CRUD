/**
 * Project files of the Symfony project: composer.json, the PHPUnit configuration, the environment files Symfony
 * reads (.env with safe defaults, .env.test for the tests), ignore rules and the README.
 */
import type { SpecResource } from '../../../api/spec.ts'
import { TEST_API_KEY, TEST_JWT_SECRET } from '../../common/testing.ts'
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import type { SymfonyContext } from './context.ts'

const SYMFONY_VERSION = '8.1.*'
const DOCTRINE_ORM_VERSION = '^3.7'
const DOCTRINE_BUNDLE_VERSION = '^3.3'
const JWT_VERSION = '^7.2'
const PHPUNIT_VERSION = '^12.5'

const DATABASE_URLS: Record<string, string> = {
  sqlite: 'sqlite:///%kernel.project_dir%/var/data.db',
  postgresql: 'postgresql://api:change-me@127.0.0.1:5432/api',
  mysql: 'mysql://api:change-me@127.0.0.1:3306/api',
  mariadb: 'mysql://api:change-me@127.0.0.1:3306/api',
}

export function composerFile(context: SymfonyContext): GeneratedFile {
  const { auth } = context.settings
  const require: Record<string, string> = {
    php: '>=8.4',
    ...(context.doctrine ? { 'doctrine/doctrine-bundle': DOCTRINE_BUNDLE_VERSION, 'doctrine/orm': DOCTRINE_ORM_VERSION } : {}),
    ...(auth === 'jwt' ? { 'firebase/php-jwt': JWT_VERSION } : {}),
    'symfony/console': SYMFONY_VERSION,
    'symfony/dotenv': SYMFONY_VERSION,
    'symfony/framework-bundle': SYMFONY_VERSION,
    'symfony/runtime': SYMFONY_VERSION,
    'symfony/uid': SYMFONY_VERSION,
    'symfony/validator': SYMFONY_VERSION,
    'symfony/yaml': SYMFONY_VERSION,
  }
  const manifest = {
    name: `model2api/${context.settings.name}`,
    type: 'project',
    description: 'REST API generated by Model2API',
    require,
    'require-dev': { 'phpunit/phpunit': PHPUNIT_VERSION, 'symfony/browser-kit': SYMFONY_VERSION },
    autoload: { 'psr-4': { 'App\\': 'src/' } },
    'autoload-dev': { 'psr-4': { 'App\\Tests\\': 'tests/' } },
    scripts: { test: ['@php vendor/bin/phpunit'] },
    config: { 'allow-plugins': { 'symfony/runtime': true }, 'sort-packages': true },
    'minimum-stability': 'stable',
    'prefer-stable': true,
  }
  return { path: 'composer.json', content: fileText(JSON.stringify(manifest, null, 4)) }
}

export function phpunitFile(): GeneratedFile {
  const content = lines(
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<phpunit xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
    '         xsi:noNamespaceSchemaLocation="vendor/phpunit/phpunit/phpunit.xsd"',
    '         bootstrap="tests/bootstrap.php"',
    '         colors="true"',
    '>',
    '    <php>',
    '        <server name="APP_ENV" value="test" force="true"/>',
    '        <server name="KERNEL_CLASS" value="App\\Kernel"/>',
    '    </php>',
    '    <testsuites>',
    '        <testsuite name="Api">',
    '            <directory>tests/Api</directory>',
    '        </testsuite>',
    '    </testsuites>',
    '    <source>',
    '        <include>',
    '            <directory>src</directory>',
    '        </include>',
    '    </source>',
    '</phpunit>',
  )
  return { path: 'phpunit.dist.xml', content: fileText(content) }
}

/** .env: defaults safe to commit, read by Symfony; real values go in .env.local or the environment. */
export function envFiles(context: SymfonyContext): GeneratedFile[] {
  const { auth, database } = context.settings
  const env = lines(
    '# Defaults of the API, safe to commit. Put real values in .env.local (not committed) or in the environment.',
    'APP_ENV=dev',
    'APP_SECRET=change-me',
    context.doctrine && ['', '# Database connection', `DATABASE_URL="${DATABASE_URLS[database ?? 'postgresql']}"`],
    auth === 'apiKey' && ['', '# Accepted API keys, separated by commas. Use long random values.', 'API_KEYS='],
    auth === 'jwt' && [
      '',
      '# Secret that signs the tokens of your identity provider. Without it every protected request is rejected.',
      'JWT_SECRET=',
      'JWT_ALGORITHM=HS256',
      '# Optional: expected audience and issuer of the tokens',
      'JWT_AUDIENCE=',
      'JWT_ISSUER=',
    ],
  )
  const test = lines(
    '# Settings of the tests',
    'APP_SECRET=test-secret',
    context.doctrine && [
      '# An in-memory SQLite database, or the database in TEST_DATABASE_URL (tests/bootstrap.php)',
      'DATABASE_URL="sqlite:///:memory:"',
    ],
    auth === 'apiKey' && `API_KEYS=${TEST_API_KEY}`,
    auth === 'jwt' && [`JWT_SECRET=${TEST_JWT_SECRET}`, 'JWT_AUDIENCE=', 'JWT_ISSUER='],
  )
  return [
    { path: '.env', content: fileText(env) },
    { path: '.env.test', content: fileText(test) },
  ]
}

export function gitignoreFile(): GeneratedFile {
  return {
    path: '.gitignore',
    content: fileText(lines('/vendor/', '/var/', '.env.local', '.env.*.local', '.phpunit.cache/', '*.log', '.DS_Store')),
  }
}

function endpointRows(resources: SpecResource[]): string[] {
  return resources.flatMap((resource) =>
    resource.endpoints.map((endpoint) => {
      const access = endpoint.access === 'roles' ? `roles: ${endpoint.roles.join(', ')}` : endpoint.access
      return `| \`${endpoint.method}\` | \`${endpoint.path}\` | ${endpoint.summary} | ${endpoint.status} | ${access} |`
    }),
  )
}

export function readmeFile(context: SymfonyContext): GeneratedFile {
  const { settings, spec } = context
  const pending: string[] = []
  if (context.pending) pending.push('- Storage: every repository answers 501 until you write it (search for `TODO`).')
  for (const resource of spec.resources) {
    if (resource.todo) pending.push(`- ${resource.todo}`)
    for (const field of resource.fields) if (field.todo) pending.push(`- ${resource.name}: ${field.todo}`)
    for (const endpoint of resource.endpoints.filter((item) => item.operation === 'custom')) {
      pending.push(
        `- \`${endpoint.method} ${endpoint.path}\` (${endpoint.summary}): write its logic in the service; it answers 501 until then.`,
      )
    }
  }
  const storage =
    settings.persistence === 'memory'
      ? 'Data is kept in memory while the application runs and is lost when it stops. Write another implementation of each repository interface and point the interface to it in `config/services.yaml`.'
      : settings.persistence === 'none'
        ? 'Storage is left to you: each repository is an interface whose methods answer 501 until you implement them.'
        : `Doctrine ORM on ${settings.database}. \`php bin/console doctrine:schema:create\` creates the tables while you develop; for a real database, use migrations (Model2DB writes them). Embedded objects and lists are stored as JSON columns, and references as key columns.`
  const auth =
    settings.auth === 'none'
      ? 'Every endpoint is public.'
      : settings.auth === 'apiKey'
        ? 'Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected.'
        : 'Protected endpoints need a bearer token issued by your identity provider. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens.'
  const layout =
    settings.architecture === 'modular'
      ? [
          'src/',
          '  <Resource>/            controller, input, response, service, repository and entity of one resource',
          '  Shared/                enums',
          '  Controller/, EventSubscriber/, Exception/, Http/, Security/, Support/   what every resource shares',
        ]
      : [
          'src/',
          '  Controller/            HTTP routes of each resource',
          '  Input/                 request bodies and their constraints',
          '  Presenter/             responses',
          '  Service/               rules of each resource',
          '  Repository/            storage',
          context.doctrine && '  Entity/                Doctrine entities',
          '  Enum/                  enums',
        ]
  const content = lines(
    `# ${spec.title}`,
    '',
    'REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Symfony. It is a starting point: review it before using it in production.',
    '',
    '## Run it',
    '',
    'Requires PHP 8.4 or later and Composer 2.',
    '',
    '```bash',
    'composer install',
    'cp .env .env.local                 # then fill in your values in .env.local',
    context.doctrine && 'php bin/console doctrine:schema:create',
    'php -S localhost:8000 -t public',
    '```',
    '',
    'The API listens on http://localhost:8000. Its contract is in `openapi.yaml`.',
    '',
    '## Test it',
    '',
    '```bash',
    'composer test',
    '```',
    '',
    context.doctrine
      ? 'The tests use an in-memory SQLite database, or the one in `TEST_DATABASE_URL` (`postgresql://` or `mysql://`).'
      : false,
    '',
    '## Endpoints',
    '',
    '| Method | Path | What it does | Success | Access |',
    '|---|---|---|---|---|',
    endpointRows(spec.resources),
    '',
    'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
    '',
    '## Storage',
    '',
    storage,
    '',
    '## Authentication',
    '',
    auth,
    '',
    '## Structure',
    '',
    '```text',
    layout,
    'config/                  bundles, packages, routes and services',
    'tests/Api/               one test class per resource',
    'openapi.yaml             the contract of the API',
    '```',
    '',
    '## Left to you',
    '',
    pending.length > 0 ? pending : '- Nothing marked: review the generated code before using it.',
  )
  return { path: 'README.md', content: fileText(content) }
}
