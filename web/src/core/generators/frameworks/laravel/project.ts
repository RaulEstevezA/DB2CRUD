/**
 * Project files of the Laravel project: composer.json, the PHPUnit configuration, the environment example,
 * ignore rules and the README.
 */
import type { SpecResource } from '../../../api/spec.ts'
import { TEST_API_KEY, TEST_JWT_SECRET } from '../../common/testing.ts'
import type { GeneratedFile } from '../../common/types.ts'
import { fileText, lines } from '../../common/text.ts'
import type { LaravelContext } from './context.ts'

const LARAVEL_VERSION = '^13.40'
const JWT_VERSION = '^7.2'
const PHPUNIT_VERSION = '^12.5'
const MOCKERY_VERSION = '^1.6'

const CONNECTIONS: Record<string, { connection: string; port?: number }> = {
  sqlite: { connection: 'sqlite' },
  postgresql: { connection: 'pgsql', port: 5432 },
  mysql: { connection: 'mysql', port: 3306 },
  mariadb: { connection: 'mariadb', port: 3306 },
}

export function composerFile(context: LaravelContext): GeneratedFile {
  const jwt = context.settings.auth === 'jwt'
  const manifest = {
    name: `model2api/${context.settings.name}`,
    type: 'project',
    description: 'REST API generated by Model2API',
    require: { php: '^8.3', ...(jwt ? { 'firebase/php-jwt': JWT_VERSION } : {}), 'laravel/framework': LARAVEL_VERSION },
    // RefreshDatabase runs the migrations through Artisan, which needs Mockery in tests
    'require-dev': { ...(context.eloquent ? { 'mockery/mockery': MOCKERY_VERSION } : {}), 'phpunit/phpunit': PHPUNIT_VERSION },
    autoload: { 'psr-4': { 'App\\': 'app/' } },
    'autoload-dev': { 'psr-4': { 'Tests\\': 'tests/' } },
    scripts: {
      'post-autoload-dump': ['Illuminate\\Foundation\\ComposerScripts::postAutoloadDump', '@php artisan package:discover --ansi'],
      test: ['@php vendor/bin/phpunit'],
    },
    config: { 'optimize-autoloader': true, 'preferred-install': 'dist', 'sort-packages': true },
    'minimum-stability': 'stable',
    'prefer-stable': true,
  }
  return { path: 'composer.json', content: fileText(JSON.stringify(manifest, null, 4)) }
}

export function phpunitFile(context: LaravelContext): GeneratedFile {
  const { auth } = context.settings
  const content = lines(
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<phpunit xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
    '         xsi:noNamespaceSchemaLocation="vendor/phpunit/phpunit/phpunit.xsd"',
    '         bootstrap="vendor/autoload.php"',
    '         colors="true"',
    '>',
    '    <testsuites>',
    '        <testsuite name="Feature">',
    '            <directory>tests/Feature</directory>',
    '        </testsuite>',
    '    </testsuites>',
    '    <source>',
    '        <include>',
    '            <directory>app</directory>',
    '        </include>',
    '    </source>',
    '    <!-- Settings of the tests; a variable already set in the environment wins -->',
    '    <php>',
    '        <env name="APP_ENV" value="testing"/>',
    '        <env name="CACHE_STORE" value="array"/>',
    '        <env name="SESSION_DRIVER" value="array"/>',
    context.eloquent && [
      '        <!-- An in-memory SQLite database, or the database in TEST_DATABASE_URL (tests/TestCase.php) -->',
      '        <env name="DB_CONNECTION" value="sqlite"/>',
      '        <env name="DB_DATABASE" value=":memory:"/>',
    ],
    auth === 'apiKey' && `        <env name="API_KEYS" value="${TEST_API_KEY}" force="true"/>`,
    auth === 'jwt' && [
      `        <env name="JWT_SECRET" value="${TEST_JWT_SECRET}" force="true"/>`,
      '        <env name="JWT_AUDIENCE" value="" force="true"/>',
      '        <env name="JWT_ISSUER" value="" force="true"/>',
    ],
    '    </php>',
    '</phpunit>',
  )
  return { path: 'phpunit.xml', content: fileText(content) }
}

export function envExampleFile(context: LaravelContext): GeneratedFile {
  const { auth, database } = context.settings
  const connection = database ? CONNECTIONS[database] : null
  const content = lines(
    '# Copy this file to .env and fill in your own values. Never commit .env.',
    '',
    `APP_NAME=${context.settings.name}`,
    'APP_ENV=local',
    'APP_DEBUG=true',
    'APP_URL=http://localhost:8000',
    context.eloquent &&
      connection && [
        '',
        '# Database connection',
        `DB_CONNECTION=${connection.connection}`,
        connection.port
          ? ['DB_HOST=127.0.0.1', `DB_PORT=${connection.port}`, 'DB_DATABASE=api', 'DB_USERNAME=api', 'DB_PASSWORD=change-me']
          : '# The database is the file database/database.sqlite',
      ],
    auth === 'apiKey' && ['', '# Accepted API keys, separated by commas. Use long random values.', 'API_KEYS='],
    auth === 'jwt' && [
      '',
      '# Secret that signs the tokens of your identity provider. Without it every protected request is rejected.',
      'JWT_SECRET=',
      'JWT_ALGORITHM=HS256',
      '# Optional: expected audience and issuer of the tokens',
      'JWT_AUDIENCE=',
      'JWT_ISSUER=',
    ],
  )
  return { path: '.env.example', content: fileText(content) }
}

export function gitignoreFile(): GeneratedFile {
  return {
    path: '.gitignore',
    content: fileText(lines('/vendor/', '.env', '.phpunit.cache/', '.phpunit.result.cache', '/storage/*.key', '*.log', '.DS_Store')),
  }
}

function endpointRows(resources: SpecResource[]): string[] {
  return resources.flatMap((resource) =>
    resource.endpoints.map((endpoint) => {
      const access = endpoint.access === 'roles' ? `roles: ${endpoint.roles.join(', ')}` : endpoint.access
      return `| \`${endpoint.method}\` | \`${endpoint.path}\` | ${endpoint.summary} | ${endpoint.status} | ${access} |`
    }),
  )
}

export function readmeFile(context: LaravelContext): GeneratedFile {
  const { settings, spec } = context
  const pending: string[] = []
  if (context.pending) pending.push('- Storage: every repository answers 501 until you write it (search for `TODO`).')
  for (const resource of spec.resources) {
    if (resource.todo) pending.push(`- ${resource.todo}`)
    for (const field of resource.fields) if (field.todo) pending.push(`- ${resource.name}: ${field.todo}`)
    for (const endpoint of resource.endpoints.filter((item) => item.operation === 'custom')) {
      pending.push(
        `- \`${endpoint.method} ${endpoint.path}\` (${endpoint.summary}): write its logic in the service; it answers 501 until then.`,
      )
    }
  }
  const storage =
    settings.persistence === 'memory'
      ? 'Data is kept in memory while the application runs and is lost when it stops. Write another implementation of each repository interface and bind it in `app/Providers/AppServiceProvider.php`.'
      : settings.persistence === 'none'
        ? 'Storage is left to you: each repository is an interface whose methods answer 501 until you implement them.'
        : `Eloquent on ${settings.database}. The tables are created by the migration in \`database/migrations/\`; embedded objects and lists are stored as JSON columns, and references as key columns.`
  const auth =
    settings.auth === 'none'
      ? 'Every endpoint is public.'
      : settings.auth === 'apiKey'
        ? 'Protected endpoints need a key in the `X-API-Key` header, one of the comma-separated keys in `API_KEYS`. Without `API_KEYS`, every protected request is rejected.'
        : 'Protected endpoints need a bearer token issued by your identity provider. The API verifies it with `JWT_SECRET` (and `JWT_AUDIENCE` / `JWT_ISSUER` when set), requires an expiry, and reads the roles from the `roles` claim. It does not issue tokens.'
  const layout =
    settings.architecture === 'modular'
      ? [
          'app/',
          '  Modules/<Resource>/    controller, requests, response, service, repository and model of one resource',
          '  Modules/Shared/        enums',
          '  Exceptions/, Http/, Providers/, Rules/, Support/   what every resource shares',
        ]
      : [
          'app/',
          '  Http/Controllers/      HTTP routes of each resource',
          '  Http/Requests/         request bodies and their validation',
          '  Http/Resources/        responses',
          '  Services/              rules of each resource',
          '  Repositories/          storage',
          context.eloquent && '  Models/                Eloquent models',
          '  Enums/                 enums',
        ]
  const database = context.eloquent
    ? settings.database === 'sqlite'
      ? ['touch database/database.sqlite', 'php artisan migrate']
      : ['php artisan migrate                # after creating the database of .env']
    : []
  const content = lines(
    `# ${spec.title}`,
    '',
    'REST API generated by [Model2API](https://raulesteveza.github.io/tools/Model2API/) with Laravel. It is a starting point: review it before using it in production.',
    '',
    '## Run it',
    '',
    'Requires PHP 8.3 or later and Composer 2.',
    '',
    '```bash',
    'composer install',
    'cp .env.example .env               # then fill in your values',
    database,
    'php artisan serve',
    '```',
    '',
    'The API listens on http://localhost:8000. Its contract is in `openapi.yaml`.',
    '',
    '## Test it',
    '',
    '```bash',
    'composer test',
    '```',
    '',
    context.eloquent
      ? 'The tests use an in-memory SQLite database, or the one in `TEST_DATABASE_URL` (`postgresql://`, `mysql://` or `mariadb://`).'
      : false,
    '',
    '## Endpoints',
    '',
    '| Method | Path | What it does | Success | Access |',
    '|---|---|---|---|---|',
    endpointRows(spec.resources),
    '',
    'Errors always have the same body: `{"error": {"code": "...", "message": "...", "details": [...]}}`. Invalid requests answer 400.',
    '',
    '## Storage',
    '',
    storage,
    '',
    '## Authentication',
    '',
    auth,
    '',
    '## Structure',
    '',
    '```text',
    layout,
    'routes/api.php           every route and its protection',
    'tests/Feature/           one test class per resource',
    'openapi.yaml             the contract of the API',
    '```',
    '',
    '## Left to you',
    '',
    pending.length > 0 ? pending : '- Nothing marked: review the generated code before using it.',
  )
  return { path: 'README.md', content: fileText(content) }
}
