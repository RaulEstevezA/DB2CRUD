/**
 * The Rust generator: data access layers in asynchronous Rust with no web framework, over SeaORM, sqlx or the MongoDB driver, the strategy
 * (orm.ts) it is given. Every file of the project, composed from the modules of this folder; each module writes one kind of file. `src/lib.rs` and the
 * `mod.rs` of every folder are derived from the modules written, so each one is declared exactly once.
 */
import type { GeneratedFile } from '../../export/files.ts'
import type { Generator } from '../types.ts'
import { createContext, type Context, type Crate } from './context.ts'
import { dtoFile } from './dtos.ts'
import type { RustOrm } from './orm.ts'
import { cargoFile, contractFile, envExampleFile, gitignoreFile, readmeFile } from './project.ts'
import { repositoryFile } from './repositories.ts'
import { snakeName } from './rust.ts'
import { serviceFile } from './services.ts'
import { commonFile, errorsFile, unitOfWorkFile } from './support.ts'
import { canMake, testFiles } from './tests.ts'
import { planConversions } from '../../conversions/plan.ts'
import { conversionFiles, conversionTestFile, MODELS_FOLDER, modelsModule, servicePlans } from './conversions.ts'

function code(context: Context): GeneratedFile[] {
  const files: (GeneratedFile | null)[] = [
    ...context.orm.databaseFiles(context),
    errorsFile(context),
    commonFile(context),
    unitOfWorkFile(context),
  ]
  for (const info of context.tables) {
    if (info.writesEntity) files.push(...context.orm.entityFiles(context, info))
    files.push(repositoryFile(context, info))
    if (context.settings.services && info.service) {
      if (context.settings.serviceTypes === 'dtos') files.push(dtoFile(context, info))
      files.push(serviceFile(context, info))
    }
  }
  return files.filter((file): file is GeneratedFile => file !== null)
}

const FOLDERS: Record<string, string> = {
  conversions: 'The conversions between the application models and the tables.',
  repositories: 'The repositories of every table.',
  services: 'The services of every table.',
  dtos: 'What the services take and return.',
}

/** `lib.rs` and the `mod.rs` of every folder, declaring the modules of the files under `src/`. */
function moduleFiles(context: Context, files: GeneratedFile[], extra: string[] = []): GeneratedFile[] {
  const children = new Map<string, Set<string>>()
  for (const file of files) {
    if (!file.path.startsWith('src/')) continue
    const parts = file.path.slice(4).replace(/\.rs$/, '').split('/')
    for (let depth = 0; depth < parts.length; depth++) {
      const folder = parts.slice(0, depth).join('/')
      children.set(folder, (children.get(folder) ?? new Set()).add(parts[depth]))
    }
  }
  return [...children.entries()].map(([folder, names]) => {
    const declarations = [...names].sort().map((name) => `pub mod ${snakeName(name)};`)
    if (folder === '')
      return {
        path: 'src/lib.rs',
        content: [
          `//! ${context.settings.name}: the data access layer of the database, through ${context.orm.label}. Generated by DB2CRUD.`,
          '',
          ...declarations,
          ...extra,
          '',
        ].join('\n'),
      }
    const table = context.tables.find((info) => info.attr.replace(/^r#/, '') === folder)
    const doc =
      (folder === 'entities' ? context.orm.readme.folder : FOLDERS[folder]) ??
      (table ? `What works on the "${table.name}" table.` : 'The modules of this folder.')
    return { path: `src/${folder}/mod.rs`, content: [`//! ${doc}`, '', ...declarations, ''].join('\n') }
  })
}

/** The crates some files name: `chrono::NaiveDate`, `rust_decimal::Decimal`. */
const cratesOf = (files: GeneratedFile[]): Crate[] => [
  ...new Set(files.flatMap((file) => [...file.content.matchAll(/\b(chrono|rust_decimal|uuid)::/g)].map((match) => match[1] as Crate))),
]

/** The files with the database structs named as the strategy asks: `SqlUnitOfWork` is `MongoUnitOfWork` in a document database. */
function named(orm: RustOrm, files: GeneratedFile[]): GeneratedFile[] {
  const { prefix } = orm
  if (!prefix) return files
  const rename = (text: string) => text.replace(/\bSql(?=UnitOfWork\b|\w+Repository\b)/g, prefix)
  return files.map((file) => ({ ...file, content: rename(file.content) }))
}

export function rustGenerator(orm: RustOrm): Generator {
  return {
    language: 'rust',
    orm: orm.id,
    generate({ schema, design, settings, models }) {
      const context = createContext(orm, schema, design, settings)
      const plans = models ? servicePlans(context, planConversions(schema, design, models, orm.documents === true)) : []
      const conversions = models ? conversionFiles(context, models.schema, plans) : []
      const files = [...code(context), ...conversions]
      // With imported models, lib.rs declares the copy while the project runs on its own
      const imported = conversions.length > 0 && settings.modelsSource === 'import'
      const extra = imported
        ? [
            '',
            '// The application models: the copy DB2CRUD read, while the project runs on its own. Inside the application, delete',
            '// application-models/ and declare your module here.',
            `#[path = "../${MODELS_FOLDER}/mod.rs"]`,
            `pub mod ${modelsModule(context).split('::')[1]};`,
          ]
        : []
      const tests = testFiles(context)
      const conversionTests =
        models && tests.length > 0 && (settings.tests === 'all' || settings.tests === 'services')
          ? conversionTestFile(context, plans, models.schema, (info) => canMake(context, info))
          : null
      // The tests crate declares the module of the conversion tests
      const testCrate = conversionTests
        ? tests.map((file) => (file.path === 'tests/data/main.rs' ? { ...file, content: `${file.content}mod conversions;\n` } : file))
        : tests
      return named(orm, [
        readmeFile(context),
        cargoFile(context, cratesOf(conversions)),
        envExampleFile(context),
        gitignoreFile(),
        contractFile(context),
        ...files,
        ...moduleFiles(context, files, extra),
        ...testCrate,
        ...(conversionTests ? [conversionTests] : []),
      ])
    },
  }
}
