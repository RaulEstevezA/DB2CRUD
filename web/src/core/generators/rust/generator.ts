/**
 * The Rust generator: asynchronous Rust + SeaORM 2 data access layers, with no web framework. Every file of the
 * project, composed from the modules of this folder; each module writes one kind of file. `src/lib.rs` and the
 * `mod.rs` of every folder are derived from the modules written, so each one is declared exactly once.
 */
import type { GeneratedFile } from '../../export/files.ts'
import type { Generator } from '../types.ts'
import { createContext, type Context } from './context.ts'
import { dtoFile } from './dtos.ts'
import { entityFile, tableFile } from './entities.ts'
import { cargoFile, contractFile, envExampleFile, gitignoreFile, readmeFile } from './project.ts'
import { repositoryFile } from './repositories.ts'
import { snakeName } from './rust.ts'
import { serviceFile } from './services.ts'
import { commonFile, databaseFile, errorsFile, unitOfWorkFile } from './support.ts'
import { testFiles } from './tests.ts'

function code(context: Context): GeneratedFile[] {
  const files: (GeneratedFile | null)[] = [databaseFile(context), errorsFile(), commonFile(context), unitOfWorkFile(context)]
  for (const info of context.tables) {
    if (info.writesEntity) files.push(entityFile(context, info), tableFile(context, info))
    files.push(repositoryFile(context, info))
    if (context.settings.services && info.service) {
      if (context.settings.serviceTypes === 'dtos') files.push(dtoFile(context, info))
      files.push(serviceFile(context, info))
    }
  }
  return files.filter((file): file is GeneratedFile => file !== null)
}

const FOLDERS: Record<string, string> = {
  entities: 'The entities of every table, and the SeaORM description of each table.',
  repositories: 'The repositories of every table.',
  services: 'The services of every table.',
  dtos: 'What the services take and return.',
}

/** `lib.rs` and the `mod.rs` of every folder, declaring the modules of the files under `src/`. */
function moduleFiles(context: Context, files: GeneratedFile[]): GeneratedFile[] {
  const children = new Map<string, Set<string>>()
  for (const file of files) {
    if (!file.path.startsWith('src/')) continue
    const parts = file.path.slice(4).replace(/\.rs$/, '').split('/')
    for (let depth = 0; depth < parts.length; depth++) {
      const folder = parts.slice(0, depth).join('/')
      children.set(folder, (children.get(folder) ?? new Set()).add(parts[depth]))
    }
  }
  return [...children.entries()].map(([folder, names]) => {
    const declarations = [...names].sort().map((name) => `pub mod ${snakeName(name)};`)
    if (folder === '')
      return {
        path: 'src/lib.rs',
        content: [
          `//! ${context.settings.name}: the data access layer of the database, through SeaORM. Generated by DB2CRUD.`,
          '',
          ...declarations,
          '',
        ].join('\n'),
      }
    const table = context.tables.find((info) => info.attr.replace(/^r#/, '') === folder)
    const doc = FOLDERS[folder] ?? (table ? `What works on the "${table.name}" table.` : 'The modules of this folder.')
    return { path: `src/${folder}/mod.rs`, content: [`//! ${doc}`, '', ...declarations, ''].join('\n') }
  })
}

export const rustGenerator: Generator = {
  language: 'rust',
  orm: 'seaorm',
  generate({ schema, design, settings }) {
    const context = createContext(schema, design, settings)
    const files = code(context)
    return [
      readmeFile(context),
      cargoFile(context),
      envExampleFile(context),
      gitignoreFile(),
      contractFile(context),
      ...files,
      ...moduleFiles(context, files),
      ...testFiles(context),
    ]
  },
}
