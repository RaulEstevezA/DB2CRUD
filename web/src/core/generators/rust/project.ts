export const VERSIONS = {
  asyncTrait: '0.1.92',
  chrono: '0.4.45',
  rustDecimal: '1.43.0',
  uuid: '1.29.3',
  tokio: '1.54.1',
}

const tests = (context: Context) => context.settings.tests !== 'none' && writesEntities(context)

/** The crates the column types come from. */
function crates(context: Context): Set<Crate> {
  return new Set(
    context.tables
      .flatMap((info) => [...info.columns.map((column) => column.crate), ...nestedCrates(info.nested.values())])
      .filter((item): item is Crate => item !== null),
  )
}

/** Cargo.toml; `extra` are the crates the conversions and the copy of the application models name too. */
export function cargoFile(context: Context, extra: Crate[] = []): GeneratedFile {
  const used = new Set([...crates(context), ...extra])
  return {
    path: 'Cargo.toml',
    content: lines(
      '[package]',
      `name = "${context.settings.name}"`,
      'version = "0.1.0"',
      'edition = "2024"',
      '',
      '[dependencies]',
      `async-trait = "${VERSIONS.asyncTrait}"`,
      used.has('chrono') ? `chrono = { version = "${VERSIONS.chrono}", default-features = false, features = ["clock", "std"] }` : null,
      used.has('rust_decimal') ? `rust_decimal = "${VERSIONS.rustDecimal}"` : null,
      ...context.orm.dependencies(context, used),
      used.has('uuid') ? `uuid = { version = "${VERSIONS.uuid}", features = ["v4"] }` : null,
      tests(context) && [
        '',
        '[dev-dependencies]',
        `tokio = { version = "${VERSIONS.tokio}", features = ["macros", "rt-multi-thread", "sync"] }`,
      ],
      '',
    ),
  }
}

export function envExampleFile(context: Context): GeneratedFile {
  const sqlite = context.settings.database === 'sqlite'
  return {
    path: '.env.example',
    content: lines(
      '# Where the database is, and who connects',
      `DATABASE_URL=${defaultUrl(context)}`,
      sqlite
        ? '# The tests use SQLite in a new temporary file unless this names another database (it is emptied by the tests)'
        : '# The database the tests use (it is emptied by the tests): one of the same kind as DATABASE_URL',
      '# TEST_DATABASE_URL=',
      '',
    ),
  }
}

