function typeOf(context: Context, column: ColumnInfo): Record<string, unknown> {
  const { kind, ...rest } = plainType(column.column.type)
  return { kind, rust: storedType(column).replace(/\bcrate::/g, `${context.crate}::`), ...rest }
}

function plainType(type: DbType): Record<string, unknown> {
  // What a nested document, or each of a list of them, holds
  const fields = nestedFields(type)
  return {
    kind: type.kind,
    ...(type.kind === 'text' && type.length !== undefined ? { length: type.length } : {}),
    ...(fields ? { fields: fields.map((field) => ({ name: field.name, type: plainType(field.type), nullable: field.nullable })) } : {}),
  }
}

/** A module as other crates name it: `crate::entities` → `data_access::entities`. */
const crateModule = (context: Context, module: string) => module.replace(/^crate::/, `${context.crate}::`)

export function contractFile(context: Context): GeneratedFile {
  const dtos = context.settings.serviceTypes === 'dtos'
  const fields = (columns: ColumnInfo[], optional: boolean) =>
    columns.map((column) => ({ name: column.key, type: typeOf(context, column), nullable: optional || column.column.nullable }))
  const types = context.tables.flatMap((info) => {
    const result: Record<string, unknown>[] = [
      {
        name: info.entity,
        module: crateModule(context, moduleOf(context, info, 'entity')),
        kind: 'entity',
        fields: fields(info.columns, true),
      },
    ]
    const writes = info.role === 'entity' && info.service
    if (dtos && writes)
      result.push({
        name: createDto(info),
        module: crateModule(context, moduleOf(context, info, 'dtos')),
        kind: 'create',
        fields: fields(createColumns(info), true),
      })
    if (writes) {
      const path = updatePath(context, info)
      result.push({
        name: updateType(context, info),
        module: crateModule(context, path.slice(0, path.lastIndexOf('::'))),
        kind: 'update',
        updates: context.settings.updates,
        fields: fields(updateColumns(info), true),
      })
    }
    if (dtos && info.service)
      result.push({
        name: readDto(info),
        module: crateModule(context, moduleOf(context, info, 'dtos')),
        kind: 'read',
        fields: fields(readColumns(info), false),
      })
    return result
  })
  const errorsOf: Record<string, string> = { NotFound: 'notFound', Conflict: 'conflict', ValidationFailed: 'validation' }
  const errorsModule = `${context.crate}::errors`
  const services = context.tables
    .filter((info) => info.service)
    .map((info) => ({
      name: serviceType(info),
      module: crateModule(context, moduleOf(context, info, 'service')),
      ...serviceTarget(info, (column) => column.key),
      operations: info.operations.map((operation) => ({
        name: operationName(context, operation),
        kind: operation.kind,
        ...(operation.columns.length > 0
          ? { by: operation.columns, byFields: byFields(info.columns, operation.columns, (column) => column.key) }
          : {}),
        ...(operation.through ? { through: operation.through } : {}),
        errors: operation.errors.map((error) => errorsOf[error]),
      })),
    }))
  const contract = {
    format: 'crud-contract',
    version: 1,
    stack: { language: 'rust', orm: context.orm.id, database: context.settings.database, execution: 'async' },
    transactions: context.settings.transactions,
    paging: context.settings.paging,
    types,
    errors: [
      { kind: 'notFound', name: 'DomainError::NotFound', module: errorsModule },
      { kind: 'conflict', name: 'DomainError::Conflict', module: errorsModule },
      { kind: 'validation', name: 'DomainError::ValidationFailed', module: errorsModule },
    ],
    common: `${context.crate}::common`,
    services,
  }
  return { path: 'crud-contract.json', content: `${JSON.stringify(contract, null, 2)}\n` }
}
