/**
 * The files around the Java code: pom.xml (Java 21, Hibernate, the JDBC driver of the database, JUnit), the
 * README, an example environment, .gitignore and crud-contract.json, which describes what was written so
 * CRUD2Controller does not have to read the code back (docs/design.md, section 6).
 */
import type { GeneratedFile } from '../../export/files.ts'
