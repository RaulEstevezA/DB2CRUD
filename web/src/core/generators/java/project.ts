export function readmeFile(context: Context): GeneratedFile {
  const { settings } = context
  const sqlite = settings.database === 'sqlite'
  return {
    path: 'README.md',
    content: lines(
      `# ${settings.name}`,
      '',
      'Data access layer generated by [DB2CRUD](https://github.com/RaulEstevezA/DB2CRUD) for a database that already exists: JPA entities, repositories over an `EntityManager` (Hibernate) and services, in Java 21. It does not create or migrate the database, and it depends on no framework.',
      '',
      '## Settings',
      '',
      `- Database: ${settings.database}.`,
      `- Entities: ${settings.entities === 'missing' ? 'written for the tables the input had no class for' : settings.entities === 'all' ? 'written for every table' : `imported from \`${settings.entitiesModule}\``}.`,
      `- Services: ${settings.services ? `take and return ${settings.serviceTypes === 'dtos' ? `DTOs (${settings.dtoKind === 'class' ? 'classes' : 'records'})` : 'the entities'}; ${LABELS.updates[settings.updates]}` : 'not written'}.`,
      `- Transactions: ${LABELS.transactions[settings.transactions]}.`,
      `- Lists: ${LABELS.paging[settings.paging]}.`,
      '',
      '## Layout',
      '',
      '```text',
      `src/main/java/${context.base}/Database.java        the EntityManagerFactory of DATABASE_URL, with every entity`,
      `src/main/java/${context.base}/UnitOfWork.java      the repositories of every table, and the transaction of each operation`,
      `src/main/java/${context.base}/errors/              NotFoundException, ConflictException, ValidationFailedException: no HTTP codes`,
      settings.architecture === 'layer'
        ? [
            `src/main/java/${context.base}/entities/            one entity per table`,
            `src/main/java/${context.base}/repositories/        the repositories of each table`,
            settings.services && `src/main/java/${context.base}/services/            one service per table`,
          ]
        : `src/main/java/${context.base}/<table>/             entity, repositories and service of each table`,
      'src/test/java/                       repositories against a database, services on the in-memory repositories',
      'crud-contract.json                   what was written, for CRUD2Controller',
      '```',
      '',
      '## Running the tests',
      '',
      '```bash',
      sqlite ? 'mvn test                                          # SQLite in target/' : null,
      `TEST_DATABASE_URL=${URLS[settings.database]}${sqlite ? '' : ' TEST_DATABASE_USER=app TEST_DATABASE_PASSWORD=app'} mvn test   # a real, disposable database: it is emptied`,
      '```',
      '',
      '`Database.open()` uses the connection pool built into Hibernate, which is fine for trying the code; in production give `Database.configuration(...)` a `DataSource` or a pool such as HikariCP.',
      '',
      'Look for `TODO` in the code: each one marks a decision the input did not settle.',
      '',
    ),
  }
}

// crud-contract.json

function typeOf(column: ColumnInfo): Record<string, unknown> {
  const type = column.column.type
  return { kind: type.kind, java: column.java, ...(type.kind === 'text' && type.length !== undefined ? { length: type.length } : {}) }
}

export function contractFile(context: Context): GeneratedFile {
  const dtos = context.settings.serviceTypes === 'dtos'
  const fields = (columns: ColumnInfo[], optional: boolean) =>
    columns.map((column) => ({ name: column.prop, type: typeOf(column), nullable: optional || column.column.nullable }))
  const types = context.tables.flatMap((info) => {
    const entity = { name: info.entity, module: packageOf(context, info, 'entity'), kind: 'entity', fields: fields(info.columns, false) }
    const result: Record<string, unknown>[] = [entity]
    const writes = info.role === 'entity' && info.service
    if (dtos && info.service) {
      const module = packageOf(context, info, 'dtos')
      if (writes) result.push({ name: createDto(info), module, kind: 'create', fields: fields(createColumns(info), false) })
    }
    if (writes)
      result.push({
        name: updateType(context, info),
        module: updatePackage(context, info),
        kind: 'update',
        updates: context.settings.updates,
        fields: fields(updateColumns(info), true),
      })
    if (dtos && info.service)
      result.push({ name: readDto(info), module: packageOf(context, info, 'dtos'), kind: 'read', fields: fields(readColumns(info), false) })
    return result
  })
  const errorsOf: Record<string, string> = { NotFound: 'notFound', Conflict: 'conflict', ValidationFailed: 'validation' }
  const services = context.tables
    .filter((info) => info.service)
    .map((info) => ({
      name: serviceClass(info),
      module: packageOf(context, info, 'service'),
      operations: info.operations.map((operation) => ({
        name: operationName(context, operation),
        kind: operation.kind,
        ...(operation.columns.length > 0 ? { by: operation.columns } : {}),
        ...(operation.through ? { through: operation.through } : {}),
        errors: operation.errors.map((error) => errorsOf[error]),
      })),
    }))
  const contract = {
    format: 'crud-contract',
    version: 1,
    stack: { language: 'java', orm: 'jpa', database: context.settings.database, execution: 'sync' },
    transactions: context.settings.transactions,
    paging: context.settings.paging,
    types,
    errors: [
      { kind: 'notFound', name: 'NotFoundException', module: errorsPackage(context) },
      { kind: 'conflict', name: 'ConflictException', module: errorsPackage(context) },
      { kind: 'validation', name: 'ValidationFailedException', module: errorsPackage(context) },
    ],
    common: commonPackage(context),
    services,
  }
  return { path: 'crud-contract.json', content: `${JSON.stringify(contract, null, 2)}\n` }
}
