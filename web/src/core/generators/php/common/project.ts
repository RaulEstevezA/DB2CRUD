const VERSIONS = {
  php: '>=8.4',
  phpunit: '^12.4',
}

const tests = (context: Context) => context.settings.tests !== 'none' && writesEntities(context)

/**
 * composer.json; `modelsNamespace` when the copy of the imported application models is in application-models/:
 * Composer loads it for that namespace too, while the folder exists.
 */
export function composerFile(context: Context, modelsNamespace: string | null = null): GeneratedFile {
  const composer = {
    name: `app/${context.settings.name}`,
    description: `Data access layer generated by DB2CRUD (${context.orm.label})`,
    type: 'project',
    license: 'proprietary',
    require: { php: VERSIONS.php, 'ext-mbstring': '*', ...context.orm.require(context) },
    ...(tests(context) ? { 'require-dev': { 'phpunit/phpunit': VERSIONS.phpunit } } : {}),
    autoload: { 'psr-4': { 'App\\': 'src/', ...(modelsNamespace ? { [`${modelsNamespace}\\`]: 'application-models/' } : {}) } },
    ...(tests(context) ? { 'autoload-dev': { 'psr-4': { 'Tests\\': 'tests/' } } } : {}),
    ...(tests(context) ? { scripts: { test: 'phpunit' } } : {}),
    config: { 'sort-packages': true },
  }
  return { path: 'composer.json', content: `${JSON.stringify(composer, null, 4)}\n` }
}

export function phpunitFile(context: Context): GeneratedFile | null {
  if (!tests(context)) return null
  return {
    path: 'phpunit.xml',
    content: lines(
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<phpunit xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
      '         xsi:noNamespaceSchemaLocation="vendor/phpunit/phpunit/phpunit.xsd"',
      '         bootstrap="vendor/autoload.php"',
      '         cacheDirectory=".phpunit.cache"',
      '         failOnWarning="true"',
      '         colors="true">',
      '    <testsuites>',
      '        <testsuite name="all">',
      '            <directory>tests</directory>',
      '        </testsuite>',
      '    </testsuites>',
      '    <source>',
      '        <include>',
      '            <directory>src</directory>',
      '        </include>',
      '    </source>',
      '</phpunit>',
      '',
    ),
  }
}

