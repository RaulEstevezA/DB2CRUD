/**
 * The files around the code: dependencies for the chosen database, execution and DTOs, the pytest
 * settings, the README, an example environment, and `crud-contract.json`, which describes what was
 * written so CRUD2Controller does not have to read the code back (docs/design.md, section 6).
 */
import type { GeneratedFile } from '../../../export/files.ts'
import { lines } from '../../types.ts'
import { columnPyType, moduleOf, operationName, serviceClass, type Context } from './context.ts'
import { createDto, readDto, updateDto } from './dtos.ts'

export function requirementsFiles(context: Context): GeneratedFile[] {
  return [
    { path: 'requirements.txt', content: lines(...context.orm.dependencies(context), '') },
    { path: 'requirements-dev.txt', content: lines('-r requirements.txt', ...context.orm.devDependencies(context), '') },
  ]
}

export function pyprojectFile(context: Context): GeneratedFile {
  const quote = (items: string[]) => items.map((item) => `    "${item}",`)
  return {
    path: 'pyproject.toml',
    content: lines(
      '[project]',
      `name = "${context.settings.name}"`,
      'version = "0.1.0"',
      'description = "Data access layer (entities, repositories and services) generated by DB2CRUD."',
      'requires-python = ">=3.12"',
      'dependencies = [',
      ...quote(context.orm.dependencies(context)),
      ']',
      '',
      '[project.optional-dependencies]',
      'dev = [',
      ...quote(context.orm.devDependencies(context)),
      ']',
      '',
      '[tool.pytest.ini_options]',
      'testpaths = ["tests"]',
      'pythonpath = ["."]',
      ...context.orm.pytestOptions(context),
      '',
    ),
  }
}

export function envExampleFile(context: Context): GeneratedFile {
  return {
    path: '.env.example',
    content: lines(
      '# Where the database is. The synchronous driver is named here; the asynchronous one is chosen from it.',
      `DATABASE_URL=${context.orm.defaultUrl(context)}`,
      '# The tests use SQLite in a temporary file unless this names another database (it is emptied by the tests)',
      '# TEST_DATABASE_URL=',
      '',
    ),
  }
}

export function gitignoreFile(): GeneratedFile {
  return { path: '.gitignore', content: lines('__pycache__/', '*.py[cod]', '.venv/', '.pytest_cache/', '.env', '*.db', '') }
}

const LABELS = {
  transactions: {
    operation: 'one transaction per service operation, committed when it ends',
    caller: 'the caller owns the transaction: nothing commits',
    repository: 'every repository write is committed at once',
  },
  paging: {
    none: 'lists return every row',
    offset: 'lists return pages by offset and limit',
    cursor: 'lists return pages after a key (cursor)',
  },
}

export function readmeFile(context: Context): GeneratedFile {
  const { settings } = context
  return {
    path: 'README.md',
    content: lines(
      `# ${settings.name}`,
      '',
      'Data access layer generated by [DB2CRUD](https://github.com/RaulEstevezA/DB2CRUD) for a database that already exists: entities, repositories and services with ' +
        context.orm.label +
        '. It does not create or migrate the database.',
      '',
      '## Settings',
      '',
      `- Database: ${settings.database}; code: ${context.async ? 'asynchronous (AsyncSession)' : 'synchronous (Session)'}.`,
      `- Entities: ${settings.entities === 'missing' ? 'written for the tables the input had no class for' : settings.entities === 'all' ? 'written for every table' : `imported from \`${settings.entitiesModule}\``}.`,
      `- Services: ${settings.services ? `take and return ${settings.serviceTypes === 'dtos' ? `DTOs (${settings.dtoKind})` : 'the entities'}` : 'not written'}.`,
      `- Transactions: ${LABELS.transactions[settings.transactions]}.`,
      `- Lists: ${LABELS.paging[settings.paging]}.`,
      '',
      '## Layout',
      '',
      '```text',
      ...context.orm.layout(context),
      'app/errors.py          NotFoundError, ConflictError, ValidationFailedError: no HTTP codes',
      'app/unit_of_work.py    the repositories of every table, and the transaction of each operation',
      settings.architecture === 'layer'
        ? [
            'app/entities/          one entity per table',
            'app/repositories/      one repository per table',
            settings.services && 'app/services/          one service per table',
          ]
        : 'app/<table>/           entity, repository and service of each table',
      'tests/                 repositories against a database, services on the in-memory repositories',
      'crud-contract.json     what was written, for CRUD2Controller',
      '```',
      '',
      '## Running the tests',
      '',
      '```bash',
      'python -m venv .venv && source .venv/bin/activate',
      'pip install -r requirements-dev.txt',
      'python -m pytest                       # SQLite in a temporary file',
      `TEST_DATABASE_URL=${context.orm.defaultUrl(context)} python -m pytest   # a real, disposable database: it is emptied`,
      '```',
      '',
      'Look for `TODO` in the code: each one marks a decision the input did not settle.',
      '',
    ),
  }
}

// crud-contract.json

function typeOf(column: Parameters<typeof columnPyType>[0]): Record<string, unknown> {
  const type = column.column.type
  return { kind: type.kind, ...(type.kind === 'text' && type.length !== undefined ? { length: type.length } : {}) }
}

export function contractFile(context: Context): GeneratedFile {
  const dtos = context.settings.serviceTypes === 'dtos'
  const types = context.tables.flatMap((info) => {
    const fields = (columns: typeof info.columns, optional: boolean) =>
      columns.map((column) => ({ name: column.attr, type: typeOf(column), nullable: optional || column.column.nullable }))
    const entity = { name: info.entity, module: moduleOf(context, info, 'entity'), kind: 'entity', fields: fields(info.columns, false) }
    if (!dtos || !info.service) return [entity]
    const module = moduleOf(context, info, 'dtos')
    const read = {
      name: readDto(info),
      module,
      kind: 'read',
      fields: fields(
        info.columns.filter((column) => !info.hidden.includes(column.column.name)),
        false,
      ),
    }
    if (info.role !== 'entity') return [entity, read]
    return [
      entity,
      {
        name: createDto(info),
        module,
        kind: 'create',
        fields: fields(
          info.columns.filter((column) => !column.generated),
          false,
        ),
      },
      {
        name: updateDto(info),
        module,
        kind: 'update',
        fields: fields(
          info.columns.filter((column) => !column.generated && !info.key.includes(column)),
          true,
        ),
      },
      read,
    ]
  })
  const errorsOf: Record<string, string> = { NotFound: 'notFound', Conflict: 'conflict', ValidationFailed: 'validation' }
  const services = context.tables
    .filter((info) => info.service)
    .map((info) => ({
      name: serviceClass(info),
      module: moduleOf(context, info, 'service'),
      operations: info.operations.map((operation) => ({
        name: operationName(context, operation),
        kind: operation.kind,
        ...(operation.columns.length > 0 ? { by: operation.columns } : {}),
        ...(operation.through ? { through: operation.through } : {}),
        errors: operation.errors.map((error) => errorsOf[error]),
      })),
    }))
  const contract = {
    format: 'crud-contract',
    version: 1,
    stack: { language: 'python', orm: context.orm.id, database: context.settings.database, execution: context.settings.execution },
    transactions: context.settings.transactions,
    paging: context.settings.paging,
    types,
    errors: [
      { kind: 'notFound', name: 'NotFoundError', module: 'app.errors' },
      { kind: 'conflict', name: 'ConflictError', module: 'app.errors' },
      { kind: 'validation', name: 'ValidationFailedError', module: 'app.errors' },
    ],
    services,
  }
  return { path: 'crud-contract.json', content: `${JSON.stringify(contract, null, 2)}\n` }
}
