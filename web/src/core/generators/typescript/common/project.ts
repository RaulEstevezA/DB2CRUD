/**
 * The files around the code: `package.json` (an ES module, with typecheck, build and test scripts), the
 * TypeScript and Vitest settings, the README, an example environment, and `crud-contract.json`, which
 * describes what was written so CRUD2Controller does not have to read the code back (docs/design.md,
 * section 6). Mirrors python/common/project.ts.
 */
import type { GeneratedFile } from '../../../export/files.ts'
import { lines } from '../../types.ts'
import { moduleOf, operationName, serviceClass, writesEntities, type ColumnInfo, type Context } from './context.ts'
import { createDto, readDto, updateDto } from './dtos.ts'

const VERSIONS = {
  typescript: '^5.9.3',
  vitest: '^3.2.4',
  typesNode: '^24.10.0',
}

const sorted = (record: Record<string, string>) =>
  Object.fromEntries(Object.entries(record).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))

export function packageFile(context: Context): GeneratedFile {
  const tests = context.settings.tests !== 'none' && writesEntities(context)
  const content = {
    name: context.settings.name,
    version: '0.1.0',
    description: 'Data access layer (entities, repositories and services) generated by DB2CRUD.',
    private: true,
    type: 'module',
    engines: { node: '>=20' },
    scripts: {
      typecheck: 'tsc --noEmit',
      build: 'tsc -p tsconfig.build.json',
      test: tests ? 'vitest run' : 'echo "No tests: the project writes no entities, or the settings asked for none"',
      ...context.orm.scripts?.(context),
    },
    dependencies: sorted(context.orm.dependencies(context)),
    devDependencies: sorted({
      ...context.orm.devDependencies(context),
      '@types/node': VERSIONS.typesNode,
      typescript: VERSIONS.typescript,
      ...(tests ? { vitest: VERSIONS.vitest } : {}),
    }),
  }
  return { path: 'package.json', content: `${JSON.stringify(content, null, 2)}\n` }
}

export function tsconfigFiles(context: Context): GeneratedFile[] {
  const tests = context.settings.tests !== 'none' && writesEntities(context)
  const setup = context.orm.testSetup?.(context) ?? null
  const options = {
    target: 'ES2022',
    module: 'NodeNext',
    moduleResolution: 'NodeNext',
    lib: ['ES2022'],
    types: ['node'],
    strict: true,
    // The ORM's decorators; every column names its type, so no decorator metadata is needed
    experimentalDecorators: true,
    useDefineForClassFields: false,
    isolatedModules: true,
    skipLibCheck: true,
    noEmit: true,
  }
  return [
    {
      path: 'tsconfig.json',
      content: `${JSON.stringify({ compilerOptions: options, include: tests ? ['src', 'test'] : ['src'] }, null, 2)}\n`,
    },
    {
      path: 'tsconfig.build.json',
      content: `${JSON.stringify({ extends: './tsconfig.json', compilerOptions: { noEmit: false, rootDir: 'src', outDir: 'dist', declaration: true }, include: ['src'] }, null, 2)}\n`,
    },
    tests && {
      path: 'vitest.config.ts',
      content: lines(
        "import { defineConfig } from 'vitest/config'",
        '',
        'export default defineConfig({',
        '  test: {',
        "    include: ['test/**/*.test.ts'],",
        setup && `    globalSetup: ['${setup}'],`,
        '    // Every test file empties the same test database: they run one after another',
        '    fileParallelism: false,',
        '  },',
        '})',
        '',
      ),
    },
  ].filter((file): file is GeneratedFile => Boolean(file))
}

export function envExampleFile(context: Context): GeneratedFile {
  return {
    path: '.env.example',
    content: lines(
      '# Where the database is',
      `DATABASE_URL=${context.orm.defaultUrl(context)}`,
      context.orm.memoryTests(context)
        ? '# The tests use SQLite in memory unless this names another database (it is emptied by the tests)'
        : `# The database the tests use (it is emptied by the tests): they need one of the same kind as DATABASE_URL`,
      '# TEST_DATABASE_URL=',
      '',
    ),
  }
}

export function gitignoreFile(context: Context): GeneratedFile {
  return { path: '.gitignore', content: lines('node_modules/', 'dist/', '.env', '*.db', ...(context.orm.ignored?.(context) ?? []), '') }
}

const LABELS = {
  transactions: {
    operation: 'one transaction per service operation, committed when it ends',
    caller: 'the caller owns the transaction: nothing commits',
    repository: 'every repository write is committed at once',
  },
  paging: {
    none: 'lists return every row',
    offset: 'lists return pages by offset and limit',
    cursor: 'lists return pages after a key (cursor)',
  },
}

